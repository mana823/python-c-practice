// ============================================================
// 第6章 第1题：找出一串数中的最大非负数
// 题目：
//   Enter a number: 60
//   Enter a number: 38.3
//   Enter a number: 4.89
//   Enter a number: 100.62
//   Enter a number: 75.2295
//   Enter a number: 0
//
//   The largest number entered was 100.62
//
//   当用户输入 0 或负数时，显示已输入的最大非负数。
//   输入的数不一定是整数。
// ============================================================

// * 你的原始代码（微调：只给输出补了 \n，逻辑没动）：
#include <stdio.h>

int main(void)
{
    float i = 0, n;
    do {
        printf("Enter a number: ");
        scanf("%f", &n);

        if (n > i)
            i = n;

    } while (n > 0);     // 注意 do-while 语句分号在 while 这里

    printf("The largest number entered was %.2f\n", i);

    return 0;
}

// ============================================================
// 批改总结：
// ✅ 完全正确。
//   - do-while 先读再判断，输入 0 或负数时退出，符合题意。
//   - i 初始为 0，因为只统计非负数，0 作为初始最大值合适。
//   - 负数不会更新 i（n > i 不成立），所以 i 始终是最大非负数。
//   - 输出 %.2f，与题目示例 100.62 的两位小数一致。
//   - 变量 i 初始值 0 还顺便处理了“第一个就输入 0 或负数”的情况，
//     此时输出 0.00，符合“最大非负数”的定义。
// * 只做了微调：printf 末尾补了 \n，其余没动。
// ============================================================