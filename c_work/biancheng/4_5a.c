// ✅ 完全正确。
// * scanf 一次读 11 位，b 组是奇数位、a 组是偶数位，权重分配正确。
// * 校验位公式已改为标准 UPC 公式：3 * 奇数位和 + 偶数位和，再 9 - ((total-1)%10)。
// * 示例 01380015173 输出 5，与题目一致。
