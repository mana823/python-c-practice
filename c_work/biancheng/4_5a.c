// ============================================================
// 第4章 第5题：重写 upc.c，一次输入 11 位 UPC 数字
// 题目：
//   Enter the first 11 digits of a UPC: 01380015173
//   Check digit: 5
// ============================================================

#include <stdio.h>

int main(void)
{
    // ! 小问题：变量 n 声明了但没有使用，可以删掉。
    // * 其余 11 个变量正好对应 11 位数字，正确。
    int n, a1, a2, a3, a4, a5, b1, b2, b3, b4, b5, b6;

    printf("Enter the first 11 digits of a UPC: ");
    // * 正确：用 11 个 %1d 一次读取 11 位数字，前导 0 也能正常读入。
    // * 读入顺序与变量对应关系：
    // *   b1 = 第1位，a1 = 第2位，
    // *   b2 = 第3位，a2 = 第4位，
    // *   b3 = 第5位，a3 = 第6位，
    // *   b4 = 第7位，a4 = 第8位，
    // *   b5 = 第9位，a5 = 第10位，
    // *   b6 = 第11位。
    // * 所以：
    // *   b1~b6 是奇数位（第1、3、5、7、9、11位）；
    // *   a1~a5 是偶数位（第2、4、6、8、10位）。
    scanf("%1d%1d%1d%1d%1d%1d%1d%1d%1d%1d%1d",
          &b1, &a1, &b2, &a2, &b3, &a3, &b4, &a4, &b5, &a5, &b6);

    // * 正确：UPC 校验位公式。
    // *   total = 3 * (奇数位之和) + (偶数位之和)
    // *   check = 9 - ((total - 1) % 10)
    // *
    // * 对照本程序：
    // *   奇数位之和 = b1 + b2 + b3 + b4 + b5 + b6
    // *   偶数位之和 = a1 + a2 + a3 + a4 + a5
    // *   所以 total = 3 * (b1 + b2 + b3 + b4 + b5 + b6)
    // *                + (a1 + a2 + a3 + a4 + a5)
    // *   再算 9 - ((total - 1) % 10)。
    // *
    // * 以示例 01380015173 验证：
    // *   奇数位 b1~b6：0 + 3 + 0 + 1 + 1 + 3 = 8
    // *   偶数位 a1~a5：1 + 8 + 0 + 5 + 7 = 21
    // *   total = 3 * 8 + 21 = 45
    // *   check = 9 - ((45 - 1) % 10) = 9 - 4 = 5
    // *   输出 Check digit: 5  ✅ 与题目示例一致。
    printf("Check digit: %d",
           9 - (((b1 + b2 + b3 + b4 + b5 + b6) * 3
                 + (a1 + a2 + a3 + a4 + a5) - 1) % 10));

    // ? 可选：末尾加 \n 换行，不影响正确性。
    return 0;
}

// ============================================================
