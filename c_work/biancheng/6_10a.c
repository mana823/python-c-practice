// ============================================================
// 第6章 第10题：输入任意个日期，找出最早日期
// 题目：
//   用 0/0/0 指示输入结束，不再输入日期。
//   示例：
//   Enter a date (mm/dd/yy): 3/6/08
//   Enter a date (mm/dd/yy): 5/17/07
//   Enter a date (mm/dd/yy): 6/3/07
//   Enter a date (mm/dd/yy): 0/0/0
//   5/17/07 is the earliest date
// ============================================================

// * 你的代码（微调：只给输出补了 \n，逻辑没动）：
#include <stdio.h>

int main(void)
{
    int m, d, y, m1 = 12, d1 = 31, y1 = 99;
    do {    // <-- 只能先do因为值还不确定，不能用来判断
        printf("Enter a date (mm/dd/yy): ");
        scanf("%d/%d/%d", &m, &d, &y);

        // * 0/0/0 表示输入结束。
        if (m == 0 && d == 0 && y == 0) break;   // <-- 只能break，不然给0/0/0算进去

        // * 先比年，年相同比月，月相同比日。
        // * 只有新日期更早时才更新 m1/d1/y1。
        // * 日期完全相等时不更新，保留原值，结果不变，正确。
        if (y1 > y) y1 = y, m1 = m, d1 = d;
        else if (y1 == y) {
            if (m1 > m) y1 = y, m1 = m, d1 = d;
            else if (m1 == m) {
                if (d1 > d) y1 = y, m1 = m, d1 = d;   // <-- 等于替换也一样，就不写了
            }
        }

    } while (1);

    printf("%d/%d/%.2d is the earliest date\n", m1, d1, y1);

    return 0;
}

// ============================================================
// 批改总结：
// ✅ 完全正确。
//   - 初始值 m1=12, d1=31, y1=99 作为“最大日期”哨兵，
//     任何合法日期都比它小，保证第一次输入一定会更新。
//     之前 d1=12 的问题是 12/31/99 这种日期不会更新，
//     现在改成 31 已修正。
//   - 0/0/0 终止，正确。
//   - 先比年，年同再比月，月同再比日，正确。
//   - 日期相等时不更新，保留原值，结果不变，正确。
//   - 年份用 %.2d 输出，08、07 这类会保留前导零，符合 yy 格式。
//
// ? 可选（不是错误）：
//   1. 逗号表达式连续赋值 y1 = y, m1 = m, d1 = d;
//      从左到右执行，正确。拆成三行可读性更好，但不改也行。
//   2. 变量名 m/d/y/m1/d1/y1 可读性一般，
//      改成 month/day/year 和 earliest_* 会更直观，但本题不改也能读懂。
//   3. 如果第一次就输入 0/0/0，程序会输出 12/31/99。
//      题目没要求处理“没有任何日期”的情况，可以接受。
