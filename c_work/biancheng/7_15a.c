// ============================================================
// 第7章 第15题：计算正整数的阶乘，并观察各类型的最大 n
// 题目：
//   Enter a positive integer: 6
//   Factorial of 6: 720
//
//   (a) short       (b) int         (c) long
//   (d) long long   (e) float       (f) double
//   (g) long double
//   问：每种类型下，能正确打印 n 的阶乘的最大 n 是多少？
//   浮点类型显示的是近似值。
// ============================================================

// * 你的代码（逻辑正确，保留原样，在原处标注）：
#define __USE_MINGW_ANSI_STDIO 1    // * MinGW 下启用标准格式符，让 %Lf 正常工作。
                                    // * 这是 Windows 平台特有的宏，放在 #include 之前正确。

#include <stdio.h>

int main(void)
{
    int n;

    short a = 1;
    int b = 1;
    long c = 1;
    long long d = 1;
    float e = 1;
    double f = 1;
    long double g = 1;

    printf("Enter a positive integer: ");
    scanf("%d", &n);

    // ✅ 七个循环分别计算各类型的阶乘，逻辑正确。
    // ⚠️ 提示：可以合并成一个循环同时计算七种类型，
    //    减少重复代码。不合并也不影响正确性。
    for (int i = 1; i <= n; i++) {
        a *= i;
    }
    for (int i = 1; i <= n; i++) {
        b *= i;
    }
    for (int i = 1; i <= n; i++) {
        c *= i;
    }
    for (int i = 1; i <= n; i++) {
        d *= i;
    }
    for (int i = 1; i <= n; i++) {
        e *= i;
    }
    for (int i = 1; i <= n; i++) {
        f *= i;
    }
    for (int i = 1; i <= n; i++) {
        g *= i;
    }

    // ✅ 格式符全部正确：
    //    short       → %hd
    //    int         → %d
    //    long        → %ld
    //    long long   → %lld
    //    float       → %f
    //    double      → %lf（printf 中 %lf 与 %f 对 double 等价）
    //    long double → %Lf
    printf("Short: %hd\n", a);
    printf("Int: %d\n", b);
    printf("Long: %ld\n", c);
    printf("Long Long: %lld\n", d);
    printf("Float: %f\n", e);
    printf("Double: %lf\n", f);
    printf("Long Double: %Lf\n", g);

    return 0;
}

// ============================================================
// * 批改：
// ============================================================
// ✅ 逻辑完全正确：
//   - 七种类型各用一个变量，初始值为 1。
//   - 循环从 1 乘到 n，阶乘计算正确。
//   - 格式符与类型全部匹配，没有错配。
//   - long double 用 %Lf，正确。
//   - Windows 下加 __USE_MINGW_ANSI_STDIO 让 %Lf 生效，做法正确。
//
// ⚠️ 警告（不是错误）：
//   1. 七个循环分开写，重复代码较多。
//      可以合并成一个循环：
//        for (int i = 1; i <= n; i++) {
//            a *= i; b *= i; c *= i; d *= i;
//            e *= i; f *= i; g *= i;
//        }
//      结果完全相同，代码更短。
//   2. 题目还要求回答“每种类型下 n 的最大值”。
//      你的程序只输出阶乘值，没有直接给出最大 n。
//      需要运行后观察哪一行开始出现负数或异常值，
//      或者分别输入不同 n 做实验。
//
// ⚠️ 重要提醒：有符号整数溢出是未定义行为（UB）。
//   short、int、long、long long 溢出后，
//   程序可能输出负数、0 或任意值，不要依赖溢出后的结果。
//   浮点类型溢出会得到 inf，这是定义好的行为。
//   所以做实验时，应该找“第一次出现错误值”的前一个 n，
//   那个 n 才是该类型能正确表示的最大阶乘。
//
// ============================================================
// * 各类型能正确表示 n! 的最大 n（典型平台，供对照）：
// ============================================================
//   short（16 位有符号，最大 32767）：
//     7! = 5040，8! = 40320 > 32767
//     → n 最大为 7
//
//   int（32 位有符号，最大 2147483647）：
//     12! = 479001600，13! = 6227020800 > 2147483647
//     → n 最大为 12
//
//   long：
//     32 位平台（Windows）：同 int，n 最大为 12
//     64 位平台（Linux/macOS）：同 long long，n 最大为 20
//
//   long long（64 位有符号，最大约 9.22e18）：
//     20! = 2432902008176640000，21! ≈ 5.11e19 溢出
//     → n 最大为 20
//
//   float（约 3.4e38，7 位有效数字）：
//     34! ≈ 2.95e38，35! ≈ 1.03e40 溢出
//     → 不溢出的最大 n 为 34
//     但 float 精度有限，n 较大时结果只是近似值，
//     不保证每一位都准确。
//
//   double（约 1.8e308，15~16 位有效数字）：
//     170! ≈ 7.26e306，171! ≈ 1.24e309 溢出
//     → 不溢出的最大 n 为 170
//     同样，n 较大时结果是近似值。
//
//   long double（依实现，常见 80 位扩展精度，最大约 1.2e4932）：
//     约 1754! 接近上限，具体值因平台而异。
//     需要在你自己的机器上实验确认。
//
// * 注意：
//   以上是“不溢出”的最大 n。
//   对于浮点类型，题目说显示近似值，
//   所以即使 n 较小，结果也可能不是精确值。
//   对于整数类型，n 超过上表后就是未定义行为，
//   输出不可预测，不能当作正确结果。
