// ❌ 问题 1：printf("%ld", i); 不能用来确定溢出点。
//   循环结束时 i 恒等于 n + 1，和 i*i 什么时候溢出没有关系。
//   你的注释“我们只看执行次数”说明你把它当成了循环次数输出，
//   但题目问的是“导致失败的 n 的最小值”，
//   也就是 i*i 第一次超出 long 范围的那个 i。
//   这个值必须通过观察输出表，或者在循环里加检查才能得到，
//   看循环结束后的 i 是看不出来的。
//
// ❌ 问题 2：只写了 long 版本，没有做 int、short、long 三次对比。
//   题目明确要求分别用三种类型各跑一次，记录各自的溢出点，
//   再总结你机器上各类型的位数。
//   只跑 long 一个版本，无法完成题目的三问。
//
// ⚠️ 警告：在 64 位 Linux/macOS 上，long 通常是 64 位，
//   i*i 的溢出点约在 i = 3037000500，
//   这个 n 大到根本跑不完，实际看不到溢出。
