//   i*i 溢出点约在 i = 3037000500，实际跑不到。
//   在 32 位 Windows 上，long 是 32 位，溢出点约 46341。
// * 所以 long 版本通常只能得出“没溢出”或“溢出点极大”的结论。

// ------------------------------------------------------------
// * 结论（典型 64 位平台）：
