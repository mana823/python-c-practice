// ------------------------------------------------------------
// * 如何真正找到“导致失败的最小 n”
// ------------------------------------------------------------
// * 方法 1：人工观察输出表。
//   输入一个足够大的 n，看 i*i 第一次变成负数或明显错误值的那一行。
//   那一行的 i 就是溢出点，n 的最小值就是它。
//
// * 方法 2：在循环里加检查，自动报告第一次异常。
//   用 long long 存正确的平方值，
//   和 i*i 比较，第一次不等就报告并退出。
//   下面给的代码用这种方法，能自动找到溢出点。
//
// ------------------------------------------------------------
// * 本文件唯一可运行的 main（自动检测溢出点，先用 int 版本演示）：
// ------------------------------------------------------------

#include <stdio.h>

int main(void)
{
    int n, i;
    long long correct;   // * 用 long long 存正确平方值，避免它先溢出

    printf("This program prints a table of squares.\n");
    printf("Enter number of entries in table: ");
    scanf("%d", &n);

    for (i = 1; i <= n; i++) {
        correct = (long long)i * i;   // * 正确的平方值

        // * 如果 i*i 和正确值不一致，说明 int 已经溢出。
        // * 报告第一次溢出点，然后退出。
        if ((long long)(i * i) != correct) {      // (这里的long long 没意义，但是写不写都无所谓，就是要让他未定义再判断)
            printf("Overflow at i = %d: i*i = %d, correct = %lld\n",
                   i, i * i, correct);
            return 0;
        }

        printf("%10d%10d\n", i, i * i);
    }

    printf("No overflow up to n = %d\n", n);
    return 0;
}

// * 用 int 跑，典型结果（32 位 int）：
//   Overflow at i = 46341: i*i = -2147479015, correct = 2147488281
//   说明 int 最大约 2^31 - 1 = 2147483647，
//   i = 46341 时 i*i 第一次超出，所以 n 的最小值约为 46341。

// ------------------------------------------------------------
// * 把 i 改成 short 再跑（同样用 long long 存正确值）：
// ------------------------------------------------------------
// * 把上面代码里的 int i 改成 short i，
//   printf 的 %d 改成 %d 即可（short 会自动提升为 int 传给 printf）。
// * 典型结果（16 位 short）：
//   Overflow at i = 182: i*i = -32424, correct = 33124
//   说明 short 最大约 2^15 - 1 = 32767，
//   i = 182 时 i*i 第一次超出，所以 n 的最小值约为 182。

// ------------------------------------------------------------
