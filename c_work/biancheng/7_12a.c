// * 批改：
//
// ✅ 对于“三个操作数、两个运算符”的表达式，逻辑正确。
// ✅ 从左向右先算前两个数，再和第三个数算，符合题目“从左向右”的要求。
// ✅ scanf 格式串里 %c 前后的空格能跳过空白，带空格和不带空格的输入都能读。
//
// ❌ 错误 1：只固定处理 3 个操作数、2 个运算符，不通用。
//   题目说“表达式从左向右求值”，示例是 1+2.5*3，
//   但并没有限定只能有两个运算符。
//   输入 1+2*3-4/5 这种更长的表达式，你的程序只读到前三个数，
//   后面的 3-4/5 全被丢掉了，结果错误。
//   正确做法是用循环：读一个操作数，再读一个运算符，
//   如果是换行就结束，否则读下一个操作数并运算，继续循环。
//
// ❌ 错误 2：注释“用 float 接 char 也可以”是错的。
//   %c 要求参数是 char*，如果传 float*，是未定义行为。(可变参数传递和隐形转换不一样)
//   你代码里实际声明的是 char n2, n4，代码本身没问题，
//   但注释说“用 float 接 char 也可以”会误导人。
//   %c 只能配 char*，不能配 float*。
//
// ⚠️ 警告 1：m1 和 m2 没有初始化。
//   如果用户输入了非法运算符（题目保证不会），
//   m1 或 m2 是垃圾值，输出不可预测。
//   题目说运算符合法，可以接受；但用循环重写后这个问题自然消失。
//
// ⚠️ 警告 2：printf 输出 %.2f，而题目示例是 10.5，
//   你的程序会输出 10.50，多了一个 0。
//   题目没强制格式，不算错，但和示例不完全一致。
//   想和示例一致可以用 %g 或 %.10g。
//
// ⚠️ 警告 3：没有处理除数为 0 的情况。
//   题目没有要求，可以不管；实际工程中应检查。
