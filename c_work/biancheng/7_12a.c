// ------------------------------------------------------------
// * 修正版（本文件唯一可运行的 main）：
// * 用循环支持任意长度表达式，从左向右求值，读到换行为止。
// ------------------------------------------------------------

#include <stdio.h>

int main(void)
{
    double result, operand;
    char op;
    int ch;

    printf("Enter an expression: ");

    // * 先读第一个操作数。
    scanf("%lf", &result);

    while (1) {
        // * 跳过运算符前的空白（包括空格、制表符等）。
        while ((ch = getchar()) == ' ' || ch == '\t')
            ;

        // * 如果读到换行或 EOF，表达式结束。
        if (ch == '\n' || ch == EOF)
            break;

        op = (char)ch;

        // * 读下一个操作数。
        scanf("%lf", &operand);

        // * 根据运算符更新 result，保持从左向右求值。
        switch (op) {
            case '+': result += operand; break;
            case '-': result -= operand; break;
            case '*': result *= operand; break;
            case '/': result /= operand; break;
            default:  break;   // * 非法运算符直接忽略，题目保证不会出现。
        }
    }

    // * 用 %.2f 输出两位小数；如果希望和示例 10.5 一致，可用 %g。
    printf("Value of expression: %.2f\n", result);

    return 0;
}


