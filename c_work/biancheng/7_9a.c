// * 批改：
//
// ✅ 12 点转换逻辑正确：
//    - PM 且 n1 == 12：保持 12（中午 12 点），正确。
//    - PM 且 n1 != 12：加 12，正确。
//    - AM 且 n1 == 12：改为 0（午夜 0 点），正确。
//    - AM 且 n1 != 12：不变，正确。
//
// ✅ 输出用了 %.2d，分钟和小时都能补零，正确。
//
// ❌ 错误 1：scanf 格式串要求读取两个字符，不支持单字母输入。
//   题目允许 A、P、AM、PM，也就是可能只有一个字母。
//   你的格式串 "%d:%d %c %c" 会强制读两个字符：
//     - 输入 "9:11PM"：第一个 %c 读 'P'，第二个 %c 读 'M'，能跑。
//     - 输入 "9:11P" ：第一个 %c 读 'P'，第二个 %c 会继续等下一个字符，
//                      用户不再输入，程序就卡住了。
//   题目明确允许单字母，所以这样写不符合要求。
//   正确做法：只读一个字符，用 "%d:%d %c"。
//   AM/PM 的第一个字母已经足够区分，后面的 'M' 留在缓冲区不影响。
//
// ❌ 错误 2：没有处理小写 a/p。
//   题目说大小写均可，你只判断了 'P' 和 'A'，
//   输入 "9:11 pm" 时 i1 是 'p'，两个 if 都不成立，
//   小时不会转换，输出错误。
//   应该用 toupper 统一转成大写再判断。
//
// ⚠️ 警告 1：printf 末尾没有换行，建议加 \n。
//
// ⚠️ 警告 2：变量名 n1、n2、i1、i2 不够直观。
//   建议改成 hour、minute、period，可读性更好。
//
// ? C23 相关：toupper、scanf、printf 的规则与 C99/C11 一致，
//   本题没有 C23 特有的变化。
//
// ------------------------------------------------------------
// * 修正版（本文件唯一可运行的 main）：
// ------------------------------------------------------------

#include <stdio.h>
#include <ctype.h>

int main(void)
{
    int hour, minute;
    char period;

    printf("Enter a 12-hour time: ");

    // * 只读一个字符作为 AM/PM 标志。
    // * 格式串里的空格会跳过数值和字母之间的空白，
    // * 所以 "9:11 PM"、"9:11PM"、"9:11 P" 都能正确读取。
    // * 如果是 "9:11PM"，只会读入 'P'，'M' 留在缓冲区，不影响结果。
    scanf("%d:%d %c", &hour, &minute, &period);

    // * 统一转大写，兼容小写 a/p。
    period = toupper((unsigned char)period);

    if (period == 'P') {
        // * PM：12 点保持 12，其他加 12。
        if (hour != 12)
            hour += 12;
    } else if (period == 'A') {
        // * AM：12 点改为 0，其他不变。
        if (hour == 12)
            hour = 0;
    }

    // * 输出 24 小时制，时和分都补零到两位。
    printf("Equivalent 24-hour time: %.2d:%.2d\n", hour, minute);

    return 0;
}

// * 验证：
//   9:11 PM   → 21:11  ✅
//   9:11PM    → 21:11  ✅
//   9:11 p    → 21:11  ✅
//   12:00 PM  → 12:00  ✅
//   12:00 AM  → 00:00  ✅
//   1:05 AM   → 01:05  ✅
//   11:59 PM  → 23:59  ✅

