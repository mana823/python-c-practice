// 公式：((((3x + 2)x - 5)x - 1)x + 7)x - 6
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int x;  // * 正确：用 int 存储 x。

    printf("Please input x value: ");  // * 正确：提示输入。
    scanf("%d", &x);                   // * 正确：读取整数 x。

    // * 正确：括号完整匹配，Horner 法则展开无误。
    // * 从内向外核对：
    // *   (3 * x + 2)
    // *   ((3 * x + 2) * x - 5)
    // *   (((3 * x + 2) * x - 5) * x - 1)
    // *   ((((3 * x + 2) * x - 5) * x - 1) * x + 7)
    // *   (((((3 * x + 2) * x - 5) * x - 1) * x + 7) * x - 6)  ← 最外层乘 x 再减 6
    // * 展开后等价于：3x⁵ + 2x⁴ - 5x³ - x² + 7x - 6
    // ? 建议：可先把结果存入 int y，再 printf 输出，可读性更好，也便于调试。
    printf("The value is %d !", ((((3 * x + 2) * x - 5) * x - 1) * x + 7) * x - 6);

    return 0;  // * 正确：程序正常结束。
}

