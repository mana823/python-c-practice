// * 批改：
//
// ✅ 核心逻辑正确：
//   - 每遇到空格或制表符，sum 加 1，表示一个单词结束。
//   - 每遇到非空格字符，i 加 1，统计单词内的字符数。
//   - 读到换行或 EOF 时，sum 再加 1，表示最后一个单词结束。
//   - 最后 i / sum 得到平均词长，用 %.1f 输出一位小数。
//   - 标点符号没有被特殊处理，自动算进前一个单词，符合题目要求。
//
// ❌ 严重错误 1：sum 和 i 都没有初始化。
//   原代码：
//     float sum;
//     int i, n;
//   然后直接 sum++、i++，是在未初始化的垃圾值上累加，
//   输出结果完全不可预测。
//   必须写成：
//     float sum = 0;
//     int i = 0;
//
// ❌ 错误 2：输出单词拼写错误。
//   "Average word lenth" 少了 g，应为 "Average word length"。
//
// ⚠️ 警告 1：sum 用来数单词，用 float 不太自然。
//   单词数应该是整数，建议用 int words = 0; 最后除法时再转 float。
//   不改也能跑，但用 int 语义更清晰。
//
// ⚠️ 警告 2：输出末尾没有换行，建议加 \n。
//
// ⚠️ 警告 3：连续多个空格会被当成多个单词分隔。
//   例如 "a  b" 中间两个空格，sum 会加 2，多算一个空单词。
//   题目示例每个单词之间只有一个空格，所以不影响本题；
//   如果要求更严谨，可以只在“从非空格进入空格”时 sum++。
//   你的注释“因为算标点符号，所以最后的 '.' 就不用去减它了”理解正确。
//
// ? 你的注释“亦可以直接在 while 上判断 EOF 和换行符，只是 sum 需要处理一下”
//   ✅ 正确。可以写成：
//     while ((n = getchar()) != '\n' && n != EOF) { ... }
//     循环结束后再 sum++，效果一样。
//
// ------------------------------------------------------------
// * 修正版（本文件唯一可运行的 main）：
// * 保留你的逻辑，只修正初始化、拼写和换行。
// ------------------------------------------------------------

#include <stdio.h>

int main(void)
{
    float sum = 0;   // ! 修正：初始化为 0
    int i = 0;       // ! 修正：初始化为 0
    int n;

    printf("Enter a sentence: ");

    while (1) {
        if ((n = getchar()) == '\n' || n == EOF) {
            sum++;   // * 最后一个单词结束
            break;
        }

        if (n == ' ' || n == '\t') {
            sum++;   // * 一个单词结束
            continue;
        }

        i++;         // * 单词内的字符数
    }

    // ! 修正：lenth → length，并加 \n
    printf("Average word length: %.1f\n", i / sum);

    return 0;
}

