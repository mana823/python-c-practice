// ============================================================
// 第2章 第4题：输入美元数额，显示增加 5% 税后的金额
// 题目格式：
//   Enter an amount: 100.00
//   With tax added: $105.00
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    float n;  // * 正确：用 float 存储输入的金额。
              // ? 可选：金额用 double 精度更高，但 float 保留两位小数也够用。

    printf("Enter an amount: ");  // * 正确：提示用户输入，格式与题目一致。
    scanf("%f", &n);              // * 正确：读取 float 用 %f。
                                  // * 你的注释“这里面不能用.2f精度” ✅ 正确。
                                  // * scanf 的格式串不能指定精度，如 %.2f 是非法的。

    printf("With tax added: $%.2f", n * 1.05f);  // * 正确：输出税后金额，保留两位小数。
                                                 // * 1.05f 表示 float 类型的常量，避免不必要的 double 转换。
                                                 // * 你的注释“1.05不带f默认double” ✅ 正确。
                                                 // * 若写 1.05，则 n 会被提升为 double 计算，结果也是 double，
                                                 // * 用 %f 输出也没问题，但显式写 1.05f 更贴合 n 的类型。
                                                 // * 末尾不需要换行，题目示例没有换行，这样输出即可。

    return 0;  // * 正确：程序正常结束。
}

// ============================================================
// 批改总结：
// ✅ 完全正确：输入、计算、输出格式均符合题目要求。
// * 注释理解到位：scanf 不能用精度修饰符，浮点常量默认 double。
// * 代码简洁，逻辑清晰，没有错误需要修改。
// ============================================================