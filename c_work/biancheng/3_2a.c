// ============================================================
// 第3章 第2题：格式化产品信息
// 题目要求：
//   Enter item number: 583
//   Enter unit price: 13.5
//   Enter purchase date (mm/dd/yyyy): 10/24/2010
//
//   Item        Unit        Purchase
//               Price       Date
//   583         $  13.50    10/24/2010
//
// 说明：产品编号和日期左对齐，单位价格右对齐，美元金额最大 9999.99。
//       提示：各列使用制表符控制。
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int item, day, month, year;  // * 正确：产品编号和日期各部分用 int。
    float price;                 // * 正确：价格用 float。

    printf("Enter item number: ");  // * 正确：提示输入。
    scanf("%d", &item);             // * 正确：读取产品编号。

    printf("Enter unit price: ");   // * 正确：提示输入。
    scanf("%f", &price);            // * 正确：读取价格。
                                    // * 你的注释“scanf 不能有精度，所以保留在 printf 完成” ✅ 正确。

    printf("Enter purchase date (mm/dd/yyyy): ");  // * 正确：提示输入。
    scanf("%d/%d/%d", &month, &day, &year);        // * 正确：按 月/日/年 读取。

    printf("Item\tUnit\t\tPurchase\n");  // * 正确：表头第一行，使用制表符分列。
    printf("\tPrice\t\tDate\n");         // * 正确：表头第二行，Price 和 Date 与上行对齐。

    // ! 原始错误行：
    // ! printf("%d\t$  %.2f\t%d/%d/%d", item, price, month, day, year);
    // ! 错误点 1：价格没有右对齐。你写的是 "$  %.2f"，$ 后固定两个空格，
    // !           数字本身没有宽度控制，导致 13.50 和 5.00 的右边缘不对齐。
    // !           题目要求“单位价格采用右对齐方式”。
    // !           应改为 "$%7.2f"：$ 后接宽度为 7 的浮点数，右对齐，不足补空格。
    // !           对于 13.50，输出 "$  13.50"；对于 5.00，输出 "$   5.00"，数字右对齐。
    // ! 错误点 2：日期没有补零。题目格式是 mm/dd/yyyy，
    // !           如果输入 2/17/2011，你输出 2/17/2011，不如 02/17/2011 规范。
    // !           建议用 %02d/%02d/%04d。
    // * 正确写法：
    printf("%d\t$%7.2f\t%02d/%02d/%04d\n", item, price, month, day, year);

    // * 制表符分列效果（从第 0 列开始）：
    // *   "583" 占 0~2 列，\t 跳到第 8 列；
    // *   "$  13.50" 从第 8 列开始，占 8 列，\t 跳到第 24 列；
    // *   日期从第 24 列开始，与表头 "Purchase"/"Date" 对齐。
    // *   价格用 %7.2f 后，无论 13.50 还是 9999.99，总宽度固定为 8（$ + 7），
    // *   所以制表位稳定，右对齐也满足。

    return 0;  // * 正确：程序正常结束。
}

// ============================================================
// 批改总结：
// ✅ 输入部分完全正确，变量类型、scanf 格式、提示语都符合题目。
// ✅ 表头使用制表符分列，思路正确。
// ❌ 价格没有右对齐：应把 "$  %.2f" 改为 "$%7.2f"。
// ⚠️ 日期建议补零：用 %02d/%02d/%04d，更符合 mm/dd/yyyy 格式。
// * 其余逻辑无误。
// ============================================================

