// 题目：
//   输入 n，输出 1~n 中所有偶数的平方。
//   例如 n = 100，输出：
//       4
//      16
//      36
//      64
//     100
// ============================================================

// ! 你的原始代码（整体注释，避免与下面可运行版本冲突）：
/*
#include <stdio.h>

int main(void)
{
    int i, n = 2, m;
    scanf("%d", &i);
    do {
        m = n * n;

        n += 2;
        if (m <= i)
            printf("%5d\n", m);
        else break;

    } while (1);
    return 0;
}
*/

// * 批改：
// ✅ 核心逻辑正确。
//   n 从 2 开始，每次加 2，m = n*n；
//   m <= i 就打印，否则 break。
//   对 100 验证：
//     n=2  → m=4   ≤100 打印 4
//     n=4  → m=16  ≤100 打印 16
//     n=6  → m=36  ≤100 打印 36
//     n=8  → m=64  ≤100 打印 64
//     n=10 → m=100 ≤100 打印 100
//     n=12 → m=144 >100 break
//   输出与题目示例一致。
//
// ⚠️ 警告 1：缺少输入提示。
//   题目说“提示用户输入一个数 n”，
//   你只有 scanf，没有 printf 提示，
//   运行时光标停在那里，用户不知道要输入什么。
//   应加一行：
//     printf("Enter a number: ");
//
// ⚠️ 警告 2：变量名不直观。
//   i 是输入上限，n 是当前偶数，m 是平方值。
//   建议改成 limit、even、square，可读性更好。
//
// ⚠️ 警告 3：do { ... } while (1); + break 结构有点绕。
//   先算 m，再 n += 2，再判断打印，顺序不自然。
//   既然循环次数不确定，用 for 或 while 条件判断更直接：
//     for (n = 2; n * n <= limit; n += 2)
//         printf("%5d\n", n * n);
//   一行条件就能表达“偶数平方不超过 n”，
//   不需要 m、不需要 break、不需要 while(1)。
//
// ? 你的版本能跑对，不是错误，只是可以写得更简洁。

// ------------------------------------------------------------
// * 推荐写法（本文件唯一可运行的 main）：
// * 用 for 循环，条件直接写 n*n <= limit，结构最清晰。
// ------------------------------------------------------------

#include <stdio.h>

int main(void)
{
    int limit;
    int n;   // * 当前偶数

    printf("Enter a number: ");
    scanf("%d", &limit);

    // * n 从 2 开始，每次加 2，保证只取偶数。
    // * 循环条件 n*n <= limit，保证平方值不超过输入上限。
    // * 循环体只负责打印，不需要额外判断和 break。
    for (n = 2; n * n <= limit; n += 2) {
        printf("%5d\n", n * n);
    }

    return 0;
}

// * 验证：
//   输入 100：
//     n=2  → 4
//     n=4  → 16
//     n=6  → 36
//     n=8  → 64
//     n=10 → 100
//     n=12 → 144 > 100，循环结束
//   输出：
//       4
//      16
//      36
//      64
//     100  ✅

