// ============================================================
// 第4章 第6题：计算 EAN 校验位
// 题目：
//   Enter the first 12 digits of an EAN: 869148426000
//   Check digit: 8
//
// 规则：
//   1. 第 2、4、6、8、10、12 位相加，得到第一个和；
//   2. 第 1、3、5、7、9、11 位相加，得到第二个和；
//   3. 第一个和 * 3 + 第二个和；
//   4. 减 1；
//   5. 除以 10 取余数；
//   6. 用 9 减去余数。
// ============================================================

#include <stdio.h>

int main(void)
{
    // * 12 个变量分别存 12 位数字。
    // * 读入顺序与变量对应关系：
    // *   b1 = 第1位，a1 = 第2位，
    // *   b2 = 第3位，a2 = 第4位，
    // *   b3 = 第5位，a3 = 第6位，
    // *   b4 = 第7位，a4 = 第8位，
    // *   b5 = 第9位，a5 = 第10位，
    // *   b6 = 第11位，a6 = 第12位。
    // * 因此：
    // *   a1~a6 是第 2、4、6、8、10、12 位（偶数位）；
    // *   b1~b6 是第 1、3、5、7、9、11 位（奇数位）。
    int a1, a2, a3, a4, a5, a6;
    int b1, b2, b3, b4, b5, b6;

    printf("Enter the first 12 digits of an EAN: ");

    // * 正确：用 12 个 %1d 一次读取 12 位数字，前导 0 也能正常读入。
    // * 输入 869148426000 时：
    // *   b1=8, a1=6, b2=9, a2=1, b3=4, a3=8,
    // *   b4=4, a4=2, b5=6, a5=0, b6=0, a6=0。
    scanf("%1d%1d%1d%1d%1d%1d%1d%1d%1d%1d%1d%1d",
          &b1, &a1, &b2, &a2, &b3, &a3,
          &b4, &a4, &b5, &a5, &b6, &a6);

    // * 正确：EAN 校验位公式。
    // *   第一个和 = a1 + a2 + a3 + a4 + a5 + a6  （偶数位和）
    // *   第二个和 = b1 + b2 + b3 + b4 + b5 + b6  （奇数位和）
    // *   total    = 第一个和 * 3 + 第二个和
    // *   check    = 9 - ((total - 1) % 10)
    // *
    // * 你的表达式：
    // *   9 - ((a1 + a2 + a3 + a4 + a5 + a6) * 3
    // *        + (b1 + b2 + b3 + b4 + b5 + b6) - 1) % 10
    // *
    // * 计算顺序：
    // *   括号内先算 (a1+...+a6)*3 + (b1+...+b6) - 1，
    // *   再对整体取 % 10，
    // *   最后用 9 减。
    // * 由于 % 的优先级高于 -，这个表达式等价于：
    // *   9 - (((a1+...+a6)*3 + (b1+...+b6) - 1) % 10)
    // * 所以公式完全正确。
    // *
    // * 以 869148426000 验证：
    // *   第一个和 = 6+1+8+2+0+0 = 17
    // *   第二个和 = 8+9+4+4+6+0 = 31
    // *   total = 17 * 3 + 31 = 82
    // *   total - 1 = 81
    // *   81 % 10 = 1
    // *   9 - 1 = 8
    // *   输出 Check digit: 8  ✅ 与题目示例一致。
    printf("Check digit: %d",
           9 - ((a1 + a2 + a3 + a4 + a5 + a6) * 3
                + (b1 + b2 + b3 + b4 + b5 + b6) - 1) % 10);

    // ? 小建议：
    // ? 1. 为了可读性，可以把整个 total 用括号括起来：
    // ?    9 - (((a1 + a2 + a3 + a4 + a5 + a6) * 3
    // ?          + (b1 + b2 + b3 + b4 + b5 + b6) - 1) % 10)
    // ?    效果完全一样，但一眼能看出先取余再被 9 减。
    // ? 2. 输出末尾可加 \n 换行，不影响正确性。
    // ? 3. 变量名 a/b 与“奇偶位”的对应关系容易混淆，
    // ?    可改成 even1...even6、odd1...odd6，更直观。

    return 0;
}

// ============================================================
// 批改总结：
// ✅ 完全正确。
// * scanf 一次读 12 位，a 组对应偶数位、b 组对应奇数位，权重分配正确。
// * 校验位公式与题目规则完全一致，示例 869148426000 输出 8。
// * 括号和 % 的优先级处理正确。
// ? 可选改进：外层加一对括号提高可读性；输出末尾加 \n；
// ?           变量名可改为 even/odd 系列，更直观。
// ============================================================