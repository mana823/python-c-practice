// 第6章 第12题：持续累加，直到当前项小于 n
// 题目：
//   修改编程题11，使得程序持续执行加法运算，
//   直到当前项小于 n 为止，其中 n 是用户输入的较小的浮点数。
// ============================================================

// * 你的代码（微调：补了提示语的冒号和输出换行，逻辑保留）：
#include <stdio.h>

int main(void)
{
    double a, sum;
    int i;
    float n;

    printf("Input n: ");   // * 微调：补了冒号和空格，提示更清楚
    scanf("%f", &n);

    for (i = 1, sum = 1, a = 1.0; ; i++) {
        a = a / i;         // * 当前项 = 1/i!
        sum += a;          // * 先累加当前项
        if (a < n) break;  // * 再判断：当前项小于 n 就停
    }

    printf("e ~= %lf\n", sum);  // * 微调：补了 \n

    return 0;
}

// ============================================================
// 批改总结：
// ✅ 递推关系正确：a = a / i，每轮得到 1/i!。
// ✅ sum 初始为 1，对应公式开头的 1。
// ✅ 循环能正常终止：a 会越来越小，最终小于 n。
//
// ⚠️ 一个需要和教材对一下的细节：终止条件的位置。
//   你的顺序是：
//     a = a / i;
//     sum += a;
//     if (a < n) break;
//   也就是说：先把小于 n 的那一项加进 sum，然后才停。
//
//   题目“直到当前项小于 n 为止”有两种理解：
//   1. 加上这一项后，发现它小于 n，于是停止 —— 你的写法符合这种理解。
//   2. 当前项一旦小于 n 就不再加，直接停止 —— 这种理解下，
//      应先判断，再决定加不加：
//        a = a / i;
//        if (a < n) break;
//        sum += a;
//
//   两种写法只差最后那一项。建议对照教材参考答案，
//   通常教材采用“先判断，再累加”的写法。
//   如果你的老师按“加上后判断”讲，那你现在的顺序就是对的。
//
