// ============================================================
// 第6章 第11题：用无穷级数近似计算 e
// 题目：
//   e = 1 + 1/1! + 1/2! + 1/3! + ...
//   用户输入 n，计算：
//   1 + 1/1! + 1/2! + ... + 1/n!
// ============================================================

// * 你的代码（微调：只给输出补了 \n，逻辑没动）：
#include <stdio.h>

int main(void)
{
    int n, i, m, a;
    float sum, b;

    printf("Input n: ");
    scanf("%d", &n);

    // * 初始化：
    // *   sum = 1 对应公式开头的 1；
    // *   a = 1 用来累积阶乘；
    // *   m = 1 是下一轮要乘的数。
    // * 循环 i 从 1 到 n：
    // *   第 1 轮 a = 1*1 = 1!，加 1/1!；
    // *   第 2 轮 a = 1!*2 = 2!，加 1/2!；
    // *   第 3 轮 a = 2!*3 = 3!，加 1/3!；
    // *   依次类推，逻辑正确。
    for (i = 1, m = 1, a = 1, sum = 1; i <= n; i++) {
        a = a * m;          // * 累积阶乘
        b = 1.0f / a;       // * 当前项 1/i!
        sum += b;           // * 累加到 sum
        m++;                // * 下一轮乘的数
    }

    // * 微调：末尾加 \n，输出更整洁。
    printf("e ~= %f\n", sum);

    return 0;
}

// ============================================================
// 批改总结：
// ✅ 完全正确。
//   - 初始化 sum = 1 对应公式开头的 1，正确。
//   - a 累积阶乘：第 1 轮 1!，第 2 轮 2!，……，第 n 轮 n!，正确。
//   - 每轮加 1.0f / a，正确。
//   - 循环 n 次，加完 1/n!，正确。
//   - 以 n=1 验证：sum = 1 + 1/1! = 2，正确。
//   - 以 n=2 验证：sum = 1 + 1 + 1/2 = 2.5，正确。
//
// ⚠️ 警告（不是错误）：a 是 int，n 较大时阶乘会溢出。
//   13! = 6227020800，已经超过 int 范围（通常 2^31-1）。
//   如果用户输入 n >= 13，a 溢出，结果会错。
//   题目没有明确 n 的范围，小 n 下你的代码完全正确。
//   若想更稳健，可以把 a 改成 float 或 double：
//     double a;
