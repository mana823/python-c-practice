#include <stdio.h>

int main(void)
{
    int ch;

    printf("Enter phone number: ");

    // * 逐字符读，直到换行。
    // * 每个字符先判断是不是大写字母：
    // *   是 → 输出对应数字字符
    // *   不是 → 原样输出
    while ((ch = getchar()) != '\n') {
        switch (ch) {
            case 'A': case 'B': case 'C':
                putchar('2'); break;
            case 'D': case 'E': case 'F':
                putchar('3'); break;
            case 'G': case 'H': case 'I':
                putchar('4'); break;
            case 'J': case 'K': case 'L':
                putchar('5'); break;
            case 'M': case 'N': case 'O':
                putchar('6'); break;
            case 'P': case 'Q': case 'R': case 'S':
                putchar('7'); break;
            case 'T': case 'U': case 'V':
                putchar('8'); break;
            case 'W': case 'X': case 'Y': case 'Z':
                putchar('9'); break;
            default:
                putchar(ch); break;   // * 非字母字符原样输出
        }
    }

    putchar('\n');
    return 0;
}

