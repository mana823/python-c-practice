// ============================================================
// 第6章 第3题：把分数约分为最简分式
// 题目：
//   Enter a fraction: 6/12
//   In lowest terms: 1/2
//
//   提示：先求分子和分母的最大公约数，
//         然后分子和分母都除以最大公约数。
// ============================================================

// * 你的代码（微调：只给 printf 补了 \n，逻辑没动）：
#include <stdio.h>

int main(void)
{
    int m, n, a, b, c;
    printf("Enter a fraction: ");
    scanf("%d/%d", &m, &n);
    b = m, c = n;          // * 保存原始分子和分母
    while (n != 0) {       // * Euclid 算法求 GCD
        a = m % n, m = n, n = a;
    }
    printf("In lowest terms: %d/%d\n", b / m, c / m);  // * 分子分母同除 GCD
    return 0;
}

// ============================================================
// 批改总结：
// ✅ 完全正确。
//   - 先用 b、c 保存原始分子分母，
//     因为 Euclid 循环会修改 m、n，不保存就没法约分了。
//   - Euclid 算法实现无误，循环结束后 m 就是 GCD。
//   - 输出 b/m 和 c/m，正好是约分后的分子和分母。
//   - 以 6/12 验证：GCD(6,12)=6，6/6=1，12/6=2，输出 1/2，正确。
// * 只做了微调：printf 末尾补了 \n，其余没动。
// ============================================================