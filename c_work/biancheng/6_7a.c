// 题目：
//   重新安排程序 square3.c，在 for 循环中对变量 i 进行初始化、判定
//   以及自增操作。不需要重写程序，特别是不要使用任何乘法。
// ============================================================

// * 你的代码：
#include <stdio.h>

int main(void)
{
    int n, odd = 3, square = 1;
    printf("This program prints a table of squares.\n");
    printf("Enter number of entries in table: ");
    scanf("%d", &n);

    // * i 的初始化、判定、自增都在 for 头部，符合题目要求。
    // * square 只在外部声明并初始化，for 里不再重复声明，没有遮蔽问题。
    // * square 和 odd 通过加法递推，完全没有使用乘法，符合题目要求。
    // * 更新表达式顺序：++i, square += odd, odd += 2。
    // * i 不参与 square、odd 的计算，所以这三个更新的先后顺序不影响结果。
    // * 第一轮：打印 i=1, square=1；更新 i=2, square=4, odd=5。
    // * 第二轮：打印 i=2, square=4；更新 i=3, square=9, odd=7。
    // * 第三轮：打印 i=3, square=9；……依次得到平方数。
    for (int i = 1; i <= n; ++i, square += odd, odd += 2) {
        printf("%10d%10d\n", i, square);
    }
    return 0;
}

// ============================================================
// 批改总结：
// ✅ 完全正确。
//   - i 的初始化、判定、自增都在 for 头部，符合题目要求。
//   - square 在外部声明并初始化为 1，for 里不再重复声明，
//     没有变量遮蔽，外层 square 也真正被使用了。
//   - square 和 odd 通过加法递推，没有使用任何乘法。
//   - 更新表达式中 ++i、square += odd、odd += 2 的先后顺序
//     不影响结果，因为 i 不参与 square、odd 的计算。
//   - 以 n=3 验证：
//       1         1
//       2         4
//       3         9
//     输出正确。
//
// ? 补充：for 初始化里声明 int i 是 C99 写法。
//    如果编译器只支持 C89，可以把 i 移到外面声明：
//      int i, n, odd = 3, square = 1;
