// ============================================================
// 第4章 第1题：两位数逆序输出
// 题目：
//   Enter a two-digit number: 28
//   The reversal is: 82
// 提示：n % 10 是个位数，n / 10 是移除个位后剩下的数。
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{   int a;          // * 正确：用 int 存储输入的两位数。
                    // ? 小建议：变量名 a 可以改得更明确，如 n，与题目提示一致。
                    // ? 风格建议：{ 后换行、缩进统一，可读性更好。

    printf("Enter a two-digit number: ");  // * 正确：提示语与题目示例一致。
    scanf("%d", &a);                       // * 正确：读取整数。

    // * 正确：逆序输出。
    // *   a % 10 得到个位数；
    // *   a / 10 得到十位数；
    // *   用两个 %d 连续输出，先个位后十位，就是逆序。
    // * 例：a = 28 → 8 和 2 → 输出 82。
    // * 例：a = 20 → 0 和 2 → 输出 02，仍然保留前导 0，符合“两位数逆序”的格式。
    // * 例：a = 10 → 0 和 1 → 输出 01，也正确。
    printf("The reversal is: %d%d", a % 10, a / 10);

    // ! 小问题：缺少 return 0;
    // * C99 起 main 函数末尾可省略 return 0，编译器会隐式返回 0；
    // * 但显式写出更规范，建议补上：
    return 0;
}

// ============================================================
// 批改总结：
// ✅ 核心逻辑完全正确：a % 10 取个位，a / 10 取十位，先输出个位再输出十位。
// ✅ 对 20、10 这类个位为 0 的两位数，%d%d 也能正确输出 02、01，不需要额外补零。
// ! 唯一小问题：缺少 return 0;，建议补上。
// ? 可选改进：变量名 a 改为 n；大括号和缩进排版更规范。
// ============================================================