// * 批改：
//
// ✅ 迭代公式正确：n = (x / y + y) / 2，符合牛顿方法。
// ✅ 变量类型正确：double x、y、m、n，精度足够。
// ✅ 包含了 <math.h>，正确使用了 fabs。
// ✅ 输出格式 %.5lf，与题目示例 1.73205 一致。
// ✅ m 初始为 1，保证第一次一定进入循环，n 会被赋值，不会未初始化。
//
// ❌ 错误：终止条件不符合题目要求。
//   题目要求：|新 y - 旧 y| < 0.00001 * 新 y 时终止。
//   你的条件：fabs(m) < 0.00001 时终止，少了“乘以新 y”。
//
//   正确循环条件应为：
//     while (fabs(m) >= 0.00001 * n)
//   或等价地：
//     while (fabs(m) >= 0.00001 * fabs(n))
//
//   影响：
//   - 当 x 较大时，新 y 也较大，0.00001 * n 比 0.00001 大得多，
//     你的条件会更严格，多迭代很多次，结果仍然正确，但效率低。
//   - 当 x 较小时，新 y 小于 1，0.00001 * n 比 0.00001 小，
//     你的条件可能过早停止，精度不够。
//   所以虽然示例 x=3 能输出正确结果，但条件不符合题目要求。
//
// ⚠️ 警告 1：变量名 m、n 不够直观。
//   建议改成 diff（差值）和 new_y（新猜测值），可读性更好。
//
// ⚠️ 警告 2：printf 末尾没有换行，建议加 \n。
//
// ? 补充：
//   1. 你写 `m = y - n` 是旧值减新值，题目只要求绝对值，
//      正负无所谓，fabs 会处理。
//   2. 用 `n` 作为最终输出值也可以，循环结束时 n 就是最后一次计算的新 y。
//      但更稳妥的写法是输出 `y`，因为循环里 y = n 后，y 才是当前猜测值。
//      两者数值相同，不影响结果。
//
// ------------------------------------------------------------
// * 修正版（本文件唯一可运行的 main）：
// ------------------------------------------------------------

#include <stdio.h>
#include <math.h>

int main(void)
{
    double x;
    double y = 1.0;       // * 当前猜测值
    double new_y;         // * 新猜测值
    double diff = 1.0;    // * 新旧猜测值之差

    printf("Enter a positive number: ");
    scanf("%lf", &x);

    // * 终止条件：|新 y - 旧 y| < 0.00001 * 新 y
    // * 即 fabs(diff) >= 0.00001 * new_y 时继续迭代。
    while (fabs(diff) >= 0.00001 * new_y) {
        new_y = (x / y + y) / 2;
        diff = y - new_y;   // * 旧值减新值，绝对值即可
        y = new_y;
    }

    // * 输出保留 5 位小数，与题目示例一致。
    printf("Square root: %.5f\n", new_y);

    return 0;
}

// * 验证（x = 3）：
//   y=1      → new_y=2,      diff=-1,      y=2
//   y=2      → new_y=1.75,   diff=0.25,    y=1.75
//   y=1.75   → new_y=1.73214,diff=0.01786, y=1.73214
//   y=1.73214→ new_y=1.73205,diff≈0.00009, y=1.73205
//   y=1.73205→ new_y=1.73205,diff≈0,       y=1.73205
//   当 |diff| < 0.00001 * new_y ≈ 0.00001732 时停止，
//   输出 1.73205  ✅

