// * 批改：❌ 逻辑有多处错误，需要重写。
//
// ❌ 错误 1：变量 n1~n5 没有初始化。
//    如果只输入两位数 12，n3、n4、n5 都是未初始化的垃圾值，
//    输出会变成“垃圾值垃圾值垃圾值21”，完全不对。
//
// ❌ 错误 2：每位数字的提取逻辑错了。
//    以 a = 12 为例：
//      第 1 次：i = 12，a = 1；
//              a < 10 成立，n2 = i % 10 = 12 % 10 = 2；
//      第 2 次：i = 1，a = 0；
//              a != 0 不成立，跳过；
//              循环结束。
//      n1 = i = 1。
//    输出 n5 n4 n3 n2 n1 → 垃圾 垃圾 垃圾 2 1，
//    期望的 21 根本没拼出来。
//
// ❌ 错误 3：最多只能处理 5 位数。
//    题目要求“一位、两位、三位或更多位”，
//    用 n1~n5 定死 5 个变量，输入 6 位数就崩了。
//
// ❌ 错误 4：每位数字打印时没有保留前导零。
//    比如输入 100，逆序应为 001；
//    如果先拼成一个整数再 printf("%d")，前导 0 会丢掉，
//    只输出 1，不符合“逆序显示”的语义。
//
// ? 正确思路：
//   不需要提前把每位存进单独变量。
//   用 do-while 每次取 n % 10 打印出来，然后 n /= 10。
//   先打印个位，再打印十位、百位……
//   打印顺序天然就是逆序。
//   而且用 %d 逐位打印，前导零也能保留。
//
// ------------------------------------------------------------
// * 正确写法（本文件唯一可运行的 main）：

#include <stdio.h>

int main(void)
{
    int n;

    printf("Enter a number: ");
    scanf("%d", &n);

    printf("The reversal is: ");

    // * do-while：至少执行一次，先取个位打印，再除以 10。
    // * 每次打印的都是当前最低位，打印顺序天然就是逆序。
    // * 用 %d 逐位打印，前导零也能保留。
    // * 例如：
    // *   28  → 先 8，再 2，输出 82
    // *   100 → 先 0，再 0，再 1，输出 001
    // *   7   → 先 7，n 变 0，退出，输出 7
    do {
        printf("%d", n % 10);   // * 打印当前最低位
        n /= 10;                // * 去掉最低位
    } while (n != 0);

    printf("\n");
    return 0;
}

// * 验证：
//   输入 28   → 8, 2           → 82     ✅
//   输入 100  → 0, 0, 1        → 001    ✅
//   输入 7    → 7              → 7      ✅
//   输入 12345→ 5,4,3,2,1      → 54321  ✅
//   输入 1234567 → 7654321               ✅ 任意位数都行

