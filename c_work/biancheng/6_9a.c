// * 批改：
// ✅ 循环公式正确：
//   m = m * (1 + month_rate) - PYTMENT;
//   每月余额 = 上月余额 + 上月余额 × 月利率 - 月还款，
//   等价于 上月余额 × (1 + 月利率) - 月还款，正确。
// ✅ month_rate = RATE / 100.0 / 12.0; 正确：
//   年利率百分数 → 小数 → 月利率。
// ✅ 输出保留两位小数，正确。
//
// ⚠️ 警告 1：贷款金额、年利率、月还款额被 #define 写死了。
//   本题是“修改第2章第8题”，原题要求用户输入这三个值。
//   你只让用户输入还贷次数 n，其他三个值固定成宏，
//   不符合“修改原程序”的要求。
//   应改成用 scanf 读取 loan、rate、payment。
//
// ⚠️ 警告 2：提示语 "Input numbers: " 太模糊。
//   用户不知道要输入什么。应明确提示输入还贷次数，
//   以及贷款金额、利率、月还款额。
//
// ⚠️ 警告 1：循环变量 i 用了 float。
//   循环计数通常用 int，float 做循环变量容易有精度问题。
//   建议改成 int i。
//
// ⚠️ 警告 2：变量名 m、i、n 不够直观。
//   建议改成 balance、month、payments 之类，可读性更好。
//   本题保留 m、n 也能跑对，不是错误。
//
// ------------------------------------------------------------
// * 正确写法（本文件唯一可运行的 main）：
//   保留原第2章第8题的三个输入，再增加还贷次数输入。
// ------------------------------------------------------------

#include <stdio.h>

int main(void)
{
    double loan;        // * 贷款金额
    double rate;        // * 年利率，例如输入 6.0 表示 6%
    double payment;     // * 每月还款额
    double monthly_rate;// * 月利率
    double balance;     // * 当前余额
    int payments;       // * 还贷次数
    int i;              // * 循环计数

    // * 读取贷款金额、年利率、月还款额。
    printf("Enter amount of loan: ");
    scanf("%lf", &loan);

    printf("Enter interest rate: ");
    scanf("%lf", &rate);

    printf("Enter monthly payment: ");
    scanf("%lf", &payment);

    // * 读取还贷次数。
    printf("Enter number of payments: ");
    scanf("%d", &payments);

    // * 年利率百分数转月利率：
    // * 例如 6.0 → 6.0 / 100 / 12 = 0.005
    monthly_rate = rate / 100.0 / 12.0;

    // * 从贷款金额开始，每次还贷后更新余额并输出。
    balance = loan;
    for (i = 1; i <= payments; i++) {
        balance = balance * (1 + monthly_rate) - payment;  // <-- 像这种自己叠加计算赋值，可以给自己搞成变量
        printf("Balance remaining after payment %d: $%.2f\n", i, balance);
    }

    return 0;
}

// * 验证（输入 20000、6.0、386.66、3）：
//   月利率 = 6.0 / 100 / 12 = 0.005
