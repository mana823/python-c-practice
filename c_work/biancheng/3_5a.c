// ============================================================
// 第3章 第5题：4×4 幻方
// 题目：输入 1~16 任意次序，按 4×4 矩阵显示，并计算行、列、对角线和。
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int a, b, c, d, e, f, g, h, i, j, k, l, m, n, o, p;
    // * 正确：用 16 个 int 变量存储 16 个数，符合题目要求。
    // ? 可选：用 int a[16] 数组会更简洁，但本题练习 printf/scanf，用变量完全可以。

    // ! 小瑕疵：提示语中 "1 to  16" 多了一个空格。
    // * 题目示例是 "1 to 16"，建议改为：
    printf("Enter the numbers from 1 to 16 in any order:\n");
    // * 正确：scanf 连续 16 个 %d，中间不需要空格，%d 会自动跳过空白字符。
    scanf("%d%d%d%d%d%d%d%d%d%d%d%d%d%d%d%d",
          &a, &b, &c, &d, &e, &f, &g, &h,
          &i, &j, &k, &l, &m, &n, &o, &p);

    // * 正确：矩阵输出格式设计得很好，列宽控制与题目示例一致。
    // * 第一列用 %-2d 左对齐宽度 2，后三列分别用 %2d、%3d、%3d，保证各列对齐。
    // * 以示例输入验证，输出与题目完全一致。
    printf("%-2d%2d%3d%3d\n", a, b, c, d);
    printf("%-2d%2d%3d%3d\n", e, f, g, h);
    printf("%-2d%2d%3d%3d\n", i, j, k, l);
    printf("%-2d%2d%3d%3d\n", m, n, o, p);

    // * 正确：行和计算。
    printf("Row sums: %d %d %d %d\n",
           a + b + c + d,
           e + f + g + h,
           i + j + k + l,
           m + n + o + p);

    // * 正确：列和计算。
    printf("Column sums: %d %d %d %d\n",
           a + e + i + m,
           b + f + j + n,
           c + g + k + o,
           d + h + l + p);

    // * 正确：两条对角线和。
    // *   主对角线：a + f + k + p
    // *   副对角线：d + g + j + m
    printf("Diagonal sums: %d %d", a + f + k + p, d + g + j + m);

    return 0;  // * 正确：程序正常结束。
}

