// ============================================================
// 第3章 第1题：日期格式转换
// 题目：输入 mm/dd/yyyy，输出 yyyymmdd
// 示例：
//   Enter a date (mm/dd/yyyy): 2/17/2011
//   You entered the date 20110217
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int day, month, year;  // * 正确：用 int 存储日、月、年。

    printf("Enter a date (mm/dd/yyyy): ");  // * 正确：提示输入，格式与题目一致。
    scanf("%d/%d/%d", &month, &day, &year); // * 正确：按 月/日/年 读取，
                                            // * 格式串中的 '/' 会精确匹配输入中的 '/'。

    // ! 原始错误行：
    // ! printf("You entered the date %d%d%d", year, month, day);
    // ! 错误点：直接使用 %d 输出，月份和日期不足两位时不会补零。
    // ! 例如输入 2/17/2011，会输出 2011217，而不是题目要求的 20110217。
    // * 正确写法：年份用 %04d，月份和日期用 %02d，保证补零到固定宽度。
    printf("You entered the date %04d%02d%02d\n", year, month, day);

    // * 各项说明：
    // *   %04d → 年份至少 4 位，不足前面补 0。
    // *   %02d → 月份至少 2 位，不足前面补 0。
    // *   %02d → 日期至少 2 位，不足前面补 0。
    // *   末尾加 \n 换行，与题目示例一致。

    return 0;  // * 正确：程序正常结束。
}

// ============================================================
// 批改总结：
// ✅ 输入、变量顺序、scanf 格式都正确。
// ❌ 输出格式错误：%d%d%d 不会补零，导致 20110217 变成 2011217。
// * 修正：printf("You entered the date %04d%02d%02d\n", year, month, day);
// ============================================================