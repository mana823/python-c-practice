// ============================================================
// 第6章 第2题：用 Euclid 算法求最大公约数
// 题目：
//   Enter two integers: 12 28
//   Greatest common divisor: 4
//
//   提示：Euclid 算法
//   如果 n 为 0，停止，m 中的值是 GCD；
//   否则计算 m 除以 n 的余数，把 n 保存到 m 中，
//   并把余数保存到 n 中，重复上述过程。
// ============================================================

// * 你的代码（微调：只给 printf 补了 \n，逻辑没动）：
#include <stdio.h>

int main(void)
{
    int m, n, a;
    printf("Enter two integers: ");
    scanf("%d%d", &m, &n);
    while (n != 0) {
        a = m % n, m = n, n = a;
    }
    printf("Greatest common divisor: %d\n", m);
    return 0;
}

// ============================================================
// 批改总结：
// ✅ 完全正确。
//   - Euclid 算法实现无误：先算余数 a，再 m = n，再 n = a。
//   - 逗号表达式从左到右执行，a 先保存旧余数，
//     所以后面 m = n 不会影响 a，n = a 用的是正确余数。
//   - 循环条件 n != 0，n 为 0 时退出，m 就是 GCD。
//   - 以 12 和 28 验证：28%12=4，12%4=0，GCD=4，正确。
// * 只做了微调：printf 末尾补了 \n，其余没动。
// ============================================================