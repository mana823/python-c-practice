// 题目：
//   修改 6.3 节的程序 square2.c，每 24 次平方运算后暂停，
//   并显示：
//     Press Enter to continue...
//   显示完消息后，程序应该使用 getchar 读入一个字符。
//   getchar 读到用户输入的回车键才允许程序继续。
// ============================================================

// ! 你的原始代码（整体注释，避免与下面可运行版本冲突）：
/*
#include <stdio.h>

int main(void)
{
    long long i;
    unsigned int a;
    do {
    for (i = 1; i <= 24; i++) {
        printf("%10lld%10lld\n", i, i * i);
    }
    printf("Press Enter to continue...");
    a = getchar();

    } while (a == 10);
    return 0;
}
*/

// * 批改：
// ❌ 错误 1：没有读入 n。
//   square2.c 原程序会先让用户输入表格条目数 n，
//   然后打印 1~n 的平方。
//   你的代码完全没有读 n，直接固定打印 1~24。
//
// ❌ 错误 2：内层 for 每次都从 1 开始，导致每轮重复打印 1~24。
//   暂停后按回车，又打印一遍 1~24，而不是继续 25~48、49~72……
//   正确的逻辑是：i 从 1 递增到 n，每打印一个平方，
//   检查是否满 24 个，满了就暂停，按回车后继续下一个 i。
//
// ❌ 错误 3：外层 do-while 的条件 a == 10 方向反了。
//   按回车 a 就是 10，条件成立会继续循环，
//   但如果用户输入的不是回车，循环就退出了。
//   而题目要求是“读到回车才继续”，
//   所以应该用 while (getchar() != '\n'); 把非回车字符都吃掉，
//   直到读到回车才往下走。
//
// ⚠️ 警告 1：a 用 unsigned int 存 getchar 的返回值。
//   getchar 返回 int，因为要能返回 EOF（通常是 -1）。
//   用 unsigned int 存，EOF 会变成很大的正数，判断会出错。
//   应改为 int a; 或 int ch;。
//
// ⚠️ 警告 2：printf("Press Enter to continue..."); 末尾没有换行。
//   题目示例消息就是这一行，不加 \n 也可以，
//   但通常按完回车后光标会换行，加不加看个人风格。
//
// ? 正确思路：
//   1. 读入 n。
//   2. for (i = 1; i <= n; i++) 打印平方。
//   3. 每打印一个，检查 i % 24 == 0 且 i != n，
//      如果是，打印提示，然后用 getchar 循环读到回车为止。
//   4. 继续下一个 i。
//
// ------------------------------------------------------------
// * 本文件唯一可运行的 main：
// ------------------------------------------------------------

#include <stdio.h>

int main(void)
{
    // * 1. 采纳你的建议，改为无符号类型，杜绝负数表项
    unsigned long long i, n;
    int ch;

    printf("This program prints a table of squares.\n");
    printf("Enter number of entries in table: ");
    
    // * 2. 检查 scanf 返回值，防止垃圾输入
    if (scanf("%llu", &n) != 1) {
        printf("输入非法！\n");
        return 1;
    }

    // * 3. 清理缓冲区，必须加上 ch != EOF，防止文件输入导致死循环
    while ((ch = getchar()) != '\n' && ch != EOF)
        ;

    for (i = 1; i <= n; i++) {
        // 如果 i 的平方超过了 unsigned long long 的极限（几乎不可能），先拦截
        printf("%10llu%20llu\n", i, i * i);

        // * 每 24 行暂停一次，最后一行不暂停
        if (i % 24 == 0 && i != n) {
            printf("Press Enter to continue...");

            // * 同样必须加上 EOF 判断
            while ((ch = getchar()) != '\n' && ch != EOF)
                ;
        }
    }

    return 0;
}

// * 验证（输入 n = 50）：
//   打印 1~24 的平方；
//   第 24 行后显示 Press Enter to continue...，
//   按回车后继续；
//   打印 25~48 的平方；
//   第 48 行后再次暂停；
//   按回车后打印 49~50 的平方；
//   因为 i = 50 == n，不再暂停，程序结束。

// ============================================================
// 批改总结：
// ❌ 没有读入 n，固定打印 1~24。
// ❌ 内层 for 每次从 1 开始，暂停后重复打印 1~24，
//    而不是继续 25~48。
// ❌ do-while 条件 a == 10 方向反了，
//    应改成 while (getchar() != '\n'); 读到回车才继续。
// ⚠️ getchar 返回值应存 int，不要用 unsigned int。
// ✅ 正确做法：
//    读入 n，for 从 1 到 n 打印平方，
//    每 i % 24 == 0 且 i != n 时暂停，
//    用 while (getchar() != '\n'); 等回车。
//    另外 scanf 后要先把残留的回车吃掉，
//    否则第一次暂停会被直接跳过。
// ============================================================