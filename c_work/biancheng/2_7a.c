// ============================================================
// 第2章 第7题：最少张数钞票付款
// 题目：输入美元数额，用最少张数的 20、10、5、1 美元钞票付款。
// 要求：始终使用整数，不要用浮点数。
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int num, _20, _10, _5, _1;  // * 正确：全部用 int，符合题目要求。
                                // ? 变量名以 _ 开头，语法合法，但风格上建议避免。
                                // ? 可改为 bills20, bills10, bills5, bills1，更清晰。

    printf("Enter a dollar amount: ");  // * 正确：提示输入。
    scanf("%d", &num);                  // * 正确：读取整数金额。

    _20 = num / 20;                     // * 正确：计算 20 美元钞票张数。
    _10 = (num - 20 * _20) / 10;        // * 正确：减去 20 美元总额后，再算 10 美元张数。
    _5  = (num - 20 * _20 - _10 * 10) / 5;  // * 正确：继续扣除，算 5 美元张数。
    _1  = (num - 20 * _20 - _10 * 10 - _5 * 5) / 1;  // * 正确：剩余全为 1 美元。
                                                     // ? 除以 1 可以省略，直接写剩余值也行。

    printf("$20 bills: %d\n", _20);  // * 正确：输出 20 美元张数。
    printf("$10 bills: %d\n", _10);  // * 正确：输出 10 美元张数。
    printf("$5 bills: %d\n", _5);    // * 正确：输出 5 美元张数。
    printf("$1 bills: %d", _1);      // * 正确：输出 1 美元张数。
                                     // * 末尾没有 \n，题目示例也没要求，没问题。

    return 0;  // * 正确：程序正常结束。
}

// ============================================================
// 批改总结：
// ✅ 完全正确。整数运算、最少张数逻辑、输出格式均符合题目要求。
// * 以 93 为例：_20=4，_10=1，_5=0，_1=3，输出与题目示例一致。
// ? 唯一小建议：变量名 _20 等虽然合法，但可读性一般，改为 bills20 等更好。
// ============================================================