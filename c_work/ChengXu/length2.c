// 第7章：计算消息长度（紧凑版 getchar 循环）
// ============================================================

// * 你的代码（微调：只把 character(S) 改成 character(s)，其余保留）：
#include <stdio.h>

int main(void)
{
    int len = 0;

    printf("Enter a message: ");

    // * 你的注释“判断表达式照样停留读取，getchar() 本来就会返回值，
    //   每次循环都被调用” ✅ 正确。
    // * 执行顺序：
    //   1. 调用 getchar() 读一个字符；
    //   2. 判断它是否等于 '\n'；
    //   3. 不等于就执行 len++，然后回到第 1 步再读下一个；
    //   4. 等于 '\n' 就退出循环，换行符本身不计入 len。
    // * “先判断再加”这个说法从“循环体”角度看是对的：
    //   每轮都是先完成判断，判断通过才 len++。
    while (getchar() != '\n')
        len++;

    // * 微调：character(S) → character(s)，题目示例是小写 s。
    printf("Your message was %d character(s) long.\n", len);

    return 0;
}

// ============================================================
// 批改总结：
// ✅ 完全正确，而且是 getchar 循环的标准紧凑写法。
//   - 不需要循环外先 getchar 一次，直接把读取放进条件里。
//   - 每次循环调用一次 getchar，读一个字符、判断、计数，
//     每个非换行字符恰好计一次。
//   - 遇到换行符退出，换行符不计入长度，符合题目要求。
//
// ✅ 你的理解正确：
//   getchar() 在条件表达式里也会“停留等待输入”，
//   它不是只在赋值语句里才读，而是每次被调用就读一个字符。
//
// ⚠️ 警告（不是错误）：printf 里 character(S) 的 S 是大写，
//   题目示例是 character(s)，已改成小写。
//   不影响运行，只是输出与题目示例更一致。
//
// ? 补充：len 用 int 没问题。
//   这种写法比“循环外先读一次”的版本更简洁，
//   也是大多数 C 程序员实际会用的形式。
// ============================================================