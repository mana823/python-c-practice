// 第5章：计算股票经纪人的佣金
// 题目：
//   当股票通过经纪人进行买卖时，经纪人的佣金往往根据股票交易额
//   采用某种变化的比例进行计算。表 5-4 显示了实际支付给经纪人的费用金额。
//
//   交易额范围                 佣金
//   低于 2500 美元             30 美元 + 1.7%
//   2500 ~ 6250 美元           56 美元 + 0.66%
//   6250 ~ 20000 美元          76 美元 + 0.34%
//   20000 ~ 50000 美元         100 美元 + 0.22%
//   50000 ~ 500000 美元        155 美元 + 0.11%
//   超过 500000 美元           255 美元 + 0.09%
//
//   最低收费是 39 美元。
//   示例：
//   Enter value of trade: 30000
//   Commission: $166.00
//
//   该程序的重点是用级联式 if 语句来确定交易额所在的数值范围。
// ============================================================

/* 计算经纪人的佣金 */
#include <stdio.h>

int main(void)
{
    float commission, value;

    // * 你的注释：
    // * “scanf 函数先接受，再想办法转换（前提是字节数要对应），无事发生，
    // *  只要地址与格式转换符对应就行；printf 除了 %f 和 %lf 其他的你就给我对应，
    // *  不然就强行解释了。”
    // ✅ 正确。
    // * scanf 运行时只看“格式符 + 地址”，不认变量声明类型。
    // * 格式符按自己的规则解析输入，并把对应类型的字节写到地址里。
    // * 所以 int 的地址被 %f 写入后，内存里就是 float 的位模式；
    // * 之后用 %d 读，就会把这个位模式当整数解释。
    // * 字节数对应是前提；类型不匹配在标准层面是未定义行为，
    // * 但在运行时机制上，就是“格式符按自己的图纸强行解释内存”。
    // ? 补充：printf 中 %f 和 %lf 等价（float 被默认提升为 double）；
    // ?       但 scanf 中 %f 用于 float，%lf 用于 double，二者不等价。

    printf("Enter value of trade: ");
    scanf("%f", &value);

    if (value < 2500.00f)
        commission = 30.00f + .017f * value;   // * 正确：30 美元 + 1.7%
                                                // * .017f 即 1.7%

    else if (value < 6250.00f)
        // * 你的注释：多个 else if 相当于逐级排查，
        // * 跨层级对应的 if-else 相当于两大板块的分割。✅ 正确。
        commission = 56.00f + .0066f * value;  // * 正确：56 美元 + 0.66%

    else if (value < 20000.00f)
        // * 你的注释：else if 相当于先把前面的排除（else），
        // * 再从后面的可能做判断（if）。✅ 正确。
        commission = 76.00f + .0034f * value;  // * 正确：76 美元 + 0.34%

    else if (value < 50000.00f)
        commission = 100.00f + .0022f * value; // * 正确：100 美元 + 0.22%

    else if (value < 500000.00f)
        commission = 155.00f + .0011f * value; // * 正确：155 美元 + 0.11%

    else
        // * 你的注释：最后直接 else 取反例，不用条件。✅ 正确。
        commission = 255.00f + .0009f * value; // * 正确：255 美元 + 0.09%

    // * 你的注释：这个 if 不是上一个 else 的子句，是独立的一个句子，
    // * 因为上一个 else 已经结束了。✅ 正确。
    // * 这个 if 与前面的级联 if-else 完全独立，用于兜底最低佣金。
    if (commission < 39.00f)
        commission = 39.00f;    // * 正确：最低收费 39 美元。

    printf("Commission: $%.2f\n", commission);  // * 正确：保留两位小数输出。
    return 0;
}

