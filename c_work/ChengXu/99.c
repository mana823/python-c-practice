#include <stdio.h>

int main(void) {
    // 外层循环控制行数，从 1 到 9
    for (int i = 1; i <= 9; i++) {

        // 【核心魔法 1：打印前置空格实现缩进】
        // 第 1 行需要 8 个缩进单位，第 9 行需要 0 个缩进单位
        // 每个缩进单位打印 4 个空格，正好是每项宽度 8 的一半，
        // 所以每一行都左右对称地扩展，整体呈居中的金字塔。
        for (int space = 1; space <= 9 - i; space++) {
            printf("    "); // 打印 4 个空格
        }

        // 【核心魔法 2：打印乘法公式】
        // %-2d 保证结果占 2 位左对齐，后面的两个空格是公式之间的间隔。
        // 每项固定宽度 8：数字1 + '*' + 数字1 + '=' + 2位结果 + 2个空格。
        for (int j = 1; j <= i; j++) {
            printf("%d*%d=%-2d  ", j, i, j * i);
        }

        // 换行！
        printf("\n");
    }
    return 0;
}

// ============================================================
// * 居中原理（为什么缩进 4 刚好）
// ============================================================
// * 每项固定宽度 = 8。
// * 第 i 行缩进 = (9 - i) * 4，也就是每少一项，缩进少 4。
// * 4 正好是 8 的一半。
//
// * 第 i 行：
//     左边缘 = (9 - i) * 4 = 36 - 4i
//     右边缘 = 左边缘 + i * 8 = 36 - 4i + 8i = 36 + 4i
//     中点   = (左边缘 + 右边缘) / 2 = 36
//
// * 每一行的中点都固定在第 36 列，
//   所以第 1 行只有 1 项偏右，第 9 行 9 项铺满，
//   中间每一行左右对称扩展，整体就是居中的倒金字塔。
//
// * 如果缩进不是 4 而是 8（每项宽度的一半变成整宽），
//   那就变成右对齐，而不是居中了。

// ============================================================
