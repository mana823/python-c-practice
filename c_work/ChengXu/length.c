// ============================================================
// 第7章：计算消息长度（getchar 逐字符读取）
// 题目：
//   Enter a message: Brevity is the soul of wit.
//   Your message was 27 character(s) long.
//
//   长度包括空格和标点，不包括结尾的换行符。
//   循环遇到换行符立刻终止。
// ============================================================

// * 你的代码（逻辑正确，保留原样，只在原处标注）：
#include <stdio.h>

int main(void)
{
    char ch;
    int len = 0;

    printf("Enter a message: ");
    ch = getchar();    // * 先读第一个字符，让 while 有东西可判断。
                       // * 你的注释“也会造成 scanf 一样的停留，同样可以用 printf 做提示词”
                       // ✅ 正确：getchar 也会等待输入，printf 提示是必要的。

    while (ch != '\n') {
        len++;         // * 当前字符不是换行符，计数加 1。
        ch = getchar();// * 读下一个字符，供下一轮判断。
                       // * 你的注释“因为缓冲区的缘故，一个个拿，
                       //   外面的主要还是为了判断，里面的循环次数要与计数对应”
                       // ✅ 基本正确：循环外先读一次是为了初始化判断条件，
                       //    循环内每次读下一个字符，保证每个字符只计一次数。
    }

    printf("Your message was %d character(s) long.\n", len);

    return 0;
}

// ============================================================
// 批改总结：
// ✅ 逻辑完全正确。
//   - 先读第一个字符，while 判断不是换行才进入循环。
//   - 循环内先 len++，再读下一个字符，每个非换行字符计一次。
//   - 遇到换行符退出，换行符本身不计入长度。
//   - 空格和标点都会被正常计数，符合题目要求。
//
// ⚠️ 警告（不是错误）：ch 声明为 char。
//   getchar() 的返回值是 int，因为要能返回 EOF（通常是 -1）。
//   用 char 存储，普通字符没问题，但如果输入结束或出错，
//   char 可能无法正确表示 EOF。
//   本题只读到换行符为止，不涉及 EOF，所以 char 能正常工作。
//   更严谨的写法是把 ch 声明为 int：
//     int ch;
//   这样 getchar 的所有返回值都能正确保存。
//
// ? 补充：这个循环可以写得更紧凑，不需要循环外先读一次：
//     while ((ch = getchar()) != '\n')
//         len++;
//   先把 getchar 的返回值赋给 ch，再判断是否等于换行符，
//   不等于就 len++，然后进入下一轮再读。
//   效果和你现在的写法完全一样，但少了一次循环外的 getchar。
//   你现在的写法更直观地展示了“先读、再判断、再读”的过程，
//   作为学习 getchar 的示例完全没问题。
// ============================================================