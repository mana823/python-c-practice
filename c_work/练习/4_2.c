// ------------------------------------------------------------

// * 你的原答：
// 10.答(a): 12 12   (b): 3 4   (c): 2 8   (d): 6 9

// * 批改：✅ 全部正确（第(d)在常见实现下正确，但有未定义行为风险，见补充）。

// (a) i = 6;
//     j = i += i;
//     赋值右结合：i += i → i = 6 + 6 = 12，表达式值为 12；
//     j = 12。
//     输出：12 12  ✅

// (b) i = 5;
//     j = (i -= 2) + 1;
//     i -= 2 → i = 5 - 2 = 3，表达式值为 3；
//     j = 3 + 1 = 4。
//     输出：3 4  ✅

// (c) i = 7;
//     j = 6 + (i = 2.5);
// ! 关键点：i 是 int，2.5 是 double。
// * 赋值时 2.5 会向零截断为 2，i = 2；
// * 赋值表达式的值是赋值后 i 的值，即 int 类型的 2；
// * j = 6 + 2 = 8。
//     输出：2 8  ✅
// ? 补充：把 double 赋给 int 会发生类型转换，小数部分被截断，不是四舍五入。

// (d) i = 2; j = 8;
//     j = (i = 6) + (j = 3);
// * 右侧两个赋值表达式分别把 i 改为 6、j 改为 3；
// * 加法结果 6 + 3 = 9，再赋给 j，最终 j = 9，i = 6。
//     输出：6 9  ✅
// ! 重要补充：这个表达式在 C 标准中属于未定义行为（undefined behavior）。
// ! 原因：j 在同一个表达式中被修改了两次（(j = 3) 和最外层 j = ...），
// !       且两次修改之间没有序列点。
// ! 所以严格来说，不同编译器可能给出不同结果，甚至可能崩溃。
// ? 本题按常见编译器（GCC/Clang）的实际结果，输出 6 9，你的答案符合教材预期。
