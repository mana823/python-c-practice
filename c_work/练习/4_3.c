// ------------------------------------------------------------
// * 第13题：++i 和 i++ 中，哪一个与 (i += 1) 完全相同？
// ------------------------------------------------------------

// * 你的原答：
// 13.答: ++i，都产生了副作用+1

// * 批改：✅ 结论正确。
// * 完整理由：
//   - ++i：先让 i 加 1，整个表达式的值是加 1 后的新值。
//   - i++：先取 i 的旧值作为表达式的值，然后 i 再加 1。
//   - i += 1：先让 i 加 1，整个表达式的值也是加 1 后的新值。
// * 所以 ++i 与 (i += 1) 的值和副作用都相同，完全相同；
//   i++ 虽然也让 i 加 1，但表达式的值是旧值，不完全相同。
// * 你的“都产生了副作用 +1”说得没错，
//   但题目问的是“与 (i += 1) 完全相同”，还要比较表达式的值，
//   这一点决定了答案是 ++i 而不是 i++。

