// ============================================================
// 2.2节 第2题
// 题目：思考下面的程序：
// (a) 请指出程序中的指令和语句。
// (b) 程序的输出是什么？
// ============================================================

#include <stdio.h>  // * 预处理指令。指令通常以 # 开头。
int main(void)      // * 主函数定义。函数定义本身不是语句。
{                   // * 复合语句/块开始。
    printf("Parkinson's Law:\nWork expands so as to ");  // * 语句
    printf("fill the time\n");                           // * 语句
    printf("available for its completion.\n");           // * 语句
    return 0;                                            // * 语句
}                   // * 复合语句/块结束。

// ============================================================
// 你的原答：
// (a) #include <stdio.h>是指令，main里面的代码是指令。
// (b) 输出：
//     Parkinson's Law:
//     Work expands so as to fill the time
//     available for its completion.
// ============================================================

// ! 批改：
// (a) 部分错误：
//   ✅ #include <stdio.h> 是指令（更准确：预处理指令）。
//   ❌ “main里面的代码是指令”错。main 里面的 printf(...); 和 return 0; 是“语句”。
//   ? 指令通常是预处理指令，以 # 开头；语句是执行单位。
// (b) ✅ 正确。输出内容完全正确。注意实际输出行首无缩进。

// ============================================================
// (a) 正确答案：
// 指令（预处理指令）：#include <stdio.h>
// 语句：三个 printf 调用 + return 0;
// 注意：main 函数体整体是复合语句/块；函数定义本身不是语句。
// ============================================================

// ============================================================
// (b) 正确答案：
// Parkinson's Law:
// Work expands so as to fill the time
// available for its completion.
// ============================================================

// ============================================================
// 额外补充：
// 1. 题目“预处理器会首先对其进行编译”不严谨，预处理器不编译，只处理 # 指令。
// 2. \n 是转义字符，表示换行。
// 3. 第一个 printf 末尾有空格，所以 to 和 fill 之间只有一个空格。
// ============================================================