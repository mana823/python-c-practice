// ============================================================
// 4.5节 第15题：表达式语句执行后 i 和 j 的值
// 题目：假设 i 初始值为 1，j 初始值为 2。
// (a) i += j;
// (b) i--;
// (c) i * j / i;
// (d) i % ++j;
// ============================================================

// * 你的原答：
// (a) i = 3, j = 2
// (b) i = 0, j = 2
// (c) 不变
// (d) i = 1, j = 3

// ------------------------------------------------------------
// * 逐项批改
// ------------------------------------------------------------

// (a) i += j;
// * 初始：i = 1, j = 2
// * i += j 等价于 i = i + j = 1 + 2 = 3。
// * j 没有被修改，仍为 2。
// ✅ 你的答案正确：i = 3, j = 2

// (b) i--;
// * 初始：i = 1, j = 2
// * i-- 是后自减：表达式的值是旧值 1，然后 i 减 1，变成 0。
// * j 不变，仍为 2。
// ✅ 你的答案正确：i = 0, j = 2
// ? 补充：i-- 表达式的值是 1，但语句执行后变量 i 是 0。

// (c) i * j / i;
// * 初始：i = 1, j = 2
// * 这是一个纯表达式语句，只计算 i * j / i，结果被丢弃。
// * 其中没有赋值、自增、自减等副作用，所以 i 和 j 都不会改变。
// ✅ 你的“不变”正确。
// * 更明确地写：i = 1, j = 2
// ? 补充：虽然表达式里出现了 i 和 j，但读取它们不会改变它们的值。

// (d) i % ++j;
// * 初始：i = 1, j = 2
// * ++j 是前自增：j 先变成 3，表达式的值也是 3。
// * 然后计算 i % 3 = 1 % 3 = 1，结果被丢弃。
// * i 没有被修改，仍为 1；j 被 ++j 修改为 3。
// ✅ 你的答案正确：i = 1, j = 3
// ? 补充：这里唯一改变变量的是 ++j 的副作用。

// ------------------------------------------------------------
// * 第15题正确答案汇总：
// (a) i = 3, j = 2
// (b) i = 0, j = 2
// (c) i = 1, j = 2   （不变）
// (d) i = 1, j = 3
// ------------------------------------------------------------

// ============================================================
// 批改总结：
// (a) ✅ 正确
// (b) ✅ 正确
// (c) ✅ 正确，建议明确写出 i = 1, j = 2
// (d) ✅ 正确
// * 本题全对。核心是分清“表达式计算”和“副作用”：
// *   只有赋值、自增、自减等才会改变变量；
// *   纯算术表达式语句不会改变变量值。
// ============================================================