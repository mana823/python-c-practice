/*2.4.1 类型*/
// >> 每一个变量都有一个类型(type)。类型用来说明变量所存储的数据的种类。C语言拥有广泛多样的类型。但是现在，我们将只限定在两种范围内:int类型和float类型。
// ! 类型会影响变量的存储方式以及允许对变量进行的操作，所以选择合适的类型是非常关键的。
// >> 数值型变量的类型决定了变量所能存储的最大值和最小值，同时也决定了是否允许在小数点后出现数字。

// ? int(integer的简写)型变量可以存储整数，如0、1、392、或-2553。但是，整数的取值范围(7.1节)有限制。最大通常是2147483647,某些计算机可能是32767.
// ? float(floating-point的简写)型变量可以存储比int型变量大很多的数值。可存储带小数位的数，如2.1。   
// ! float计算比int慢，更重要的是其所存储的数值往往只是实际数值的近似值。如存储0.1，可能变量值为0.09999999999999987，这是舍入造成的误差。

