// 7.1节 第1题：给出下列整型常量的十进制值
// 题目：
//   (a) 077
//   (b) 0x77
//   (c) 0XABC
// ============================================================

// * 你的原答：
// 答: (a) 63   (b) 109   (c) 2748

// * 批改：
// (a) ✅ 正确。077 以 0 开头，是八进制。
//     077 = 7 * 8 + 7 = 56 + 7 = 63
//
// (b) ❌ 错误。0x77 以 0x 开头，是十六进制，不是十进制。
//     0x77 = 7 * 16 + 7 = 112 + 7 = 119
//     你写 109，可能是把 0x77 当成别的进制或算错了。
//     正确答案：119
//
// (c) ✅ 正确。0XABC 是十六进制，0X 大小写都行。
//     0xABC = 10 * 16^2 + 11 * 16 + 12
//           = 10 * 256 + 176 + 12
//           = 2560 + 176 + 12
//           = 2748

// * 正确答案汇总：
// (a) 63
// (b) 119
// (c) 2748

// * 补充规则：
// 1. 以 0 开头、后面是 0~7 的数字 → 八进制。
//    例如 077、012、0100。
// 2. 以 0x 或 0X 开头 → 十六进制。
//    例如 0x77、0XABC、0xff。
// 3. 十进制没有前缀，例如 77、123。
// 4. 十六进制中 A~F 分别表示 10~15，大小写都可以。

// ============================================================
