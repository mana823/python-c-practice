// * 第14题：
// frac_part = f - (int) f; 是否总能正确计算 f 的小数部分？
// ------------------------------------------------------------
// * 你的原答：
// 14.答: 不一定，如果float型的值大于int的极限，还要转换，
// 那么高位会被直接砍掉(由实现定义)，导致无法准确计算小数部分，
// 会有整数多余，不过小数部分还是可以看出来的。

// * 批改：⚠️ 结论“不一定”正确，但原因表述有误。
// ! 错误点：你说“由实现定义”，不对。
// ! 浮点数转整数时，如果值无法用目标整数类型表示，
// ! C 标准规定这是未定义行为（undefined behavior），
// ! 不是实现定义（implementation-defined）。
// ! 实现定义是“标准允许实现自己决定，但必须文档化”，
// ! 未定义行为是“标准不保证任何事情，程序可能崩溃、可能得到任意值”。
//
// * 正确解释：
//   1. 如果 f 的绝对值超出 int 能表示的范围，
//      (int) f 是未定义行为，结果不可预测。
//   2. 即使 f 在 int 范围内，如果 f 很大，
//      float 本身的精度也可能不足以表示小数部分，
//      这时 frac_part 会丢失精度。
//   3. 对负数，f - (int) f 得到的是负的小数部分，
//      例如 -3.7 → -3.7 - (-3) = -0.7。
//      如果希望得到 0.7，需要额外处理符号。
//
// * 正确答案：
//   不一定总能正确。
//   主要原因：
//   - f 超出 int 范围时，(int) f 是未定义行为；
//   - f 很大时，float 精度不足，小数部分可能丢失；
//   - 对负数，结果是负的小数部分，不是绝对值。

// ============================================================
// * 你的笔记批改：
// “存的时候（赋值大转小）：是按图纸砍高位
//  （由实现定义，通常不会崩，但可能变成负数或极小的值）。”
// ------------------------------------------------------------
// * 需要区分两种情况：
//   1. 整数赋给较小的整数类型（如 long → int）：
//      如果值无法表示，结果是实现定义（implementation-defined）
//      或抛出实现定义的信号。
//      你说“由实现定义”在这一种情况下是对的。
//   2. 浮点数赋给整数类型（如 double → int）：
//      如果值无法表示，是未定义行为（undefined behavior）。
//      第14题的 (int) f 属于这一种，不是实现定义。
//
// * 你的后半句：
// “算的时候（算术溢出）：是彻底放飞自我
//  （未定义行为，程序可能随时暴毙或被删防御代码）。”
