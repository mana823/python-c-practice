// * 第5题题目：
// 下列 C 语言标识符中，哪些是不合法的？
// (a) 100_bottles
// (b) _100_bottles
// (c) one__hundred__bottles
// (d) bottles_by_the_hundred
// ------------------------------------------------------------

// * 你的原答：
// (5)答: 不合法的有: (a)

// ! 批改：✅ 正确。
// * 补充规则：
// *   C 语言标识符只能由字母、数字、下划线组成，且不能以数字开头。
// *   (a) 100_bottles 以数字 1 开头，不合法。
// *   (b) _100_bottles 以下划线开头，合法。
// *   (c) one__hundred__bottles 由字母和下划线组成，合法（虽然多个连续下划线不推荐，但语法合法）。
// *   (d) bottles_by_the_hundred 合法。
// * 所以不合法只有 (a)。

