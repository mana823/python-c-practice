// * 第6题题目：
// 为什么说在标识符中使用多个相邻的下划线（如 current__balance）不太合适？
// ------------------------------------------------------------

// * 你的原答：
// (6)答: 容易看错？

// ! 批改：❌ 不完整，只答对了一小部分。
// * 主要原因：
// *   1. C 标准保留了一些包含双下划线的标识符给实现（编译器等）使用。
// *      具体来说，包含两个连续下划线的标识符，以及以下划线后跟大写字母开头的标识符，
// *      都是保留给实现使用的。用户程序使用它们可能导致与库或编译器内部名称冲突。
// *   2. 多个连续下划线容易与单个下划线混淆，降低可读性。
// * 所以“容易看错”只是次要原因，核心是“保留给实现，可能冲突”。

// * 正确答案：
// *   使用多个相邻下划线（如 current__balance）不太合适，是因为 C 标准将包含双下划线的
// *   标识符保留给实现使用，用户程序使用可能引起命名冲突；同时也会降低代码可读性。

