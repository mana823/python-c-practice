// 3.1节 第1题：printf 输出结果
// 题目：下面的 printf 函数调用产生的输出分别是什么？
// (a) printf("%6d, %4d", 86, 1040);
// (b) printf("%12.5e", 30.253);
// (c) printf("%.4f", 83.162);
// (d) printf("%-6.2g", .0000009979);
// ============================================================

// * 你的原答：
// (1)答: (a): ····86, 1040   (b): ·0.30253e+02   (c): 83.1620    (d): 99e-8
// * 你的补充注释：
// 指数在printf函数默认带正负号，指数至少为两位，不齐前面面补零。%g当指数小于-4或大于等于精度p用%e，不大不小用%f,且%g的精度p是保留有效数字
// 【printf 浮点输出核心法则】
// 1. %e：指数部分默认带正负号（如 e+05），且指数至少占 2 位，不足则前面补零。
// 2. %g：设精度为 p（默认为6）。若指数 < -4 或 指数 >= p，则用 %e；否则用 %f。
// 3. %g 的精度 p：代表的是“总共保留的有效数字”（而非小数点后的位数）(不管是%d还是%e都是这样)，且输出时会自动去掉尾随的零和多余的小数点。如没有6位有效数字，则不会补0

// ------------------------------------------------------------
// * 逐项批改
// ------------------------------------------------------------

// (a) printf("%6d, %4d", 86, 1040);
// * 你的答案：····86, 1040
// ✅ 正确。
// * %6d：宽度 6，右对齐，86 占 2 位，前面补 4 个空格。
// * %4d：宽度 4，右对齐，1040 正好 4 位，不补空格。
// * 输出就是：    86, 1040
// * 用 · 表示空格：····86, 1040

// (b) printf("%12.5e", 30.253);
// ! 你的答案：·0.30253e+02
// ❌ 错误。
// * 错误点：%e 要求小数点前只有 1 位非零数字，不能写成 0.30253e+02。
// * 正确计算：
//   30.253 = 3.0253 × 10¹
//   %.5e 表示小数点后保留 5 位：
//   3.02530e+01
// * 字符串 "3.02530e+01" 长度为 11：
//   3 . 0 2 5 3 0 e + 0 1  → 11 个字符
// * %12.5e 宽度 12，右对齐，前面补 1 个空格。
// * 正确答案：·3.02530e+01

// (c) printf("%.4f", 83.162);
// * 你的答案：83.1620
// ✅ 正确。
// * %.4f 表示小数点后保留 4 位，83.162 补 0 后为 83.1620。

// (d) printf("%-6.2g", .0000009979);
// ! 你的答案：99e-8
// ❌ 错误。
// * 错误点：没有按 %g 的精度 2 位有效数字计算，也没有处理进位和去掉尾随零。
// * 正确计算：
//   0.0000009979 = 9.979 × 10⁻⁷
//   %.2g 表示保留 2 位有效数字：
//   9.979 → 第三位 7 ≥ 5，第二位 9 进位，变成 10 → 1.0 × 10⁻⁶
//   %g 会去掉尾随零，所以科学计数形式为：1e-06
// * %-6.2g：宽度 6，左对齐。
//   字符串 "1e-06" 长度为 5，左对齐后补 1 个空格。
// * 正确答案：1e-06·   （即 "1e-06" 后面一个空格）

// ------------------------------------------------------------
// * 第1题正确答案汇总
// ------------------------------------------------------------
// (a)     86, 1040
// (b)  3.02530e+01
// (c) 83.1620
// (d) 1e-06·      （末尾一个空格，表示左对齐宽度 6）

// * 你的补充注释基本正确：
// ✅ %e 指数默认带正负号，指数至少两位，不足补零。
// ✅ %g 在指数 < -4 或 指数 >= 精度 p 时用 %e，否则用 %f。
// ✅ %g 的精度 p 表示有效数字，并且会去掉尾随零和多余小数点。
// ? 补充：%g 的精度 p 默认为 6；当 p 为 0 时按 1 处理。
// ? 补充：本题 (d) 的精度是 2，不是默认 6，所以只保留 2 位有效数字。

