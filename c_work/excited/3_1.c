// 3.1节 第2题：编写 printf 调用
// 题目：编写 printf 函数调用，以下列格式显示 float 型变量 x。
// (a) 指数表示形式，栏宽 8，左对齐，小数点后保留 1 位数字。
// (b) 指数表示形式，栏宽 10，右对齐，小数点后保留 6 位数字。
// (c) 定点十进制表示形式，栏宽 8，左对齐，小数点后保留 3 位数字。
// (d) 定点十进制表示形式，栏宽 6，右对齐，小数点后无数字。
// ============================================================

// * 你的原答：
// (2)答: (a): printf("%-8.1e", x);  (b): printf("%10.6e", x);   (c): printf("%-8.3", x);   (d): printf("%6d", x)

// ------------------------------------------------------------
// * 逐项批改
// ------------------------------------------------------------

// (a) 指数表示形式，栏宽 8，左对齐，小数点后保留 1 位数字。
// * 你的答案：printf("%-8.1e", x);
// ✅ 正确。
// * %e 是指数表示形式；
// * - 表示左对齐；
// * 8 是栏宽；
// * .1 是小数点后 1 位。

// (b) 指数表示形式，栏宽 10，右对齐，小数点后保留 6 位数字。
// * 你的答案：printf("%10.6e", x);
// ✅ 正确。
// * 右对齐是默认，不用加 -；
// * 10 是栏宽；
// * .6e 表示小数点后 6 位。

// (c) 定点十进制表示形式，栏宽 8，左对齐，小数点后保留 3 位数字。
// ! 你的答案：printf("%-8.3", x);
// ❌ 错误。
// * 错误点：缺少转换字符 f。%-8.3 不是完整的格式说明符，没有说明输出类型。
// * 正确：printf("%-8.3f", x);
// * %f 表示定点十进制表示形式；
// * -8 左对齐宽度 8；
// * .3 小数点后 3 位。

// (d) 定点十进制表示形式，栏宽 6，右对齐，小数点后无数字。
// ! 你的答案：printf("%6d", x);
// ❌ 错误。
// * 错误点 1：%d 用于输出 int，不能输出 float。用 %d 输出 float 是未定义行为。
// * 错误点 2：定点十进制表示形式应该用 %f。
// * 正确：printf("%6.0f", x);
// * %6.0f：宽度 6，右对齐，小数点后 0 位。
// * 也可以写成 printf("%6.0f", x); 或 printf("%6.f", x);，但 %6.0f 更清晰。

// ------------------------------------------------------------
// * 第2题正确答案汇总
// ------------------------------------------------------------
// (a) printf("%-8.1e", x);   ✅
// (b) printf("%10.6e", x);   ✅
// (c) printf("%-8.3f", x);   ❌ 原答缺 f
// (d) printf("%6.0f", x);    ❌ 原答用了 %d，应改为 %f 系列

// * 最终批改总结：
// 第1题：(a) ✅  (b) ❌  (c) ✅  (d) ❌
// 第2题：(a) ✅  (b) ✅  (c) ❌  (d) ❌
// * 主要问题：
//   1. %e 科学计数法小数点前必须一位非零数字。
//   2. %g 要按有效数字精度计算，注意进位和去掉尾随零。
//   3. 定点输出必须用 %f，不能用 %d，也不能漏掉 f。
