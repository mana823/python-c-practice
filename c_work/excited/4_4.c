// ------------------------------------------------------------
// * 题目：
// 添加圆括号，说明 C 语言编译器如何解释下列表达式。
// (a) a * b - c * d + e
// (b) a / b % c / d
// (c) - a - b + c - + d
// (d) a * - b / c - d
// ------------------------------------------------------------

// * 你的原答：
// 答(a): 先算 a*b 和 c*d，之后先 - 再 +
//   (b): 一个个往后算
//   (c): 给 -a 和 +d 看成整体，然后一个个往后算
//   (d): 先算 a * -b 之后 /c，最后 -d

// ------------------------------------------------------------
// * 批改与正确答案
// ------------------------------------------------------------

// * 关键规则：
// *   1. 一元 +、- 优先级高于 * / %，高于 + -。
// *   2. * / % 同级，左结合。
// *   3. + - 同级，左结合。
// *   4. 括号用来显式表示结合顺序。

// (a) a * b - c * d + e
// * 你的描述：先算 a*b 和 c*d，之后先 - 再 +。✅ 方向正确。
// * 正确加括号：
//     ((a * b) - (c * d)) + e
// * 说明：
//     * 先算 a*b 和 c*d；
//     * 再算减法 (a*b) - (c*d)；
//     * 最后算加法 + e。
// * 表达式等价于：(((a * b) - (c * d)) + e)

// (b) a / b % c / d
// * 你的描述：一个个往后算。⚠️ 太模糊。
// * 正确加括号：
//     ((a / b) % c) / d
// * 说明：
//     / 和 % 同级，左结合；
//     先算 a/b，再算 (a/b)%c，最后再除以 d。
// * 表达式等价于：(((a / b) % c) / d)

// (c) - a - b + c - + d
// * 你的描述：给 -a 和 +d 看成整体，然后一个个往后算。✅ 方向正确。
// * 注意：这里的 +d 是一元正号，不是加法。
// * 正确加括号：
//     (((-a) - b) + c) - (+d)
// * 说明：
//     一元 -、+ 优先：先得到 (-a) 和 (+d)；
//     然后 +、- 同级左结合：
//     先 (-a) - b，再 + c，最后 - (+d)。
// * 表达式等价于：((((-a) - b) + c) - (+d))

// (d) a * - b / c - d
// * 你的描述：先算 a * -b 之后 /c，最后 -d。✅ 方向正确。
// * 正确加括号：
//     ((a * (-b)) / c) - d
// * 说明：
//     一元 - 优先：先得到 (-b)；
//     * 和 / 同级左结合：先 a * (-b)，再 / c；
//     最后减 d。
// * 表达式等价于：(((a * (-b)) / c) - d)

// ------------------------------------------------------------
// * 第14题正确答案汇总：
// (a) ((a * b) - (c * d)) + e
// (b) ((a / b) % c) / d
// (c) (((-a) - b) + c) - (+d)
// (d) ((a * (-b)) / c) - d
// ------------------------------------------------------------

// ============================================================
// 批改总结：
// (a) ✅ 描述方向正确，补上括号即可。
// (b) ⚠️ “一个个往后算”太笼统，应明确 / 和 % 同级左结合。
// (c) ✅ 方向正确，注意 +d 是一元正号，应写成 (+d)。
// (d) ✅ 方向正确，补全括号即可。
// * 核心：一元运算符优先，* / % 同级左结合，+ - 同级左结合。
// ============================================================