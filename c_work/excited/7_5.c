/* ============================================================================
 * 【极客复盘：%zu 格式符与 size_t 的跨平台物理尺寸博弈】
 * ============================================================================
 * 
 * 1. 逻辑本质：
 *    - %zu 是 C99 专门为打印 size_t 类型发明的格式符。
 *    - z：长度修饰符，代表当前平台的 size_t 尺寸。
 *    - u：无符号十进制输出（unsigned）。
 *    - 对应地，打印十六进制用 %zx，八进制用 %zo。
 * 
 * 2. 底层行为（为什么必须用 z）：
 *    - size_t 是由编译器决定的“无符号整型”，专门用来表示内存字节数或数组下标。
 *    - 在 32 位系统上，size_t 是 4 字节（32位）。
 *    - 在 64 位系统上，size_t 是 8 字节（64位）。
 *    - 如果强行用 %u（默认认4字节），在64位系统上打印一个8字节的 size_t，
 *      会导致 printf 只读了低32位，高位被忽略，引发参数尺寸错位。
 * 
 * 3. 工程/安全铁律：
 *    - 凡是用 sizeof() 算出来的结果，或者 strlen() 返回的长度，必须用 %zu 打印。
 *    - 在进行内存分配（malloc）、数据拷贝（memcpy）计算长度时，长度变量
 *      必须声明为 size_t，且打印时格式符必须匹配。
 * 
 * 4. 坑与反例：
 *    - 错误代码：printf("%d", sizeof(int)); 
 *      - 后果：不仅类型有符号/无符号不匹配，一旦遇到大尺寸，直接导致栈上参数解析错位，
 *        后续的 %s、%n 等格式符全盘崩溃（格式化字符串漏洞的温床）。
 *    - 错误代码：size_t len = 0xFFFFFFFF; printf("%u", len);
 *      - 后果：在 64 位下，%u 只读 4 字节，如果是负数或大数截断，输出结果完全错乱。
 * 
 * 5. [安防微架构备注]：
 *    - 格式符的尺寸不匹配是【信息泄露（Info Leak）】的高发区。
 *    - 黑客可以故意构造超长数据，让你的 printf 用错尺寸，将内存里原本不该打印的
 *      敏感数据（如指针地址、密码残渣）当成整数打印出来，直接绕过 ASLR 防御。
 * ============================================================================
 */