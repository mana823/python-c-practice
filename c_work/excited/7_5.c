// * 批改：
// ❌ 错误：类型选错了。
//   short 通常是 16 位，不是 8 位；
//   int 通常是 32 位，不是 16 位；
//   long long 至少 64 位，不是 32 位。
//   你写的三个 typedef 全部对不上题目要求的位宽。
//
//
// ⚠️ 警告：没有输出，也没有用 sizeof 验证位宽。
//   题目只要求“创建类型”，不强制输出，
//   但加几行 sizeof 打印，能直接看出每个类型到底几位，
//   也方便验证你的机器上是否满足 8/16/32 位。
//
// ------------------------------------------------------------
// * 正确思路（C23 标准下最推荐）：
//   用 <stdint.h> 里的精确宽度整数类型：
//     int8_t、int16_t、int32_t
//   只要实现提供了这些类型，它们就正好是 8/16/32 位。
//   再用 typedef 给它们起别名 Int8、Int16、Int32。
//
// * 如果按教材风格（不引入 stdint.h）：
//   signed char 通常 8 位，short 通常 16 位，int 通常 32 位，
//   但 C 标准只保证最小位宽，不保证“正好”。
//   所以必须用 sizeof 在你的机器上确认。
// ------------------------------------------------------------

// * 本文件唯一可运行的 main（推荐写法，C23 下精确宽度）：

#include <stdio.h>
#include <stdint.h>   //  <-- intxx_t需要调用这个库

typedef int8_t  Int8;    // * 正好 8 位有符号整数
typedef int16_t Int16;   // * 正好 16 位有符号整数
typedef int32_t Int32;   // * 正好 32 位有符号整数

int main(void)
{
    Int8  a;
    Int16 b;
    Int32 c;

    // * 用 sizeof 验证位宽：sizeof 返回字节数，乘 8 得到位数。
    printf("Int8  size = %zu bytes (%zu bits)\n", sizeof(Int8),  sizeof(Int8)  * 8);
    printf("Int16 size = %zu bytes (%zu bits)\n", sizeof(Int16), sizeof(Int16) * 8);
    printf("Int32 size = %zu bytes (%zu bits)\n", sizeof(Int32), sizeof(Int32) * 8);

    // * 变量声明了但没使用，加一句 (void) 消除警告。
    (void)a;
    (void)b;
    (void)c;

    return 0;
}

// * 典型输出（常见平台）：
//   Int8  size = 1 bytes (8 bits)
//   Int16 size = 2 bytes (16 bits)
//   Int32 size = 4 bytes (32 bits)

