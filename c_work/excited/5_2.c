// 下面的 if 语句不需要这么复杂，请尽可能地加以简化。
// if (age >= 13)
//     if (age <= 19)
//         teenager = true;
//     else
//         teenager = false;
// else if (age < 13)
//     teenager = false;
// ------------------------------------------------------------

// * 你的原答：
// 8.答: if (age >= 13 && age <= 19) teenager = true; else teenager = false;

// * 批改：✅ 正确。
// * 原因：
//   * 注意悬垂 else：内层 else 匹配的是最近的 if (age <= 19)，
//     不是外层 if (age >= 13)。
//   * 所以逻辑是：
//     - age >= 13 且 age <= 19 → true
//     - age >= 13 且 age > 19  → false
//     - age < 13               → false
//   * 合并后：age 在 [13, 19] 内为 true，否则为 false。
//   * 你的写法完全正确。
// ? 还可以进一步简化为一行赋值表达式：
// ?   teenager = (age >= 13 && age <= 19);
// ? 效果相同，更简洁。
// * 正确答案：
//   if (age >= 13 && age <= 19)
//       teenager = true;
//   else
//       teenager = false;
//   或 teenager = (age >= 13 && age <= 19);

