// * 第5题：
// 下面的 if 语句在 C 语言中是否合法？
// if (n >= 1 <= 10)
//     printf("n is between 1 and 10\n");
// 如果合法，那么当 n 等于 0 时会发生什么？
// ------------------------------------------------------------

// * 你的原答：
// 5.答: 合法，会执行子句

// * 批改：✅ 正确。
// * 原因：
//   * 关系运算符 <、>、<=、>= 同级，左结合。
//   * n >= 1 <= 10 等价于 (n >= 1) <= 10。
//   * n >= 1 的结果是 0 或 1。
//   * 0 <= 10 和 1 <= 10 都为真（1）。
//   * 所以整个条件永远为真，无论 n 取什么值都会执行子句。
// * n = 0 时：
//   * 0 >= 1 → 0
//   * 0 <= 10 → 1（真）
//   * 所以会执行 printf。
// ? 补充：这显然不是“判断 n 是否在 1 到 10 之间”，
// ?       正确写法应为 if (n >= 1 && n <= 10)。
// * 正确答案：合法；n = 0 时条件仍为真，会执行子句。

// ------------------------------------------------------------
// * 第6题：
// 下面的 if 语句在 C 语言中是否合法？
// if (n == 1 - 10)
//     printf("n is between 1 and 10\n");
// 如果合法，那么当 n 等于 5 时会发生什么？
// ------------------------------------------------------------

// * 你的原答：
// 6.答: 合法，不会执行子句

// * 批改：✅ 正确。
// * 原因：
//   * 算术运算符 - 的优先级高于判等运算符 ==。
//   * 1 - 10 先算，结果是 -9。
//   * 所以条件等价于 n == -9。
//   * n = 5 时，5 == -9 为假，不会执行子句。
// ? 补充：这也不是“判断 n 是否在 1 到 10 之间”，
// ?       正确写法应为 if (n >= 1 && n <= 10)。
// * 正确答案：合法；n = 5 时不执行子句。

