// * 第9题：
// 下面两个 if 语句是否等价？如果不等价，为什么？
//
// if (score >= 90)                if (score < 60)
//     printf("A");                    printf("F");
// else if (score >= 80)           else if (score < 70)
//     printf("B");                    printf("D");
// else if (score >= 70)           else if (score < 80)
//     printf("C");                    printf("C");
// else if (score >= 60)           else if (score < 90)
//     printf("D");                    printf("B");
// else                            else
//     printf("F");                    printf("A");
// ------------------------------------------------------------

// * 你的原答：
// 9.答: 意思等价，底层运行顺序不一样

// * 批改：✅ 结论正确。
// * 详细说明：
//   * 左边链：从高到低检查（>=90, >=80, >=70, >=60, else）。
//   * 右边链：从低到高检查（<60, <70, <80, <90, else）。
//   * 对任何 score，两边最终输出完全一致：
//     90+ → A，80~89 → B，70~79 → C，60~69 → D，<60 → F。
//   * 所以逻辑等价，输出结果相同。
//   * 但检查顺序不同：左边先排除高分，右边先排除低分。
//     对某个具体 score，左边可能多做几次比较，右边可能少做几次，反之亦然。
// ? 补充：如果 score 是 95，左边第一次就命中 A；
// ?       右边要连续判断 <60、<70、<80、<90 都为假，最后才到 else 输出 A。
// ?       所以“运行顺序不一样”这个观察是对的，
// ?       但最终结果完全等价。
// * 正确答案：等价；输出相同，只是检查顺序相反。

