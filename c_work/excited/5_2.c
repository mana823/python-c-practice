// * 第7题：
// 如果 i 的值为 17，下面的语句显示的结果是什么？
// 如果 i 的值为 -17，下面的语句显示的结果又是什么？
// printf("%d\n", i >= 0 ? i : -i);
// ------------------------------------------------------------

// * 你的原答：
// 7.答: 17。 17。  打印 i 的绝对值

// * 批改：✅ 正确。
// * 原因：
//   * 条件运算符 ?: 的规则：条件为真取冒号前的值，为假取冒号后的值。
//   * i = 17：i >= 0 为真，取 i，输出 17。
//   * i = -17：i >= 0 为假，取 -i = 17，输出 17。
//   * 所以这个表达式整体就是求 i 的绝对值。
// * 正确答案：17；17；打印 i 的绝对值。

