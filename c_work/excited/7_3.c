// * 第2题（7.2节）：哪些常量不合法？合法的是整数还是浮点数？
//   (a) 010E2
//   (b) 32.1E+5
//   (c) 0790
//   (d) 100_000
//   (e) 3.978e-2
// ------------------------------------------------------------
// * 批改：
// (a) 010E2  → 合法，浮点数。
//     带指数 E，是浮点常量；前导 0 在浮点常量里不代表八进制，
//     010 就是十进制数字序列，值为 10，010E2 = 1000.0。
// (b) 32.1E+5 → 合法，浮点数。
// (c) 0790 → 不合法。
//     以 0 开头按八进制解析，八进制只允许 0~7，出现 9 不合法。
// (d) 100_000 → 不合法。
//     C 语言不支持下划线作为数字分隔符。
//     C23 起支持单引号，如 1'000'000，但下划线仍然不合法。
// (e) 3.978e-2 → 合法，浮点数。
// * 正确答案：
// (a) 合法，浮点数
// (b) 合法，浮点数
// (c) 不合法
// (d) 不合法
// (e) 合法，浮点数

