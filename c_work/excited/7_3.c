//   (a) 077
//   (b) 0x77
//   (c) 0XABC
// ------------------------------------------------------------
// * 批改：
// (a) 077   → 八进制，7*8 + 7 = 63
// (b) 0x77  → 十六进制，7*16 + 7 = 112 + 7 = 119
// (c) 0XABC → 十六进制，10*16^2 + 11*16 + 12 = 2560 + 176 + 12 = 2748
// * 正确答案：63、119、2748

