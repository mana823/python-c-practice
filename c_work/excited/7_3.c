//   (a) short unsigned int
//   (b) short float
//   (c) long double
//   (d) unsigned long
// ------------------------------------------------------------
// * 批改：
// (a) 合法，等价于 unsigned short int。
// (b) 不合法，C 没有 short float 这种类型。
// (c) 合法，扩展精度浮点类型。
// (d) 合法，等价于 unsigned long int。
// * 正确答案：(a) 合法，(b) 不合法，(c) 合法，(d) 合法

