// * 第4题（7.3节）：变量 c 是 char 类型，哪条语句非法？
//   (a) i += c;        /* i has type int */
//   (b) c = 2 * c - 1;
//   (c) putchar(c);
//   (d) printf(c);
// ------------------------------------------------------------
// * 你的原答：
// 4.答: (a) 合法   (b) 合法   (c) 合法   (d) 不合法

// * 批改：✅ 完全正确。
// * 理由：
//   (a) char 参与 int 运算时自动提升为 int，合法。
//   (b) 2*c-1 是 int，赋给 char 可能窄化，但语法合法。
//   (c) putchar 接受 int 参数，char 自动提升，合法。
//   (d) printf 第一个参数必须是 const char*，
//       c 是 char，不是指针，非法。
// * 正确答案：(d)

