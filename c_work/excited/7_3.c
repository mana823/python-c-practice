// * 第6题（7.3节）：足以存储数据的最小类型（char/short/int/long）
//   (a) 一个月的天数
//   (b) 一年的天数
//   (c) 一天的分钟数
//   (d) 一天的秒数
// ------------------------------------------------------------
// * 你的原答：
// 6.答: (a) char   (b) short  (c) short   (d) int

// * 批改：✅ 全部正确。
// * 理由：
//   (a) 一个月最多 31 天，char 足够。
//   (b) 一年最多 366 天，char 不够（有符号 char 最大 127），short 足够。
//   (c) 一天 24*60 = 1440 分钟，char 不够，short 足够。
//   (d) 一天 24*60*60 = 86400 秒，short 不够（最大 32767），int 足够。
// * 正确答案：char、short、short、int

