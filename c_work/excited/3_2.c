// * 第4题：
// scanf("%d%f%d", &i, &x, &j);
// 输入：10.3 5 6
// 求 i、x、j 的值。（i、j 为 int，x 为 float）
// ------------------------------------------------------------

// * 你的原答：
// i = 10   x = 0.3   y = 5
// 【scanf 的边界判定逻辑】
// 1. 前导空白（起跑线）：转换说明会自动跳过（吸尘器）。
// 2. 尾部空白（冲刺线）：一旦读到了符合格式的数据，遇到空白字符（或非格式字符）立刻“歇菜”（停止当前读取）。
//    注意：这个空白字符不会被消耗，会原封不动留在缓冲区，成为下一个转换说明的“拦路虎”。

// * 批改：✅ 数值完全正确，只是变量名写错了。
// * 应为：i = 10   x = 0.3   j = 5（不是 y）。
// * 过程：
//   1. %d 读取 "10"，遇到 '.' 停止，'.' 留在缓冲区。
//   2. %f 从 '.' 开始读取 ".3"，得到 0.3，遇到空格停止。
//   3. %d 跳过空格，读取 "5"，得到 5。
// * 你的边界判定逻辑总结得很好，抓住了关键：
//   - 前导空白自动跳过；
//   - 读到符合格式的数据后，遇到不匹配的字符就停止，且该字符不会被消耗。
// ? 补充：非格式字符（如 '-'、','）必须精确匹配；
// ?       格式串中的空白字符则匹配零个或多个空白。

