// * 第3题：
// 说明下列每对 scanf 格式串是否等价？如果不等价，请指出差异。
// (a) "%d" 与 " %d"
// (b) "%d-%d-%d" 与 "%d -%d -%d"
// (c) "%f" 与 "%f "
// (d) "%f,%f" 与 "%f, %f"
// ------------------------------------------------------------

// * 你的原答：
// (a) 等价。
// (b) 不等价，scanf 格式串中出现非格式转化字符，空白字符为跳过空白字符，
//     而非空白字符，则是相匹配，不匹配则崩溃。
// (c) 不等价，第一个接受完就结束，第二个还得遇见一个非空白字符才行。
// (d) 等价。

// * 批改：
// (a) ✅ 正确。%d 本身会跳过前导空白，所以 " %d" 中的空格不改变结果。
// (b) ✅ 结论正确，但“不匹配则崩溃”说法错误。
//     ! scanf 匹配失败时不会崩溃，只是停止读取，返回已成功赋值的项数。
//     * 真正差异：第二个格式在 %d 和 '-' 之间多了一个空格，
//     * 格式串中的空白会匹配零个或多个空白字符，
//     * 所以第二个格式允许数字和 '-' 之间有空白，第一个不允许。
// (c) ✅ 正确。
//     * 补充："%f " 末尾的空格会继续跳过并消耗后续空白，
//     * 直到遇到非空白字符或输入结束；"%f" 读完数字就停止。
// (d) ✅ 正确。
//     * 原因：逗号后的 %f 本身会跳过前导空白，
//     * 所以格式串里写不写空格，对第二个浮点数的读取结果没有影响。

// * 第3题正确答案汇总：
// (a) 等价。
// (b) 不等价：第二个格式允许数字和 '-' 之间有空白，第一个不允许。
// (c) 不等价："%f " 会消耗后续空白，"%f" 不会。
// (d) 等价。

