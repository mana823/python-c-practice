// * 第6题：
// 指出如何修改 3.2 节中的 addfrac.c 程序，
// 使用户可以输入在字符 / 的前后都有空格的分数。
// ------------------------------------------------------------

// * addfrac.c 原读取语句：
// scanf("%d/%d", &num1, &denom1);
// scanf("%d/%d", &num2, &denom2);

// * 你的原答：
// “如果你要输入空格，那我在 / 前加上一个空格就行了，
//   直接跳过第一个 %d 输入后后续的所有空白字符，
//   后面的不用动，%d 自动跳过空白字符。
//   如果你要想加就加，那我不知道怎么做。”

// * 批改：✅ 核心方案正确！
// * 在 / 前加一个空格，写成：
// scanf("%d /%d", &num1, &denom1);
// scanf("%d /%d", &num2, &denom2);
// * 就能读取 / 前后都有空格的分数。
// * 原因：
//   - 格式串中 %d 后的空格可以匹配零个或多个空白字符，
//     所以 / 前有空格也能匹配。
//   - '/' 后的第二个 %d 会自动跳过前导空白，
//     所以 / 后有空格也能读取。
// * 验证下面几种输入都能正确读取：
//   1/2      → %d 读 1，空格匹配零个，'/' 匹配 '/'，%d 读 2。✅
//   1 / 2    → %d 读 1，空格匹配空格，'/' 匹配 '/'，%d 跳过空格读 2。✅
//   1 /2     → %d 读 1，空格匹配空格，'/' 匹配 '/'，%d 读 2。✅
//   1/ 2     → %d 读 1，空格匹配零个，'/' 匹配 '/'，%d 跳过空格读 2。✅
// * 你答中“如果你要想加就加，那我不知道怎么做”这句其实不必纠结：
//   写成 scanf("%d / %d", ...) 也可以，而且更对称、更易读，
//   但不是必须的，你的 "%d /%d" 已经满足题目要求。

// * 第6题正确答案：
// 将 scanf("%d/%d", &num1, &denom1);
// 改为 scanf("%d /%d", &num1, &denom1);
// 或 scanf("%d / %d", &num1, &denom1);
// 两种写法都能读取 / 前后带空格的分数。

