// 7.2节 第2题：判断常量是否合法，并区分整数/浮点数
// 题目：
//   (a) 010E2
//   (b) 32.1E+5
//   (c) 0790
//   (d) 100_000
//   (e) 3.978e-2
// ============================================================

// * 你的原答：
// 答: (a) 合法   (b) 合法，浮点数   (c) 不合法   (d) 合法，整数   (e) 合法，浮点数

// ------------------------------------------------------------
// (a) 010E2
// ✅ 合法，但你没区分类型。
// * 它是浮点常量：数字序列 010 + 指数 E2。
//   在浮点常量里，前导 0 不代表八进制，
//   010 只是十进制数字序列，值为 10。
//   所以 010E2 = 10 × 10² = 1000.0，类型是 double。
// * 正确答案：合法，浮点数。

// ------------------------------------------------------------
// (b) 32.1E+5
// ✅ 正确：合法，浮点数。
// * 32.1 × 10⁵，符合十进制浮点常量。

// ------------------------------------------------------------
// (c) 0790
// ✅ 正确：不合法。
// * 以 0 开头，按八进制解析，但八进制只允许 0~7，出现 9 不合法。

// ------------------------------------------------------------
// (d) 100_000
// ❌ 错误：不是合法整数，而是不合法。
// * 在下划线（_）作为分隔符的情况下，100_000 不合法。
// * 但注意：C23 标准引入了单引号（'）作为数字分隔符，
//   所以 100'000 在 C23 中是合法的整数常量，
//   而 100_000 在任何标准中都不合法。
// * 正确答案：不合法。

// ------------------------------------------------------------
// (e) 3.978e-2
// ✅ 正确：合法，浮点数。
// * 3.978 × 10⁻²，符合十进制浮点常量。

// ============================================================
