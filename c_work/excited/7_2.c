// (c) 合法
// (d) 合法

// ============================================================
// * 关于你补充的 C23 单引号分隔符：
// ============================================================
// * int million = 1'000'000;  // ✅ C23 合法
// * 你的理解正确：
//   C23 标准允许在整数和浮点常量中使用单引号（'）作为数字分隔符。
//   编译器会忽略这些单引号，所以 1'000'000 等同于 1000000。
//
// * 支持的范围：
//   - 十进制整数：1'000'000
//   - 十六进制整数：0xFE'DC'BA'98
//   - 二进制整数：0b1010'0110
//   - 浮点常量：3.141'592
//   - 各种进制都支持，不限于十进制。
//
// * 历史：
//   单引号分隔符最早在 C++14 中标准化，
//   C 语言直到 C23 才正式引入。
//   在此之前，C 语言不支持任何形式的数字分隔符
//   （包括下划线 _ 和单引号 '）。
//   所以 100_000 和 1'000'000 在 C23 之前都不合法。
//
// * 注意事项：
//   1'000'000 虽然可读性更好，但编译器会完全忽略单引号，
//   实际值仍然是 1000000，类型和值都不变。
//   单引号只能出现在数字之间，不能放在开头或结尾，
//   也不能连续出现两个单引号。