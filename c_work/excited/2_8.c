// ------------------------------------------------------------
// * 第10题题目：
// 在 dweight.c 程序（2.4 节）中，哪些空格是必不可少的？
// ------------------------------------------------------------

// * 你的原答：
// (10)答: int后面;return后面。

// * 批改：✅ 基本正确，但不完整、表述可更精确。
// * 你抓住了关键：int 后面和 return 后面需要空格，否则会和后面的标识符/常量粘成一个记号。
// * 但 dweight.c 中不止这两处，还有：
// *   - #include <stdio.h> 中，严格来说 #include 和 <stdio.h> 之间的空格不是必须的，
// *     因为 < 不是标识符字符，写成 #include<stdio.h> 也合法。但通常写成空格更清晰。
// *   - int main(void) 中，int 和 main 之间的空格是必须的。
// *   - int height, length, width, volume, weight; 中，int 和 height 之间的空格是必须的。
// *   - return 0; 中，return 和 0 之间的空格是必须的。
// * 其他空格，比如运算符两侧、逗号后、printf 和 ( 之间，都不是必须的，只是为了可读性。
// * 所以更准确的答案：
// *   必不可少的空格出现在需要分隔两个相邻记号、防止它们合并成一个记号的地方。
// *   在 dweight.c 中主要是：
// *     1. int 和 main 之间
// *     2. int 和 height 之间
// *     3. return 和 0 之间
// *   （#include 和 <stdio.h> 之间的空格不是严格必须，但习惯保留。）

