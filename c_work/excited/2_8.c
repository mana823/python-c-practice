// * 第8题题目：
// 下面的语句中有多少个记号？
// answer=(3*q-p*p)/3;
// ------------------------------------------------------------

// * 你的原答：
// (8)答: 8个

// ! 批改：❌ 错误。
// ! 你数少了。分号也是记号，括号、运算符、常量、标识符各自都是独立记号。
// * 正确数法：
// *   answer  标识符
// *   =       运算符
// *   (       标点符号
// *   3       常量
// *   *       运算符
// *   q       标识符
// *   -       运算符
// *   p       标识符
// *   *       运算符
// *   p       标识符
// *   )       标点符号
// *   /       运算符
// *   3       常量
// *   ;       标点符号
// * 总共 14 个记号。
// * 正确答案：14 个。

