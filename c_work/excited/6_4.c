//   i=7：1，continue → sum=12
//   i=8：0，sum += 8 → sum=20
//   i=9：1，continue → sum=20
//
// * 所以 sum = 0 + 2 + 4 + 6 + 8 = 20。
// ? 你写 21，可能是把某个奇数也加进去了，或者 0 被算成了 1。
//
// * 正确答案：20

// ------------------------------------------------------------
// * 第12题：
// for (d = 2; d < n; d++)
//     if (n % d == 0)
//         break;
// 修改循环，只检查不大于 n 的平方根的除数。
// 提示：用 d*d 和 n 比较，不要计算平方根。
// ------------------------------------------------------------

// * 你的原答：
// 12.答: for (d = 2; d < n; d++) if (d * d <= n) break;

// ! 批改：❌ 错误。
// ! 错误点：你把 d*d <= n 放进了循环体，变成了 break 的条件。
// ! 这样只要 d*d <= n 成立就立刻 break，
// ! 对 n=100，d=2 时 4 <= 100 成立，直接 break，
// ! 根本没检查 100 % 2 是否等于 0，逻辑完全错了。
//
// * 题目要求的是：把“循环条件”从 d < n 改成 d*d <= n。
//   d*d <= n 应该出现在 for 的条件部分，不是循环体里。
//
// * 正确写法：
//   for (d = 2; d * d <= n; d++)
//       if (n % d == 0)
//           break;
//
// * 解释：
//   只检查 d 从 2 到 sqrt(n) 的除数。
//   不直接算 sqrt(n)，而是用 d*d <= n 判断，
//   避免浮点运算，也避免 sqrt 的精度问题。
//   如果 n 有大于 sqrt(n) 的因子，
//   那它一定有一个小于 sqrt(n) 的配对因子，
//   所以只查到 sqrt(n) 就够了。

// ------------------------------------------------------------
// * 本文件唯一可运行的 main（验证第11题和第12题）：
// ------------------------------------------------------------

#include <stdio.h>

int main(void)
{
    // * 第11题验证
    int sum = 0;
    int i;
    for (i = 0; i < 10; i++) {
        if (i % 2)
            continue;
        sum += i;
    }
    printf("sum = %d\n", sum);   // * 输出 20

    // * 第12题验证：判断 97 是否为素数
    int n = 97;
    int d;
    for (d = 2; d * d <= n; d++)
        if (n % d == 0)
            break;

    if (d * d > n)
        printf("%d is prime\n", n);   // * 97 是素数
    else
        printf("%d is not prime\n", n);

    return 0;
}

// * 输出：
//   sum = 20
//   97 is prime

