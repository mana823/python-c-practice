// ------------------------------------------------------------
// * 第10题：如何用等价的 goto 语句替换 continue？
// ------------------------------------------------------------

// * 你的原答：
// “continue 无非是在 while 循环跳至判断前，
//   而 for 语句跳至最后那个表达式3语句那边。
//   我们可以在 while 语句前写一个空语句标号，直接跳过去。
//   而在 for 语句我们不写表达式3在圆括号内，
//   而是自己手动在最后写，并且把这个表达式写进一个标号内，
//   之后 goto 跳至那个标号就可以。”

// * 批改：⚠️ 思路基本正确，但 while 那句表述有歧义，需要澄清。
//
// ✅ for 部分正确：
//   continue 在 for 里就是跳到“更新表达式”（表达式3）的位置。
//   改成 while 风格时，不写表达式3，把更新表达式放到循环体末尾，
//   前面加一个标签，goto 跳过去即可。
//
// ⚠️ while 部分要澄清：
//   continue 在 while 里不是“跳至判断前”，
//   而是“跳过循环体剩余部分，直接去执行下一次条件判断”。
//   对应的 goto 写法是：在循环体末尾放一个空语句标签，
//   continue 改成 goto 跳到这个标签，标签之后自然回到 while 条件。
//
//   你说“在 while 语句前写一个空语句标号”，
//   如果字面理解成“while 之前”，那就错了，goto 会直接跳出整个循环。
//   正确位置是“while 循环体的末尾”。
//
// * 正确写法：
//
//   while 的 continue：
//     while (test) {
//         ...
//         if (cond) goto continue_label;
//         ...
//         continue_label: ;     // 空语句，循环体末尾
//     }
//
//   for 的 continue：
//     for (init; test; ) {
//         ...
//         if (cond) goto update_label;
//         ...
//         update_label: update;  // 更新表达式挪到这里
//     }
//
// ? 注意：for 版本里圆括号内不再写 update，
//   否则 update 会在每次循环体结束后自动执行一次，
//   再叠加 goto 跳过去的 update，就执行两次了。

