// * 第13题：重写循环，使循环体为空。
// 原循环：
// for (n = 0; m > 0; n++)
//     m /= 2;
// ------------------------------------------------------------

// * 你的原答：
// 13.答: for (n = 0; m > 0; m /= 2, n++) {}

// * 批改：✅ 正确。
// * 原循环每轮做两件事：
//   1. 循环体执行 m /= 2;
//   2. 更新表达式执行 n++。
// * 把 m /= 2 挪进更新表达式，循环体就空了：
//   for (n = 0; m > 0; m /= 2, n++)
//       ;
// * 你写成 `m /= 2, n++`，顺序是“先除以 2，再 n++”。
//   原循环是“先 m /= 2，再 n++”，顺序一致。
// * 因为 m /= 2 和 n++ 互不依赖，交换顺序也不影响结果，
//   所以写成 `n++, m /= 2` 也对。
//
// * 正确写法（任选其一）：
//   for (n = 0; m > 0; m /= 2, n++)
//       ;
//   for (n = 0; m > 0; n++, m /= 2)
//       ;
// ? 循环体用单独一行的 `;` 比 `{}` 更直观地表达“空循环体”。
// ? 你写 `{}` 也完全正确，效果一样。

// ------------------------------------------------------------
// * 第14题：找出下面程序片段中的错误并修正。
// if (n % 2 == 0);
// printf("n is even\n");
// ------------------------------------------------------------

// * 你的原答：
// 14.答: if 后面有分号，执行空，而后面的 printf 语句不在 if 语句里面
// 修正: if (n % 2 == 0) printf("n is even\n");

// * 批改：✅ 完全正确。
// * 错误原因：
//   if (n % 2 == 0); 后面这个分号，让 if 的语句体变成了空语句 `;`。
//   也就是说：
//     if (n % 2 == 0)
//         ;              // 空语句
//     printf("n is even\n");   // 这条语句和 if 无关，永远执行
//   结果不管 n 是奇数还是偶数，都会打印 "n is even"。
// * 修正：
//   去掉 if 后面的分号，
//   或者用花括号把 printf 包起来：
//     if (n % 2 == 0) {
//         printf("n is even\n");
//     }
// * 正确答案：删除 if 后的分号。

// ------------------------------------------------------------
// * 本文件唯一可运行的 main（验证第13、14题）：
// ------------------------------------------------------------

#include <stdio.h>

int main(void)
{
    // * 第13题验证
    int n, m = 10;
    for (n = 0; m > 0; m /= 2, n++)
        ;
    printf("n = %d, m = %d\n", n, m);   // * n=4, m=0

    // * 第14题验证
    int x = 3;
    if (x % 2 == 0)
        printf("x is even\n");
    else
        printf("x is odd\n");           // * 输出 x is odd

    return 0;
}

// * 输出：
//   n = 4, m = 0
//   x is odd

// ============================================================
// 批改总结：
// 第13题：✅ 正确。
//   m /= 2 挪进更新表达式，循环体为空。
//   写成 `m /= 2, n++` 或 `n++, m /= 2` 都对。
//   循环体用 `;` 或 `{}` 都行。
// 第14题：✅ 完全正确。
//   if 后面多了一个分号，语句体变成空语句，
//   printf 变成了无条件执行。
//   修正：删掉 if 后的分号。
// ============================================================