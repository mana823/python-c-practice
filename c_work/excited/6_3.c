// * 第9题：把练习题 8 中的 for 语句改写为等价的 while 语句。
// 除了 while 循环本身之外，还需要一条语句。
// ------------------------------------------------------------

// * 你的原答：
// 9.答: while (i >= 1) {i = 10; printf("%d ", i++); i /= 2;}

// ! 批改：❌ 错误。
// ! 错误点：你把初始化 `i = 10;` 放进了循环体。
// ! 这样每次循环都会把 i 重置为 10，
// ! 打印永远是 10，然后 i=11，i/=2 变 5，
// ! 下一次循环又 i=10，永远循环打印 10，
// ! 和原 for 的输出 10 5 3 2 1 1 1... 完全不同。
//
// * 正确改写：
//   for 的三个部分分别对应：
//     初始化 i = 10;        → 放在 while 之前
//     条件   i >= 1;        → 放在 while 条件里
//     更新   i /= 2;        → 放在循环体最后
//   循环体 printf("%d ", i++); 原样保留。
//
// * 正确写法：
//   i = 10;
//   while (i >= 1) {
//       printf("%d ", i++);
//       i /= 2;
//   }
//
// * 题目说“除了 while 循环本身之外，还需要一条语句”，
//   指的正是循环之前的那条 `i = 10;`。
//   你把它放到循环体里，位置错了。

// ------------------------------------------------------------
// * 本文件唯一可运行的 main（把第9题的正确写法放进程序验证）：
// ------------------------------------------------------------

#include <stdio.h>

int main(void)
{
    int i;

    // * 第9题：for 改 while 的正确写法
    i = 10;                    // * 初始化放在 while 之前
    while (i >= 1) {           // * 条件
        printf("%d ", i++);    // * 循环体，打印后 i 加 1
        i /= 2;                // * 更新，放在循环体最后
    }
    printf("\n");

    return 0;
}

