// >> 当程序含有常量时，建议给这些常量命名，在以后阅读程序时可能有人不明白这些常量的含义，因此可以采用称为宏定义(macro difinition)的特性给常量名:
// >>      #define INCHES_PER_POUND 166   <-- 这里的#define是预处理指令，类似#include，所以末尾没有分号
// ! #define 名字 值  <-- 名字和值之间用空格隔开，不加等号，不加分号。本质是“编译前的文本替换”，不是“赋值”。
// >> 当对程序进行编译时，预处理器会把每一个宏替换为其表示的值。例如:
// >>      weight = (volume + INCHES_PER_POUND - 1) / INCHES_PER_POUND;   <-- 将变为:
// >>      weight = (volume + 166 - 1) / 166;   <-- 效果就如同在前一个地方写的是最后一条语句(相当于直接替换)

// ? 宏定义是“编译前的文本替换”，不占内存、没有类型、不能取地址；变量赋值是“运行时的内存存储”，占内存、有类型、能取地址。 表面像，底层完全不是一回事。
// >> 此外，还可以利用宏来定义表达式:
// >>      #define RECIPROCAL_OF_PI (1.0f / 3,14159f)  <-- 当宏包含运算符时，建议建议建议用括号(14.3节)把表达式括起来。
// ! f后缀是用来指定浮点数字面量的类型的:不加 f 默认是 double,加了 f 就是 float。书上的宏加了 f,是为了让整个算式从头到尾都是 float 类型,避免隐式转换的警告，让代码和运算类型精确匹配。
// ! 宏定义本身无类型，但它替换进去的字面量有默认类型：整数默认 int，浮点默认 double。想让它是 float，就手动加 f 后缀。
// * 定义（宏）无内存：#define 只是起个名字，替换完就消失了。f是标志：它只是告诉编译器“这个数字是 float”，没有内存，也不参与替换。

// ? 宏不一定要大写，只是增加可读性，这是C语言程序员的共识

