// >> 当这些转义序列出现在printf函数的格式串中时，它们表示在显示中执行的操作。在大多数机器上，输出\a会产生一声鸣响，
// >> 输出\b会使光标从当前位置会退一个位置，输出\n会使光标跳到下一行的起始位置，输出\t会把光标移动到下一个制表符的位置

// ! 【问答补充】不可能知道转义序列\t水平制表符在printf函数到底可以跳多远，打印\t的效果不是由C语言定义的，而是依赖于所使用的操作系统。水平制表符通常是8个字符宽度，但C语言本身无法保证这一点
// ? \t 在 C 语言层面只代表 ASCII 码 9，跳多远由操作系统和终端渲染决定，C 语言本身不做保证。

// >> 字符串可以包含任意数量的转义序列:
// >>      printf("Them\tUnit\tPurchase\n\tPrice\tDate\n");
