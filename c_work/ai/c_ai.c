// ! 一般记号之间可以不用空格，除非两个记号合并会产生第三个记号
// >> 语句可以分开放在任意多行内:
// >>      printf("Dimendional weight (pounds): %d\n",
// >>          (volume + INCHES_PER_POUND - 1) / INCHES_PER_POUND);
// >> 记号之间的空格让我们更容易区分:      volume = height * length * width;
