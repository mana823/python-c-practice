/* 3.1 printf函数 */
// >> printf函数被设计为显示格式串(format string)的内容，可在指定位置插入可能的值。调用必须提供格式串，格式串后面的参数是需要显示时插入的值:
// >> printf(格式串, 表达式1, 表达式2, ...);    <-- 显示值可以是常量、变量或更加复杂的表达式。

// >> 格式串包含普通字符和转换说明(conversion specification),转换说明以字符%开头，是用来表示打印过程中的带填充的值的占位符。
// >> 跟随在字符%后边的信息指定了把数值从内部形式(二进制)转换成打印形式(字符)的方法，这就是“转换说明”这一术语的由来:例如转换说明%d指定printf函数把int型值从二进制形式转换成十进制数字组成的字符串
// ? 内存里确实全是二进制，int 这类类型是编译期契约，规定"占几字节 + 怎么编码解码"。编译后类型消失，运行期只剩位和指令。

// ! 注意: C语言编译器不会检测格式串中转换说明的数量是否和输出项的数量相匹配:
// >>      int i = 10, j = 20;
// >>      float x = 43.2892f, y = 5527.0f;
// >>      printf("%d %d\n", i);   <-- 正常显示变量i的值，接着显示另一个(无意义的)整数值。
// >>      printf("%d\n", i, j);   <-- 会显示变量i的值，但不显示变量j的值。

// ! 此外，C语言编译器也不检测转换说明是否合适要显示项的数据类型:
// >>      printf("%f %d\n", i, x);  <-- printf函数必须服从于格式串，所以它将如实显示出一个float型值和一个int型值。可惜两个值都是无意义的
// ! printf 和 scanf 都只认格式串、不认变量类型；区别是 printf 按格式串"解码读出"，scanf 按格式串"编码写入"。 格式串写错，printf 输出乱码，scanf 直接写坏内存。
// ? 输入流是"队列"，scanf 按格式串消费，没消费完的留在缓冲区，下次继续用。这确实像"提前接收"——但接收的是输入流，不是内存。


