/*2.5 读入输入*/
// >> scanf函数与pringf函数相对应(f的含义都是"格式化"的意思),都需要使用格式串(format string)来指定输入数据或输出数据的形式。
// >> scanf函数需要知道将获得的输入数据的格式，而printf函数需要知道输出数据的显示格式。

// >> 为了读一个int型值，可以使用下面的scanf函数调用:
// >>      scanf("%d", &i);  /* 读取一个整数，存进变量i里面*/
// >> 其中，字符串"%d"说明scanf读入的是一个整数，而i是一个int型变量，用来存储scanf读入的输入。&运算符(11.2节)在这里很难解释清楚，因此现在只说明它在使用scanf函数时通常是(但不总是)必需的。

// >> 读取一个float型值时，需要一个形式略有不同的scanf调用:
// >>      scanf("%f", &x);  /*读取一个浮点数，并存储到x中*/
// >> %f只用于float型变量，因此这里假设x是一个float型变量。字符串"%f"告诉scanf函数去寻找一个float格式的输入值(此数可以含有小数点，但不是必须含有)

// >> 格式串：告诉 scanf 要读什么类型。比如 %d 读整数、%f 读浮点数、%s 读字符串。
// >> 地址（&）：告诉 scanf 读到的数据存到哪。&age 就是 age 变量的地址。
// >> 按顺序一一对应：格式串里第几个格式符，就对应后面第几个地址实参。

// ! 必须加 &：普通变量要加 &（如 &age），否则会把变量的值当成地址，导致崩溃。
// ! 字符串数组例外：数组名本身就是地址，所以 scanf("%s", name); 不加 &。
// ! 类型必须匹配：%d 配 int，%f 配 float，%lf 配 double。类型写错，写进去的数据就乱了。
// ! %s 遇到空格就停：输入 Zhang San，只会读到 Zhang，空格后面的内容留在缓冲区。

// >> scanf(按格式串的约定，解释后面的地址实参，从输入流中读取对应类型的数据，转换后写入该地址。)
// ? scanf 只管读，不管提示。想给用户提示，必须自己先写一句 printf。 这就像 Python 里把 input 拆成两半：一半是 print("提示")，一半是 input()。
// ! scanf 读取到合适类型，enter让终端推给scanf(提交),之后结束。如果类型不一样，存储到垃圾信息后续调用程序报错，还会把错误的数据"卡"到缓冲区内
// ! scanf 里的 \n 不是“换行”，而是“跳过空白字符直到遇到非空白字符”。它会导致程序“假死”或“吃错数据”。

// ! 【底层认知：各阶段依谁】—— 你的绝佳总结
// >> 阶段         依谁
// >> scanf 解析输入   依格式串 %f
// >> scanf 往内存写   依格式串决定的类型（float）
// >> printf 读 r      依printf的格式串（比如 %d）
// >> 变量声明 int      只在编译期约束，运行时 scanf 不管
// * 总结：变量声明只是给编译器看的“标签”，真正的运行时，scanf 和 printf 完全按照“格式串”的指示去解析和读写内存。

