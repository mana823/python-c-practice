/*2.8 C程序的书写规范*/
// >> 把C程序看作一连串记号(token)，即许多再不改变意思的情况上无法再分割的字符组。标识符和关键字都是记号。像+和-这样的运算符、逗号和分号这样的标点符号以及字串面，都是记号:
// >>      printf("Height: %d\n", height);   <-- 由7个符号组成
