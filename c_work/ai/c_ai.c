/* 3.1 printf函数 */
// >> printf函数被设计为显示格式串(format string)的内容，可在指定位置插入可能的值。调用必须提供格式串，格式串后面的参数是需要显示时插入的值:
// >> printf(格式串, 表达式1, 表达式2, ...);    <-- 显示值可以是常量、变量或更加复杂的表达式。
// >> 格式串包含普通字符和转换说明(conversion specification),转换说明以字符%开头，是用来表示打印过程中的带填充的值的占位符。
// >> 跟随在字符%后边的信息指定了把数值从内部形式(二进制)转换成打印形式(字符)的方法，这就是“转换说明”这一术语的由来:例如转换说明%d指定printf函数把int型值从二进制形式转换成十进制数字组成的字符串
// ? 内存里确实全是二进制，int 这类类型是编译期契约，规定"占几字节 + 怎么编码解码"。编译后类型消失，运行期只剩位和指令。

// ! 注意: C语言编译器不会检测格式串中转换说明的数量是否和输出项的数量相匹配:
// >>      int i = 10, j = 20;
// >>      float x = 43.2892f, y = 5527.0f;
// >>      printf("%d %d\n", i);   <-- 正常显示变量i的值，接着显示另一个(无意义的)整数值。
// >>      printf("%d\n", i, j);   <-- 会显示变量i的值，但不显示变量j的值。

// ! 此外，C语言编译器也不检测转换说明是否合适要显示项的数据类型:
// >>      printf("%f %d\n", i, x);  <-- printf函数必须服从于格式串，所以它将如实显示出一个float型值和一个int型值。可惜两个值都是无意义的
// ! printf 和 scanf 都只认格式串、不认变量类型；区别是 printf 按格式串"解码读出"，scanf 按格式串"编码写入"。 格式串写错，printf 输出乱码，scanf 直接写坏内存。
// ? 输入流是"队列"，scanf 按格式串消费，没消费完的留在缓冲区，下次继续用。这确实像"提前接收"——但接收的是输入流，不是内存。
// ? 【问答补充】printf 遇到连续的 %% 时，会将其识别为特殊格式，并在屏幕上输出一个实际的 % 字符。(注意：这不是转义，转义是指 \n, \\ 等反斜杠操作)

/* 3.11 转换说明 */
// >> 转换说明可以包含格式化信息。具体来说，可以用%.1f来显示小数点后带一位数字的float型值。
// * 更一般地，转换说明可以用( %m.pX )格式或( %-m.pX )格式，这里面的m和p都是整型常量，而X是字母。m和p都是可选的。如果省略p，m和p之间的的小数点要去掉(%m.X合法，这时算p是0)
// >> 在转换说明 %10.2f 中,m是10，p是2，X是f。  在转换说明 %10f 中，m是10，p(连同小数点一起)省去了;而在转换说明 %.2f 中，p是2，m省去了

// ! 【问答补充】转换说明%i也可以用于读写整数。%i和%d之间的区别: 
// >> 在printf格式串使用中，二者没有区别。但是在scanf格式串中，%d只能与十进制(基数为10)形式整数相匹配，
// ! 而%i可以匹配用八进制(基数为8)、十进制或十六进制(基数为16)表示的整数。如果输入的数有前缀0(如056)，那么%i会把它作为八进制数(7.1节)来处理;
// ! 如果输入的数有前缀0x或0X(如0x56)，那么%i会把它作为十六进制数(7.1节)来处理。如果用户意外地将0放在数的开始处，那么用%i代替%d读取数可能会意想不到，所以建议坚持采用%d

/* 最小栏宽 */
// >> 最小栏宽(minimum field width)m制定了要显示的最少字符数量。如果需显示的数值所需字符数少于m，那么值在字段内向右对齐。(在之前面防治额外空格)
// >> 例如转换说明 %4d 将以 ·123 的形式显示数 123(本章用符号 · 表示空格字符)
// >> 如果要显示的值所需的字符数多于m那么栏宽会自动扩展为所需的尺寸。因此，转换符说明 %4d 将以12345显示12345，不会丢失数字。
// >> 在m前放上一个负号会导致左对齐;转换符说明 %-4d 将以 123· 的形式显示 123

/* 精度 */
// >> 精度(precison)p的含义很难描述，因为它依赖于转化指定符(conversion specifier)X的选择。X表明在显示数值前需要对其进行哪种转换。
// >> d —— 表示十进制(基数为10)形式的整数,p指明了待显示数字的的最少个数(必要时在数前加上额外的零);如果省略p默认为1
// >> e —— 表示指数(科学计数法)形式的浮点数。p指明了小数点后应该出现的数字个数(默认6).如p为0，则不显示小数点。
// >> f —— 表示“定点十进制”形式的浮点数，没有指数。p的含义与说明符e中一样
// >> g —— 表示指数形式或定点十进制形式的浮点数，形式的选择根据数的大小决定。p意味着可以显示的有效数字(不是小数点后的数字)的最大数量。与转换指定符f不同，g的转换将不显示尾随的零。此外，如果要显示的数值没有小数点后的数字，g就不会显示小数点
// ? E < -4 或 E >= P 用 %e，否则用 %f；E 是科学计数法指数，P 是精度（默认6）。 选完再去尾零、去多余点。边界是"定点形式是否还合理"，不是比字符串长短。
// >> 编写程序无法预知数大小或者数值变化范围很大的情况下，说明符g对于数的显示特别有用，显示适中采用定点十进制，过大或过小转换成指数形式以便减少所需的字符数
// >> 除了%d, %e, %f, %g以外，还有许多其他的说明符[整形说明符(7.1节)， 浮点型说明符(7.2节)， 字符说明符(7.3节)， 字符串说明符(13.3节)]

// ! 【精度规则完全总结】
// >> 1. 浮点数（%f/%e/%g）：四舍五入（底层遵循向偶数舍入）。
// >> 2. 字符串（%s）：直接截断（取前 p 个字符，绝不进位）。
// >> 3. 整数（%d）：不涉及小数，.p 代表最少数字位数（补零）。
// ? 精度（.p）和四舍五入、截断，只属于 printf 及其变体（sprintf, fprintf）。scanf 家族根本没有精度概念，只有宽度（读取最大字符数）。

