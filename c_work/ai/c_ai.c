// >>      printf("\"Hello!\"");
// 输出如下:
//      "Hello!"
// ! 附带提一下，不能在字符串中只放置单独一个字符\，编译器会认为它是一个转义序列的开始。为了单独显示一个字符\，需要放置两个字符\:
// >>      printf("\\");    <-- 打印一个字符\

/* 3.2 scanf函数*/
// >> 如同printf函数用特定的格式显示输出一样，scanf函数的格式也根据特定的格式读入输入。像printf函数的格式串一样
// >> scanf函数的格式串也可以包含普通字符和转换说明(不过没有精度.p)两部分，其两者转换说明的用法本质一样。

// >> 在多数情况，scanf函数的格式串只包含转换说明，如下例所示:
// >>      int i, j;
// >>      float x, y;
// >>      scanf("%d%d%f%f", &i, &j, &x, &y);  <-- 这种"紧密压缩"的格式串很普遍，而printf函数很少这样

// ? 指数（科学计数法 e）只是人类为了好写、好看而发明的一种“表示形式”（语法糖）；
// ? 而计算机内存里真正存的，只有浮点数格式（通常是 IEEE 754 标准的二进制），所以在scanf函数输入"-4.0e3"，会赋值-4000.0给地址变量

// ! 注意检查scanf函数转换说明的数量是否与输入的变量数量相匹配，并检查每个转换是否适合相对应的变量(编译器无法检测出)，符号&常常(但不总是)是需要的

/*****************************************   注意    *******************************************/
// ! 如果 scanf 函数调用中忘记在变量前面放置符号 &，将产生不可预知甚至可能是毁灭性的结果。程序崩溃是常见的结果。
// ! 最轻微的后果则是从输入读进来的值无法存储到变量中，变量将保留原有的值（如果没有给变量赋初始值，那么这个原有值可能是没有意义的）。
// ! 忽略符号 & 是极为常见的错误，一定要小心！一些编译器可以检查出这种错误，并产生一条类似“format argument is not a pointer”的警告消息。
// >> （术语指针将在第 11 章定义，符号 & 用于创建一个指向变量的指针。）如果抛出警告消息，检查一下是否遗漏了符号 &。

/* 3.2.1 scanf函数的工作方法*/
// ? scanf函数能做的事很多，其本质上是一种"模式匹配"函数，试图把输入的字符组与转换说明相匹配。
// >> 和printf函数一样，其是由格式串控制。调用时从左边处理字符串中的信息，并在必要时跳过空格。然后读取数据，并在遇到不可能属于此项的字符停止。
// ! 如果读取数据成功，那么scanf函数会继续处理格式串的剩余部分;如果某一项不能成功接入，那么scanf函数将不再查看格式串的剩余部分(或者余下的输入数据)，并立即返回

// >> 在寻找数的起始位置时，scanf函数会忽略空白字符(white-space character，包括空格符、水平和垂直制表符、换页符和换行符)。因此可以把数字放在同一行或分为几行来输入:

// >>      scanf("%d%d%f%f", &i, &j, &x, &y);
// 假设用户录入3行输入:
//        1
//      -20   .3
//         -4.0e3
//      (敲回车的隐藏¤,实则每一行都有)
// scanf会给它们看成一个连续的字符流:
//      ··1¤-20···.3¤···-4.0e3¤        <-- (这里使用符号·代表空格符，符号¤表示换行符)
// 因为scanf函数在寻找每个数的起始位置时会跳过空白字符，所以它可以成功读取这些数。在接下来的代码示意中，字符下方的s表示此项被跳过，而字符下面的r表示此项被读取为输入项的一部分:
//      ··1¤-20···.3¤···-4.0e3¤
//      ssrsrrrsssrrssssrrrrrrr
// ! scanf函数"忽略"了最后的换行符，实际上没有取用它。这个换行符将是下一次scanf函数调用到第一个字符。

/* 
================================================================================
                    C语言 scanf 输入流与换行符(\n) 避坑完全指南
================================================================================

【核心概念】
1. 终端敲的回车，本质是字符流中的一个普通字符：'\n'（换行符）。
2. scanf 在处理输入时，就像流水线上的工人，按格式串的要求挑选零件，多余的留在传送带上（输入缓冲区）。
3. 格式串里的 '\n' 和终端敲的 '\n'，在 scanf 眼里是完全不同的两个东西。

--------------------------------------------------------------------------------
场景一：终端敲的回车（针对 %d、%f）
--------------------------------------------------------------------------------
* 现象：你输入 "10" 然后按下回车。
* 输入流：字符串 "10\n" 进入缓冲区。
* scanf行为：%d 和 %f 是“自动吸尘器”，它们在找数字。读完 10 后，遇到 '\n'，
              会认为这是“空白字符”而自动跳过，继续往后找下一个数字。
* 结果：数字完美录入。
// ! 隐患：被跳过的 '\n' 并没有消失，它依然留在输入缓冲区里，准备坑下一次输入。

--------------------------------------------------------------------------------
场景二：终端敲的回车（针对 %c）
--------------------------------------------------------------------------------
* 现象：你输入 "A" 然后按下回车。接着代码里还有一句 scanf("%c", &ch2);
* 输入流：字符串 "A\n" 进入缓冲区。
* scanf行为：%c 是“极度死心眼”，它绝对不跳过任何空白字符！
              第一个 scanf 读走了 'A'。第二个 scanf 会瞬间读走留在缓冲区里的 '\n'。
* 结果：程序看起来“跳过”了你的第二次输入，直接往下运行了。
// ! 解法：在 %c 前面加个空格！写成 scanf(" %c", &ch); 
        这个空格是在命令 scanf：“先把前面所有的空白字符（包括换行）全给我吃掉，再读字符”。

--------------------------------------------------------------------------------
场景三：scanf 格式串里主动写了换行 \n（如 scanf("%d\n", &i)）
--------------------------------------------------------------------------------
* 现象：代码里写了 scanf("%d\n", &i);
* scanf行为：格式串里的 '\n' 不是数据，而是一个“死等指令”。
              意思是：读完数字后，一直往后吃空白字符，直到遇见一个“非空白字符”才肯收工。
// ! 结果：程序卡死。你输入 "10" 回车，程序不走；你必须再输入一个字符（比如 'X'）再回车，
        它吃了空格吃了回车，看到 'X' 发现不是空白，指令结束。但 'X' 还会留在缓冲区里坑下一个 scanf。
// ! 铁律：【永远不要在 scanf 的格式串末尾写 '\n' 或空格！】

--------------------------------------------------------------------------------
场景四：scanf 格式串里写了普通字符（如 scanf("%d,%d", &a, &b)）
--------------------------------------------------------------------------------
* 现象：代码里写了逗号。
* scanf行为：遇到非空白普通字符（逗号、横杠等），scanf 要求用户输入必须“严丝合缝”地匹配。
// ! 结果：你必须输入 "10,20" 才能成功。如果你输入 "10 20"，scanf 读完 10 后期待逗号，
        结果遇到了空格，它会立刻罢工（读取失败），导致 b 变量根本没有被赋值。

--------------------------------------------------------------------------------
场景五：读完了，但没读干净（多余残留）
--------------------------------------------------------------------------------
* 现象：书上的例子，输入流 "... -4.0e3\n"。
* scanf行为：当格式串要求的 4 个变量 (i, j, x, y) 都塞满了，scanf 任务完成，立刻收工。
// ! 结果：指针刚好停在这个最后的 '\n' 前面。这个换行符被彻底遗留在缓冲区，
        它将成为下一次 scanf 函数调用读取到的“第一个字符”。

--------------------------------------------------------------------------------
终极记忆口诀：
--------------------------------------------------------------------------------
1. %d %f 不吃草（自动跳过所有空格、换行等空白字符）。
2. %c 吃草不挑食（连空格、换行都当成普通字符吃进去）。
3. 格式串里别写 \n（写了程序必定卡死等输入）。
4. 草没吃完会发臭（多余的换行留在缓冲区，随时坑死下一次读取）。
// ! 5. 想清空残留？ 用 while ((c = getchar()) != '\n' && c != EOF); 把缓冲区吸干。
================================================================================
*/

// >> 当读取整数时，scanf函数首先寻找正号或负号，然后读取数字，直到读到一个非数字时才停止。当要求读入浮点数时，scanf函数会寻找一个正号或负号(可选)
// >> 随后是一串数字(可能含有小数点)，再往后是一个指数(可选)。指数由字母e(或者字母E)、可选的符号，以及一个或多个数字构成。scanf函数%e,%f,%g可以互换

// ! 注意一个 C 语言允许的变态语法：
// 你输入 1e 会怎样？
// scanf 读完 1，看到 e，以为指数来了，准备吃指数。结果发现后面是回车（没有数字）。这时候，scanf 会把 e 吐回缓冲区，只把 1 存进变量里。 
// （因为指数必须是完整的，没数字的 e 不合法，它不认）。

// >> 当scanf函数遇到一个不可能属于当前项的字符时，它会把此字符"放回原处"，以便在扫描下一个输入项或者下一次调用scanf函数时再次接入。思考(公认有问题)4个数排列:
//      1-20.3-4.0e3¤
// 我们使用与以前一样的scanf函数调用:
//      scanf("%d%d%f%f", &i, &j, &x, &y);
// 下面列出了 scanf 函数处理这组新输入的方法:

// >> ● 转换说明 %d。第一个非空的输入字符是 1；因为整数可以以 1 开始，所以 scanf 函数接着读取下一个字符，即 -。
// scanf 函数识别出字符 - 不能出现在整数内，因此把 1 存入变量 i 中，而把字符 - 放回原处。

// >> ● 转换说明 %d。随后，scanf 函数读取字符 -、2、0 和 .（句点）。
// 因为整数不能包含小数点，所以 scanf 函数把 -20 存入变量 j 中，而把字符 . 放回原处。

// >> ● 转换说明 %f。接下来 scanf 函数读取字符 .、3 和 -。
