// >> 这些字符包括非打印的(控制)字符和对编译器有特殊含义的字符(如")。后面会提供完整的转义序列表，现在先看一组示例。
// >> 警报(响铃)符: \a
// >> 回退符: \b
// >> 换行符: \n
