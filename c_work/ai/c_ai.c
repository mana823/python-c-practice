/* ============================================================================
 * 【C语言自增自减（++ / --）底层完全指南】
 * ============================================================================
 * 
 * 一、 核心铁律：表达式的“值” 与 “副作用”
 * ----------------------------------------------------------------------------
 * 1. 表达式的值（Value）：这个算式最终交出的结果（用于参与外层运算或赋值）。
 * 2. 副作用（Side Effect）：在计算过程中，偷偷改变了内存中变量的实际数值。
 * 
 * 二、 前缀 (++i) vs 后缀 (i++)
 * ----------------------------------------------------------------------------
 * 【前缀 ++i】（如 ++i, --i）
 * - 动作：先发生副作用（内存里的 i 立刻 +1），再交出表达式的值。
 * - 结果：i 和表达式的值，都是更新后的“新值”。
 * - 结合性：右结合（与一元正负号相同）。
 * 
 * 【后缀 i++】（如 i++, i--）
 * - 动作：先交出表达式的值（当前旧值），随后发生副作用（内存里的 i 再 +1）。
 * - 结果：表达式的值是“旧值”，但 i 随后变成了“新值”。
 * - 结合性：左结合（优先级极高，甚至高于乘除号）。
 * 
 * 三、 经典求值推导（合法且无歧义）
 * ----------------------------------------------------------------------------
 * 场景：i = 1; j = 2; k = i++ + j++;
 * 执行步骤：
 * 1. 先取值：i++ 交出 1，j++ 交出 2。
 * 2. 算外层：k = 1 + 2 = 3。
 * 3. 副作用生效：i 变成 2，j 变成 3。
 * 结果：k=3, i=2, j=3。（此处绝对没有未定义行为，结果唯一确定）
 * 
 * 场景：i = 1; j = 2; k = ++i + j++;
 * 执行步骤：
 * 1. 前缀 i 先自增：i 变成 2，++i 交出 2。
 * 2. 后缀 j 先取值：j++ 交出 2。
 * 3. 算外层：k = 2 + 2 = 4。
 * 4. 后缀 j 副作用生效：j 变成 3。
 * 结果：k=4, i=2, j=3。
 * 
 * 四、 致命雷区：未定义行为（UB）
 * ----------------------------------------------------------------------------
 * C 语言标准只规定了“交值”和“自增”的顺序，并没有规定“自增”和“赋值/参数求值”的先后。
 * 因此，在【两个顺序点之间】（比如同一个表达式里），绝对不要对同一个变量多次修改！
 * 
 * ❌ 错误示范 1：i = i++;
 *    - 编译器可能先算右边的 i++ (交出1)，然后再赋值给 i (i=1)，最后副作用 (i=2)。
 *    - 也可能先副作用 (i=2)，再赋值 (i=2)，结果变成 2。
 *    - 结果不可控，不同编译器行为不同。
 * 
 * ❌ 错误示范 2：printf("%d %d", i++, i++);
 *    - 参数是从右往左求值还是从左往右？自增什么时候发生？
 *    - C 标准说：编译器自己看着办。你可能会看到 "1 2"、"2 1" 甚至直接崩溃。
 * 
 * 五、 [安防视角] 指针与自增的千层套路
 * ----------------------------------------------------------------------------
 * 1. *p++  等价于 *(p++) 
 *    - 动作：先取 p 指向的值，然后再让 p 指针向后移动一个单位。
 *    - 黑客场景：在遍历网络数据包时，常用于连续读取缓冲区数据。
 * 
 * 2. (*p)++ 
 *    - 动作：取出 p 指向的值，然后把那个内存里的值 +1。
 *    - 黑客场景：如果 p 指向的是系统的权限标志位，这个操作能悄悄篡改权限，而指针本身不动。
 * ============================================================================
 */

