/* %i 与 %d 的区别 */
// ? 转换说明%i也可以用于读写整数。%i和%d之间的区别: 
// >> 在printf格式串使用中，二者没有区别。
// >> 但是在scanf格式串中，%d只能与十进制(基数为10)形式整数相匹配，
// ! 而%i可以匹配用八进制(基数为8)、十进制或十六进制(基数为16)表示的整数。
// >> 如果输入的数有前缀0(如056)，那么%i会把它作为八进制数(7.1节)来处理;
// >> 如果输入的数有前缀0x或0X(如0x56)，那么%i会把它作为十六进制数(7.1节)来处理。
// >> 如果用户意外地将0放在数的开始处，那么用%i代替%d读取数可能会意想不到，所以建议坚持采用%d。

