/* ============================================================================
 * 【极客复盘：C语言标号、空语句与编译器的“前向引用”机制】
 * ============================================================================
 * 
 * * 1. 逻辑本质：
 *    - 标号（Label）：代码段里的一个物理坐标（门牌号），供 goto 跳转使用。
 *    - 语法铁律：标号必须依附于一条“语句”。如果后面没代码，必须用分号 ; 
 *      （空语句）垫底，否则编译器报语法错误（标号悬空）。
 *    - 前向引用：编译器允许 goto 往前跳（目标标号在后面），依靠的是“符号表”。
 * 
 * ? 2. 底层行为（编译器的两遍扫描）：
 *    - 第一遍（建账本）：从上往下扫描。遇到变量声明、函数、标号，立刻记入
 *      “符号表（Symbol Table）”。
 *    - 遇到 goto：如果 goto 的目标标号还没出现（前向引用），编译器不会立刻崩溃，
 *      而是记下一张“欠条（未解决的外部引用）”，继续往下扫。
 *    - 对账清算：扫到函数末尾（右大括号），如果符号表里还没找到那个标号，
 *      立刻报错（Label used but not defined）。找到则销账。
 *    - 汇编层：编译完成后，标号名字灰飞烟灭，全部被替换成相对于当前指令的
 *      地址偏移量（Offset），CPU 依靠 RIP + Offset 实现物理跳转。
 * 
 * ! 3. 工程/安全铁律：
 *    - 同一函数限制：标号拥有独立的作用域（生命周期仅在当前函数）。跨函数 goto 
 *      会导致符号表断裂，绝对禁止。
 *    - 标号防呆：写 goto cleanup; 统一释放资源时，如果 cleanup 后面没代码了，
 *      必须写 cleanup: ; 垫底，满足编译器的强迫症。
 * 
 * ! 4. 坑与反例：
 *    - 语法坑：end: }（报错） vs end: ; }（合法）。
 *    - 优化坑：在 -O2 优化下，编译器发现某段代码永远跳不到，或者标号没有
 *      任何 goto 指向它（死代码），会直接把这段代码连同标号一起删掉。
 * 
 * ! 5. [安防微架构视角（逆向与PWN）]：
 *    - 逆向分析：你拿到的 .exe 文件里，绝对没有 my_label 这种人类可读的符号，
 *      只有 0x401000 这种裸地址。
 *    - ROP (返回导向编程)：黑客在打栈溢出时，由于现代系统有 ASLR（地址随机化），
 *      黑客无法写死绝对地址。黑客会寻找程序里的 Gadget（指令片段），比如
 *      pop rdi; ret;。这里的 Gadget 本质上就是黑客强行拼凑出的“底层标号”。
 *    - 为什么黑客爱空语句 (NOP)？：在 Shellcode 前面狂塞 NOP (0x90)，形成 
 *      NOP Sled（雪橇）。CPU 只要跳进这个区域，就会一路顺着 NOP 滑到真正的
 *      恶意代码里，极大提高了攻击命中率。
 * ============================================================================ */


