/* ============================================================================
 * 【极客复盘：for 与 while 中 continue 的生死之别与底层跳转】
 * ============================================================================
 * 
 * 1. 逻辑本质与物理落点：
 *    - for 循环：循环控制的三要素（初始化、条件、更新）全在括号内。
 *      continue 的跳转目标是【循环体末尾】，到达末尾后，紧接着执行的是
 *      【第三个表达式（自增/自减）】。
 *    - while 循环：只有条件判断。continue 的跳转目标是【循环体末尾 }】。
 *      跨过末尾大括号后，自然顺延回到【while 的条件判断处】。
 * 
 * 2. 底层行为（汇编与 goto 视角）：
 *    - continue 在底层就是一条无条件的 JMP 指令。
 *    - 在 for 中，JMP 的目标地址是自增代码块的起始位置（先执行 i++，再 cmp 判断）。
 *    - 在 while 中，JMP 的目标地址是循环体末尾的空语句/结束地址（直接跳过循环体
 *      后半段，顺着物理流向回到 cmp 比较指令的位置）。
 *    - [核心结论]：for 循环中的 continue 必定会执行自增；而 while 中的
 *      continue 极容易跳过更新逻辑，导致变量永远不变。
 * 
 * 3. 工程/安全铁律：
 *    - for 循环天然免疫“状态未推进死循环”：哪怕满屏幕写 continue，
 *      底层也会帮你把自增跑完。
 *    - while 循环必须防呆：若使用 continue，更新变量的代码（如 i++）必须
 *      写在 continue 之前，或者在 while 条件里完成更新（如 while(i++ < 10)）。
 * 
 * 4. 坑与反例（死循环现场）：
 *    - C 语言 while 灾难写法：
 *      int i = 0;
 *      while (i < 10) {
 *          if (i == 5) { continue; } // 当 i=5 时触发，跳到 }，然后回到 i < 10 判断
 *          i++;                      // 永远被跳过，i 永远是 5，死循环爆发
 *      }
 *    - [安防视角]：如果这种代码出现在网络服务器处理数据包的逻辑中，
 *      黑客只需构造一个触发 continue 的畸形数据包（如 i=5 的状态），
 *      就能让服务器瞬间卡死在死循环中，CPU 占用 100%，引发 DoS（拒绝服务）攻击。
 * 
 * 5. [跨语言对比（Python）]：
 *    - Python 的 for 循环本质是基于迭代器（Iterator）。
 *    - 在 Python 中执行 continue，解释器会自动调用迭代器的 __next__() 
 *      获取下一个元素。因此 Python 的 for + continue 不会因状态未推进而死循环。
 *    - 但如果是 Python 的 while 循环，逻辑与 C 语言一模一样，continue 前若没
 *      修改条件变量，照样死循环。
 * ============================================================================
 */


