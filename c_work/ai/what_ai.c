// ? if(表达式)只关心表达式最后的值是不是非0，所以if(1)合法，很多也一样

// >> 有四种常见在复合语句多种缩进和放置花括号的风格，因人而异，选自己喜欢的

// ? 如果int型和float型的值混合在一个条件表达式中时，表达式的类型为float型。如果最后判断是选择那个int型，那么那个int型转换为float型之后就是表达式的值。
// >> 如若没有规定和限制永远向高精度转移。

// ! ============================================================================
// ! 【底层暴击：“超大 int 转 float 尾数不够”的真相】
// ! ============================================================================
// 1. 物理限制：
//    - int (32位)：拥有 31 位精度，能精确表示到 2147483647。
//    - float (32位)：尾数只有 23 位（加隐藏位共 24 位精度）。
// 
// 2. 临界点：超过 2^24 (16,777,216) 后，float 无法精确表示每一个整数。
//    此时进行强制转换，底层会发生“四舍五入”截断，导致数值发生偏移。
//    例如：int 类型的 16777217，转成 float 会变成 16777216.0。
// 
// ! 3. [安防暴击]：在金融、加密货币等对精度要求极高的系统中，大整数与浮点数
//    的隐式转换会引发致命的“精度丢失漏洞”。永远不要用 float 处理精确的金额。
// ! ============================================================================


