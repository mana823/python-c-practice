// ? C语言没有指数运算符，如果想计算非整数次幂，可以调用pow函数(23.3节)

// ? 想把%运算符用于浮点数，但是程序无法通过编译，这种情况下可以试试fmod函数。

// >> C89和C99都要保证 (a / b) * b + a % b 的结果总是等于a(只要a / b 的只是可以表示的)问题是C89可能有两种可能:
// >> -9 / 7 为-1(-2)   -9 % 7 为-2(5)       <--   (-9 / 7) * 7 + -9 % 7  的值是-1 * 7 + -2 = -9(-2 * 7 + 5 = -9)  C99出现，大多数CPU将除法趋零截尾。

// ? C语言"值"就是"右值"，都是指"表达式的值"只有左值才可以放在运算符的左侧，否则它就是一个值，或者说右值。当然C语言不需要这个概念，这是C++才使用的概念

// ! 计算 v += e只会求一次v的值，而计算v = v + e会求两次v的值。在后一种情况下，对v值可能引起的任何副作用也可能会出现两次:
// !      a[i++] += 2;
// !      a[i++] = a[i++] + 2;     <--   用 = 代替 +=   i的值在别处被修改和使用了，不仅语句是未定义，而且还自增了两次

// >> 对于现代编译器，使用++和--不会使编译后的程序变得更短小更快，继续普及这些运算符是由于它们简洁和便利

// >> 自增和自减运算也可以用于浮点数，但实际应用中极少采用自增和自减运算符处理float型变量。

// ? 对于何时执行自增和自减的操作，C语言标准引入了"序列点"的概念，并且指出"应该在前一个序列点和后一个序列点之间对存储的操作数的值进行更新"。
// ? 在C语言有多个不同类型的的序列点，表达式语句的末尾是其中一种。在表达式语句末尾，该语句所有自增自减必须完成，否则不能执行下一条语句。
// ? 后面章节(逻辑与、逻辑或、条件和逗号)对序列点也有影响。函数调用也是如此:在函数调用执行之前，所有的实际参数必须全部算出来。

// >>      i = 1;   <--   把1赋给i。整个表达式的值是1，然后值被丢掉了。首要目的是改变i的值，丢掉没什么大的损失

/* ============================================================================
 * 【C语言回执单（表达式值）的四大保留场景】
 * ============================================================================
 * 只要表达式没有直接被分号 ; 终结，它就会作为“子表达式”将值传递出去：
 * 
 * 1. 赋值给其他变量（链式赋值）： a = b = 1;
 * 2. 作为条件判断： if (i = 1)  （安防高危：误把 == 写成 =，导致条件永真）
 * 3. 作为函数参数： printf("%d", (i = 1));
 * 4. 参与外层运算： x = (i = 1) + 10;
 * 
 * [注]：如果没有副作用且直接跟分号（如 a + b;），编译器优化时甚至会连算都不算。
 * ============================================================================ */



