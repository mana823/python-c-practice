/* ============================================================================
 * 【C语言底层终极笔记：switch 语句的物理实现与漏洞利用】
 * ============================================================================
 * 核心口诀：密集建表瞬移，稀疏二分排查；break只是局部跳转，漏写直接穿透。
 * 
 * ============================================================================
 * 一、 底层实现机制（两种模式，取决于编译器的优化）
 * ============================================================================
 * 1. 跳转表（Jump Table）模式 —— O(1) 瞬间寻址：
 *    - 触发条件：case 的值是【连续】或【密集】的（如 case 1, 2, 3...）。
 *    - 物理本质：它不是元组，而是编译器在只读数据段（.rodata）建的一个【指针数组】。
 *    - 数组元素：存放的是每一个 case 代码块的【门牌号（内存地址）】。
 *    - 寻址公式：目标地址 = 表基地址 + (变量值 - 最小case值) * 指针大小(64位系统8字节)。
 *    - 编译器抠门优化：通过减去最小 case 值，让稀疏的 case 也能变成连续下标，避免数组空洞浪费。
 *    - 优势：无论 case 有多少个，一步数学运算瞬间定位，速度极快（相当于查字典）。
 * 
 * 2. 逐级比较/二分查找模式 —— O(n) 或 O(log n)：
 *    - 触发条件：case 的值极其【稀疏】（如 case 1, case 100, case 99999）。
 *    - 物理动作：退回为 if-else if 的逻辑，生成连续的 CMP 和 JMP 指令。
 * 
 * ============================================================================
 * 二、 致命陷阱：Fall-through（穿透）与 break 的真相
 * ============================================================================
 * 1. case 的本质：
 *    - case 并不是代码块的分隔符，它仅仅是内存里的一个【标签（Label）】。
 * 
 * 2. 为什么会发生穿透？
 *    - 编译器是【从左到右】单向扫描的。遇到 break，就吐一条 JMP（无条件跳转）
 *      指令；如果没写 break，编译器绝不会多管闲事生成 JMP。
 *    - CPU 顺着物理内存执行完当前 case 的代码后，因为没有 JMP 拦截，会顺理成章
 *      地“滑进”下一个 case 的代码块，导致后面的代码被连带执行。
 * 
 * 3. break 的作用域（局部暴君）：
 *    - break 绝不是作用全局的。它只作用于【离它最近的那一层】 switch 或循环。
 *    - 在嵌套结构中（如 for 循环里套 switch），switch 里的 break 只能跳出 switch，
 *      外层的 for 循环依然会继续跑。
 * 
 * ============================================================================
 * 三、 [安防暴击]：黑客如何利用 switch 搞破坏？
 * ============================================================================
 * 1. 逻辑穿透越权（漏写 break）：
 *    - 程序员在普通用户 case (Level 1) 忘写 break，黑客利用低权限账号进入，
 *      执行流顺延滑落进管理员 case (Level 9)，直接触发提权代码。
 * 
 * 2. 控制流劫持（篡改跳转表/越界读）：
 *    - 如果没写 default 且未校验变量范围，极端数值（如超大数或负数）会导致数组越界读。
 *    - 若黑客配合其他内存漏洞（如栈溢出），篡改了跳转表里的真实地址，CPU 就会
 *      直接跳进黑客构造的 Shellcode（恶意代码）里。
 * 
 * 3. 必须使用 default 兜底：
 *    - 如果变量值不匹配任何 case，程序会直接跳过 switch。在权限校验中，必须用
 *      default 抛出错误或拒绝访问，防止静默放行。
 * ============================================================================
 */

