 /* ============================================================================
 * 【底层终极笔记：从字符表象到 CPU 执行的全链路真相】
 * ============================================================================
 * 核心思想：人类看到的是字符，网线传输的是电信号（二进制），CPU 执行的是指令。
 * 中间的每一次“转换/解码”，都是黑客发动攻击的温床。
 * 
 * ============================================================================
 * 一、 物理真相：引号与二进制的“千层套路”（表象 vs 本质）
 * ============================================================================
 * 1. 物理层（无差别）：
 *    - 字符 '  、URL 编码 %27 、十六进制 0x27，在经过网卡发送时，
 *      跑的全是同一串物理电信号（00100111）。哪怕上帝来了也看不出区别。
 * 
 * 2. 软件层（千变万化）：
 *    - 为什么黑客要搞出这么多花样？为了“欺骗中间的解码器（WAF、服务器）”。
 *    - 发纯字符 '  ：容易暴露特征，被 WAF 一眼拦截。
 *    - 发 %27      ：URL 编码。骗过不解码的初级 WAF，后端自动解码成 '。
 *    - 发 \x27     ：纯二进制。直接通过 Socket 穿透协议层，绕过只看文本特征的防御。
 * 
 * 3. [安防暴击：宽字节注入]
 *    - 黑客输入 %bf%27。后端转义为 %bf\ (0xbf 0x5c 0x27)。
 *    - 底层解码器（GBK）发现 0xbf > 128，触发多字节判定，吃掉 0x5c（反斜杠）。
 *    - 单引号 (0x27) 暴露，SQL 注入成功。
 * 
 * ============================================================================
 * 二、 编译与执行流水线：从源码到 CPU 寄存器
 * ============================================================================
 * 1. 编译期（编码写入，固化字节）：
 *    - 源码解码：编译器用 UTF-8 读源码，把 "你" 还原成 Unicode 编号。
 *    - 编译转码：根据目标系统执行字符集（如 GBK），把编号变成物理字节。
 *    - 固化存储：把转好的字节，连同 \0，写死进可执行文件的 .rodata 段。
 * 
 * 2. 运行期（取指 Fetch，带入寄存器）：
 *    - CPU 顺着地址总线，把内存（RAM）里的指令和数据，
 *      按 64 位（8字节）的口径，一把抓进内部寄存器（如 RAX、RDI）。
 * 
 * 3. CPU 解码（Decode，定生死）：
 *    - 译码器识别这堆 0 和 1：这是指令？还是数据？还是地址？
 *    - 如果数据（如输入字符）被错误地当成了指令去解码，就会触发
 *      【代码执行漏洞/缓冲区溢出（Shellcode）】。
 *    - 如果写入的编码规则（UTF-8）和解码规则（GBK）不一致，就会乱码或引发注入。
 * 
 * ============================================================================
 * 三、 终极融合口诀（极客防身术）
 * ============================================================================
 * 1. 万物皆比特：字符、引号、指令，在物理层全是一串电信号。
 * 2. 变形皆为骗：所有编码变形（%27, \x27）都是为了骗过中间层的解析器。
 * 3. 解码即执行：数据如果被错误解码（当成指令），系统就会沦为肉鸡。
 * 4. 边界即漏洞：跨语言、跨系统、跨协议时的“编码/解码不一致”，就是黑客的提款机。
 * ============================================================================
 */


