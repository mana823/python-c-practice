/* ============================================================================
 * 【C语言格式转换符 (Format Specifiers) 与 底层踩坑漏洞 全景笔记】
 * ============================================================================
 * 
 * [核心心法]：格式符是 printf/scanf 的“翻译图纸”。
 * printf 负责按图纸把内存的二进制“解码”输出；
 * scanf 负责按图纸把输入的字符“编码”硬塞进内存地址。
 * 图纸给错，轻则数据乱码，重则内存越界、程序崩溃。
 * ============================================================================
 */

/* ----------------------------------------------------------------------------
 * 一、 整数类格式符（Integer）
 * ----------------------------------------------------------------------------
 * 【%d】 (Decimal)
 *   - 含义：有符号十进制整数（针对 int，4字节）。
 *   - 坑点：若用 %d 强行打印 float，会把浮点数的 IEEE 754 位模式当做补码整数解读，
 *           输出毫无意义的巨大垃圾值（如 10.5 打印出 1093140480）。
 * 
 * 【%u】 (Unsigned)
 *   - 含义：无符号十进制整数。
 *   - 坑点（安防高危）：若把 -1 (int) 用 %u 打印，最高位的符号位 1 会被当做数值，
 *                       输出 42亿多。这是“逻辑绕过漏洞”的重灾区（黑客输入-1绕过校验）。
 * 
 * 【%x / %X】 (Hexadecimal)
 *   - 含义：十六进制整数（小写/大写字母）。
 *   - 用途（安防神技）：查内存地址、逆向分析、看二进制文件、抓包全靠它。
 * 
 * 【%ld / %lld】
 *   - 含义：长整型 / 超长整型（8字节）。
 *   - 坑点：若用 %d 打印 long 类型（8字节），会截断数据产生乱码；反之则会越界读取。
 * ----------------------------------------------------------------------------
 */

/* ----------------------------------------------------------------------------
 * 二、 浮点类格式符（Floating-point）
 * ----------------------------------------------------------------------------
 * 【%f】
 *   - 含义：定点十进制浮点数（默认保留6位小数）。
 *   - 差异：在 printf 中，float 和 double 都可以用 %f。
 *   - 坑点（安防高危）：在 scanf 中，如果给 float 变量用了 %lf，scanf 会强行写入
 *                       8个字节，导致覆盖相邻内存（栈溢出漏洞）。
 * 
 * 【%lf】 (Long Float)
 *   - 含义：双精度浮点数（针对 double，8字节）。
 *   - 铁律：在 scanf 中，读 float 必须用 %f，读 double 必须用 %lf。绝不能混用！
 * 
 * 【%e / %E】
 *   - 含义：科学计数法（如 1.23e+05）。
 * 
 * 【%g / %G】
 *   - 含义：智能选择 %f 或 %e，自动去掉尾随的零（基于有效数字，非小数位数）。
 * ----------------------------------------------------------------------------
 */

/* ----------------------------------------------------------------------------
 * 三、 字符与字符串类格式符（Char & String）
 * ----------------------------------------------------------------------------
 * 【%c】
 *   - 含义：单个字符（针对 char，1字节）。
 *   - 底层动作：绝不跳过任何前导空白（空格、回车）。
 *   - 坑点一：若用 %c 打印 int（如 321），只会截取最低1字节（65），输出 ASCII 字符 'A'。
 *   - 坑点二：scanf("%c") 会吃掉缓冲区残留的换行符 \n。解法：用 " %c"（加空格）。
 * 
 * 【%s】 (String)
 *   - 含义：字符串（针对 char 数组/指针）。
 *   - 底层动作：从给定地址开始读，直到遇到 \0 为止。
 *   - 坑点一（极危）：若用 %s 打印 int，会把整数当做内存地址去找字符串，极易引发段错误（程序崩溃）。
 *   - 坑点二（极危）：scanf("%s") 不检查边界，若输入超长字符串，直接导致【缓冲区溢出】。
 * 
 * 【%*d / %*c / %*s】 (赋值抑制符)
 *   - 含义：读入数据但丢弃，不赋值给任何变量。
 *   - 坑点：带 * 的格式符不需要提供变量地址，若多传了地址，会导致后续参数全盘错位！
 * ----------------------------------------------------------------------------
 */

/* ----------------------------------------------------------------------------
 * 四、 指针与特殊格式符（高级 / 黑客必看）
 * ----------------------------------------------------------------------------
 * 【%p】 (Pointer)
 *   - 含义：打印内存地址（以十六进制形式）。搞底层调试、漏洞分析必用。
 * 
 * 【%n】
 *   - 含义：把已经打印的字符数量，写入指定的整型指针变量中。
 *   - 坑点（格式化字符串漏洞的万恶之源）：
 *          正常代码：printf("abc%n", &num); // num 会变成 3
 *          恶意代码：printf("%s%s%s%s%n", ...); // 黑客利用它强行向内存地址写入数据（实现任意地址写）。
 * ----------------------------------------------------------------------------
 */

/* ----------------------------------------------------------------------------
 * 【终极安防避坑铁律】：
 * 1. 严格对齐：printf/scanf 的格式符必须与变量类型100%匹配。
 * 2. 永远不要用 %d 去打 float，也不要用 %s 去打 int。
 * 3. 传参时，scanf 必须传地址（&），printf 必须传值（不加&）。
 * 4. 开编译器警告（-Wall -Wformat），它能在编译阶段抓住 90% 的格式错配灾难。
 * ============================================================================
 */




/* ============================================================================
 * 【C语言格式转换符：底层动作与坑点速查表】
 * ============================================================================
 * 核心前提：printf/scanf 不看变量类型，只看格式符去内存或寄存器里“硬读/硬写”。
 * ============================================================================
 */

/* ----------------------------------------------------------------------------
 * 1. %d (十进制有符号整数)
 * ----------------------------------------------------------------------------
 * [底层动作]：
 *   printf：从寄存器/栈取 4 字节，按补码解析，除以 10 转 ASCII 码输出。
 *   scanf：跳过前导空白，读数字转补码，强行写入 4 字节地址。
 * [坑点]：用 %d 打印 float，会把浮点数的 IEEE 754 位模式当整数解析，输出垃圾值。
 * ---------------------------------------------------------------------------- */

/* ----------------------------------------------------------------------------
 * 2. %u (十进制无符号整数)
 * ----------------------------------------------------------------------------
 * [底层动作]：读取 4 字节，无视最高符号位，全部当正数计算输出。
 * [坑点]：若传入 -1 (int)，底层 32 个 1 会被解析为 4294967295。常导致权限校验绕过。
 * ---------------------------------------------------------------------------- */

/* ----------------------------------------------------------------------------
 * 3. %x / %X (十六进制整数)
 * ----------------------------------------------------------------------------
 * [底层动作]：读取 4 字节，每 4 个二进制位转换为 1 个十六进制字符输出。
 * [坑点]：格式化字符串漏洞中，常配合 %x 批量泄露栈内存或寄存器里的密码/地址。
 * ---------------------------------------------------------------------------- */

/* ----------------------------------------------------------------------------
 * 4. %f / %lf (浮点数)
 * ----------------------------------------------------------------------------
 * [底层动作]：
 *   printf：float 自动提升为 8 字节 double。从 XMM 寄存器取值，按 IEEE 754 逆算十进制。
 *   scanf：%f 读入转 4 字节浮点位强写地址；%lf 读入转 8 字节浮点位强写地址。
 * [坑点]：
 *   1. scanf 用 %lf 读 float（只有4字节），会导致 8 字节越界写入（栈溢出）。
 *   2. 浮点数存在二进制精度丢失，不可用于金额比对。
 * ---------------------------------------------------------------------------- */

/* ----------------------------------------------------------------------------
 * 5. %c (单字符)
 * ----------------------------------------------------------------------------
 * [底层动作]：
 *   printf：取 4 字节参数，砍掉高 3 字节，保留最低 1 字节查 ASCII 表输出。
 *   scanf：从缓冲区死板提取 1 字节，强行写入地址。
 * [坑点]：
 *   1. 用 %c 打印 321，截断后只剩 65 (即 'A')。
 *   2. scanf("%c") 绝不跳过空白，会吃掉上一次残留的换行符 \n。
 * ---------------------------------------------------------------------------- */

/* ----------------------------------------------------------------------------
 * 6. %s (字符串)
 * ----------------------------------------------------------------------------
 * [底层动作]：
 *   printf：把参数当内存地址，一字节一字节往后读，直到遇到 \0 结束。
 *   scanf：读入字符直到遇到空白，在末尾强行补 \0，不检查目标空间大小。
 * [坑点]：
 *   1. 用 %s 打印整数（如 65），会把 65 当地址去找字符串，直接触发段错误。
 *   2. scanf("%s") 是经典的“缓冲区溢出”元凶（输入超长数据覆盖内存）。
 * ---------------------------------------------------------------------------- */

/* ----------------------------------------------------------------------------
 * 7. %p (指针/内存地址)
 * ----------------------------------------------------------------------------
 * [底层动作]：提取 8 字节（64位），按十六进制加 0x 前缀输出。
 * [坑点]：程序泄露真实内存地址，会破坏 ASLR（地址随机化）防御，便于黑客精准攻击。
 * ---------------------------------------------------------------------------- */

/* ----------------------------------------------------------------------------
 * 8. %* (赋值抑制符)
 * ----------------------------------------------------------------------------
 * [底层动作]：scanf 读入数据后直接丢弃，不执行写内存操作。
 * [坑点]：%* 不消耗参数。如果多传了地址，会导致后续所有变量读取/赋值参数错位。
 * ---------------------------------------------------------------------------- */

/* ----------------------------------------------------------------------------
 * 9. %n (已输出字符数写入)
 * ----------------------------------------------------------------------------
 * [底层动作]：printf 统计当前已打印的字符数量，提取参数指针，将数字强行写入该地址。
 * [坑点]：极度危险。若控制格式串，可用 %n 向任意内存地址写入任意数值（格式化字符串漏洞核心）。
 * ---------------------------------------------------------------------------- */



 /* ============================================================================
 * 【C语言底层暴击：字符整型的等价性 & m.p 格式控制的真相】
 * ============================================================================
 * 
 * ============================================================================
 * 一、 为什么“字符与整型随便转”？（底层动作）
 * ============================================================================
 * 1. 底层真相：在 C 语言（以及计算机底层）看来，根本不存在“字符”。
 *    'A' 的真身就是整数 65，'0' 的真身就是整数 48。它们都以 1 个字节的二进制形式存在。
 * 
 * 2. 随便转的本质：
 *    - char 转 int：把 1 字节扩展成 4 字节（高位补 0 或符号位）。
 *    - int 转 char：直接把高 3 字节砍掉，只保留最低的 1 字节（发生截断）。
 * 
 * 3. 黑客视角的坑：
 *    - int a = 321; printf("%c", a); // 321 的二进制被截断，只留最后 8 位（65），打印出 'A'。
 *    - 很多防火墙只检查 "A" 字符串，黑客故意传数字 321 进去，底层截断成 'A'，绕过检测！
 * ============================================================================
 * 
 * ============================================================================
 * 二、 m.p 到底对谁生效？（纠正你的误区）
 * ============================================================================
 * 你说“m.p 也对字符串生效”，这里必须精确纠正：只有 p（精度）对字符串生效，m（宽度）对所有东西生效。
 * 并且，p 对不同类型的意思完全不一样！
 * 
 * 【m（最小宽度）—— 对所有类型生效】
 * - 动作：如果输出内容长度小于 m，就在左边（或右边，看有没有 - 号）补空格。
 * - 例子：printf("%5s", "Cat"); // 输出 "  Cat"
 * 
 * 【p（精度）—— 对不同类型玩“双标”】
 * 1. 对浮点数（%f/%e/%g）：
 *    - 动作：控制【小数点后保留几位】。超出部分四舍五入。
 *    - 例子：printf("%.2f", 3.14159); // 3.14
 * 
 * 2. 对字符串（%s）：
 *    - 动作：控制【最多输出几个字符】。绝不四舍五入，多出来的直接砍掉（截断）。
 *    - 例子：printf("%.3s", "Hello"); // 输出 "Hel"，剩下的 "lo" 被无情砍掉。
 * 
 * 3. 对整数（%d）：
 *    - 动作：控制【最少输出几位数字】。不够的话前面补 0。
 *    - 例子：printf("%.5d", 42); // 输出 "00042"
 * ============================================================================
 */


 /* ============================================================================
 * 【底层深渊：字符编码与多字节限制】
 * ============================================================================
 * 1. 基础：ASCII 码用 1 个字节（0-255）表示英文字符，完美匹配。
 * 2. 扩展：超过 1 字节的字符（如中文），必须用“多字节”拼凑。
 *    - GBK：通常 2 个字节表示一个汉字。
 *    - UTF-8：变长编码（汉字 3 字节，Emoji 4 字节）。
 * 3. 查找方式：程序读到大于 128 的字节，会触发“多字节判定”，继续往后吃字节。
 * 4. [安防视角]：黑客故意输入多字节字符（如 %bf%27），让系统误以为是一个宽字符，
 *    从而“吃掉”安全字符（如单引号），引发【宽字节注入】漏洞。
 * ============================================================================
 */



/* ============================================================================
 * 【C语言底层真相：未初始化变量的“垃圾值”】
 * ============================================================================
 * 1. 内存不清零：声明变量（如 int a;）只是分配内存，C 语言绝不自动清零。
 * 2. 继承遗产：如果 scanf 罢工未给变量赋值，变量将保留该内存地址上的历史残留数据。
 * 3. 能正常打印：printf 读内存不会报错，只要地址合法，它会将残留的 0 和 1 当成数值打印。
 * 4. 【高危漏洞】：黑客常利用未初始化变量里的“随机垃圾值”碰运气（如碰巧等于管理员权限位），
 *                  从而绕过安全检查。
 * 5. 【防御法则】：声明变量必赋值（int a = 0;），且必须校验 scanf 返回值。
 * ============================================================================
 */


// · printf 是“读”：你往里传参时，编译器会偷偷帮你整齐划一（%f全变成 8 字节），所以 %f 和 %lf 在 printf 里没区别。
// · scanf 是“写”：你需要传地址（指针），编译器不会帮你做任何大小提升。你给 %f，它就是个无情的 4 字节压路机；你给 %lf，它才是 8 字节压路机。
