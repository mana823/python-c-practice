/* ============================================================================
 * 【C语言终极笔记：运算符优先级与表达式底层求值逻辑】
 * ============================================================================
 * 
 * [核心心法]：
 * 先弄出值 -> 再比较 -> 逻辑运算 -> 赋值最后赋 -> 逗号垫底。
 * （说明：计算机必须把算式“降维”算出一个完整的值，才能进行下一步换位和判断）
 * 
 * ============================================================================
 * 【第一梯队：最高优先级】（结合性：多为从左往右）
 * ============================================================================
 * 1. 破局者（强行插队）：()  圆括号、[] 数组下标
 * 2. 结构体访问：. 、 ->
 * 3. 单目运算符（从右往左算）：! (非)、~ (按位取反)、++、--、+ (正)、- (负)、* (解引用)、& (取地址)、sizeof
 * 
 * ============================================================================
 * 【第二梯队：算术与移位】（结合性：从左往右）
 * ============================================================================
 * 1. 乘除取余：* 、 / 、 %
 * 2. 加减：+ 、 -
 * 3. 移位：<< (左移) 、 >> (右移)
 * 【底层动作】：在这一步，算式开始真正计算，逐渐降解为确定的值。
 * 
 * ============================================================================
 * 【第三梯队：关系比较】（结合性：从左往右）
 * ============================================================================
 * 1. 大小关系：< 、 <= 、 > 、 >=
 * 2. 相等判断：== 、 !=
 * 【底层动作】：必须等第二梯队的值全算完，才能在这里进行比较，结果只能是 1(真) 或 0(假)。
 * 
 * ============================================================================
 * 【第四梯队：逻辑与位运算】（结合性：从左往右）
 * ============================================================================
 * 1. 位运算：& (按位与) 、 ^ (按位异或) 、 | (按位或)
 * 2. 逻辑运算：&& (逻辑与) 、 || (逻辑或)
 * 【安防防坑】：&& 和 || 具有“短路求值”特性。左边能决定结果，右边就不执行。
 *              黑客常利用此特性，将核心校验函数放在右侧，从而绕过检查。
 * 
 * ============================================================================
 * 【第五梯队：条件运算】（结合性：从右往左）
 * ============================================================================
 * 1. 三元运算符：? :  （例如：a > b ? a : b）
 * 
 * ============================================================================
 * 【第六梯队：赋值运算】（结合性：从右往左）
 * ============================================================================
 * 1. 基本赋值：=
 * 2. 复合赋值：+= 、 -= 、 *= 、 /= 、 %= 、 <<= 、 >>= 、 &= 、 ^= 、 |=
 * 【底层动作】：赋值是终点站。把右边全算完的“完整值”，塞进左边的内存地址中。
 * 【致命陷阱】：不要把 == (判断相等) 写成 = (赋值)，编译器可能不报错，但逻辑全错。
 * 
 * ============================================================================
 * 【第七梯队：最低优先级——破局者二】（结合性：从左往右）
 * ============================================================================
 * 1. 逗号：,
 * 【本质】：隔断符。在表达式中充当“弱化版括号”，把多个独立动作打包串成流水线。
 * 【规则】：从左往右依次执行，但整个表达式的最终结果，只取【最右边】那个值。
 * 
 * ============================================================================
 * 【安防铁律】：永远不要迷信自己的记忆力去排优先级。遇到复杂逻辑，直接用 () 
 * 把顺序“焊死”，既能防漏洞，又能防逆向分析时自己看不懂自己的代码。
 * ============================================================================
 */



 /* ============================================================================
 * 【C语言核心笔记：右结合运算符 (Right-to-Left Associativity)】
 * ============================================================================
 * 
 * [核心概念]：
 * 当同一个表达式中出现多个【同级】的右结合运算符时，编译器会从最右边开始计算，
 * 然后把算出的“值”层层向左传递。
 * 
 * ============================================================================
 * 【第一类：赋值运算符（重灾区）】
 * ============================================================================
 * 包含：= 、 += 、 -= 、 *= 、 /= 、 %= 、 <<= 、 >>= 、 &= 、 ^= 、 |=
 * 
 * 1. 底层动作解析：
 *    代码：a = b = c = 10;
 *    结合性：从右向左。等价于 a = (b = (c = 10));
 *    - 第一步：把 10 塞进 c，表达式 (c=10) 的结果为 10。
 *    - 第二步：把 10 塞进 b，表达式 (b=10) 的结果为 10。
 *    - 第三步：把 10 塞进 a。
 * 
 * 2. [致命坑点]：
 *    - 连续赋值时，不能带类型声明（如 int a = b = 10; 会报错，因为从左到右扫描时 b 未声明）。
 *    - 如果混合了复合赋值，例如：a += b *= 2; 等价于 a += (b *= 2);（先让 b 乘 2，再让 a 加），极易算错。
 * ============================================================================
 * 
 * ============================================================================
 * 【第二类：单目运算符（从右往左结合）】
 * ============================================================================
 * 包含：! (非) 、 ~ (按位取反) 、 ++ 、 -- 、 + (正) 、 - (负) 、 * (解引用) 、 & (取地址) 、 sizeof 、 (type)强制转换
 * 
 * 1. 底层动作解析：
 *    代码：- - a; (注意中间有空格) 等价于 -(-a)。
 *    代码：* & a; 等价于 *( &a );（先取 a 的地址，再顺着地址去取值）。
 * 
 * 2. [致命坑点与安防视角]：
 *    - 指针叠加：**ptr 表示指向指针的指针。如果少写了层级，会引发内存越界或段错误。
 *    - 前置/后置混用：*p++ 等价于 *(p++)（先取 p 指向的值，再让 p 指针地址加1）。
 *      这在对字符串或数组进行黑客Payload处理时经常用，一旦搞反，就会读到内存里的脏数据。
 * ============================================================================
 * 
 * ============================================================================
 * 【第三类：条件（三目）运算符】
 * ============================================================================
 * 包含：? : (C语言唯一的单目运算符，哦不，是三目运算符)
 * 
 * 1. 底层动作解析：
 *    代码：a > b ? a : b > c ? b : c;
 *    结合性：从右向左。等价于 a > b ? a : (b > c ? b : c);
 *    先算最右边的嵌套条件，再逐步向左返回结果。
 * 
 * 2. [致命坑点]：
 *    嵌套三目运算符非常容易把逻辑绕晕，导致“逻辑绕过”漏洞。
 *    黑客经常利用复杂的嵌套，让程序走不到正确的边界校验分支。
 * ============================================================================
 */

/* ============================================================================
 * 【安防避坑终极铁律】
 * 即使你背下了所有的右结合规则，人脑在解析长代码时依然会出错。
 * 安全领域的底线操作：
 * 1. 遇到多级赋值：拆成多行写，别装逼。
 * 2. 遇到单目运算符叠加：强制加圆括号，如 (*(&a))，( -( -a ))。
 * 3. 遇到嵌套三目：直接换成 if-else，可读性不仅是给同事看的，是防系统崩溃的。
 * ============================================================================
 */


