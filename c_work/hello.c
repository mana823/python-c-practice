/* ============================================================================
 * 【C语言程序编译产物全解剖笔记】
 * ============================================================================
 * 
 * 一、 编译四部曲与文件流转
 * ----------------------------------------------------------------------------
 * 源文件(.c) --[gcc -E]--> 预处理文件(.i) --[gcc -S]--> 汇编文件(.s) 
 *            --[gcc -c]--> 目标文件(.o) --[gcc]--> 可执行文件(ELF/EXE)
 * 
 * 
 * 二、 各文件详细解剖
 * ----------------------------------------------------------------------------
 * 
 * 1. 源文件 (.c)
 *    - 内容：程序员手写的 C 语言高级代码。
 *    - 本质：纯文本。
 * 
 * 2. 预处理文件 (.i)
 *    - 生成命令：gcc -E test.c -o test.i
 *    - 内容：将所有的 #include 头文件内容拷贝进来，展开所有的 #define 宏，处理条件编译，删除注释。
 *    - 本质：展开后的纯文本 C 语言代码。
 *    - 安防视角：常用于分析宏病毒或复杂恶意代码的真实意图。
 * 
 * 3. 汇编文件 (.s)
 *    - 生成命令：gcc -S test.i -o test.s
 *    - 内容：将 C 代码一对一（或一对多）翻译成汇编指令（如 mov, push, call）。
 *    - 本质：人类可读的底层指令，直接对应 CPU 寄存器和内存地址的操作。
 *    - 安防视角：逆向工程的起点，分析外挂、病毒逻辑的必经之路。
 * 
 * 4. 目标文件 (.o / .obj)
 *    - 生成命令：gcc -c test.s -o test.o
 *    - 内容：将汇编代码翻译成的机器指令（0101 二进制），通常遵循 ELF 格式。
 *    - 本质：高度结构化的“半成品”二进制文件（还不能直接运行）。
 *    - 内部结构：
 *      > .text   (代码段)：存放真正的机器指令。
 *      > .data   (数据段)：存放已初始化的全局变量/静态变量。
 *      > .bss    (未初始化段)：存放未初始化的全局变量（不占文件体积）。
 *      > .rodata (只读段)：存放字符串常量（如 "Hello"）。
 *      > 符号表  (Symbol Table)：记录函数名、变量名。发布软件通常需剥离(strip)以防泄露信息。
 *    - 安防视角：.o 文件里的外部函数地址是空的（存在未填的“坑”）。黑客常用 strings 命令从中扫出硬编码密码。
 * 
 * 5. 可执行文件 (a.out / .exe)
 *    - 生成命令：gcc test.o -o test (也就是链接器 Linker 的工作)
 *    - 内容：将多个 .o 文件，加上 C 标准库（如 printf 的实现）、系统启动代码拼装在一起。
 *    - 核心动作：链接器把 .o 文件中未填的“坑”（如 printf 的地址），强制填上真实的绝对内存地址。
 *    - 本质：完整成品，操作系统可加载进内存，从 main 函数开始执行。
 *    - 安防视角：动态链接库劫持 (DLL Hijacking) 和 GOT 表劫持漏洞，全发生在这个阶段。
 * 
 * 
 * 三、 总结与核心差异
 * ----------------------------------------------------------------------------
 * - .c 和 .i 是纯文本；.s 是汇编文本；.o 和可执行文件是二进制。
 * - .o 和 可执行文件的区别：.o 是零件（有坑没填），可执行文件是组装好的整车（坑已填平）。
 * - 编译的本质：把人类语言 -> 汇编 -> 机器码 -> 组装拼接。
 * ============================================================================
 */

