// 程序 计算股票经纪人的佣金

// 当股票通过经纪人进行买卖时，经纪人的佣金往往根据股票交易额采用某种变化的比例进行计算。表 5-4 显示了实际支付给经纪人的费用金额。

// 表 5-4 支付股票经纪人实际费用

// 交易额范围                         佣金
// 低于 2500 美元                30 美元 + 1.7%
// 2500 ~ 6250 美元              56 美元 + 0.66%
// 6250 ~ 20000 美元             76 美元 + 0.34%
// 20000 ~ 50000 美元            100 美元 + 0.22%
// 50000 ~ 500000 美元           155 美元 + 0.11%
// 超过 500000 美元              255 美元 + 0.09%

// 最低收费是 39 美元。下面的程序要求用户输入交易额，然后显示出佣金的数额：
// Enter value of trade: 30000
// Commission: $166.00

// 该程序的重点是用级联式 if 语句来确定交易额所在的数值范围。

/*计算经纪人的佣金*/
#include <stdio.h>

int main(void)
{
    float commission, value;
// scanf函数先接受，再想办法转换(前提是字节数要对应)，无事发生，只要地址与格式转换符对应就行，printf除了%f和%lf其他的你就给我对应，不然就强行解释了
    printf("Enter value of trade: ");
    scanf("%f", &value);
    if (value < 2500.00f)
        commission = 30.00f + .017f * value;   // <-- 相当于1.7%
    else if (value < 6250.00f)         // <--  多个else if 相当于逐级排查，而跨层级对应的if-else，相当于两大板块的分割 
        commission = 56.00f + .0066f * value;
    else if (value < 20000.00f)        // <--  else if 相当于先把前面的排除(else)，再从后面的可能做判断(if)
        commission = 76.00f + .0034f * value;
    else if (value < 50000.00f)
        commission = 100.00f + .0022f * value;
    else if (value < 500000.00f)
        commission = 155.00f + .0011f * value;
    else                               // <-- 这后面就是最后条件了，直接else取反例就行了，不用条件
        commission = 255.00f + .0009f * value;

    if (commission < 39.00f)           // <-- 不是上一个else的子句，是独立的一个句子，因为上一个else已经结束了
        commission = 39.00f;    // <-- 最低收费
    printf("Commission: $%.2f\n", commission);
    return 0;
}
/* ============================================================================
 * 【C语言运行时的终极真相：图纸与地址的粗暴游戏】
 * ============================================================================
 * 1. scanf (输入加工厂)：
 *    - 流程：接受字符流 -> 按图纸解析转换 -> 顺地址强行写入。
 *    - 原则：不认变量声明，只看地址大小，大小，注意字节数对应。图纸与地址尺寸匹配，无事发生；
 *            尺寸不匹配，直接越界覆盖相邻内存（栈溢出漏洞）。
 * 
 * 2. printf (盲目解释器)：
 *    - 流程：拿到图纸 -> 去寄存器/栈按图纸尺寸抓数据 -> 强行编码输出。
 *    - 特例：%f 和 %lf 等价，因为编译器传参时把 float 强制提升为 8字节 double。
 *    - 原则：除了浮点数，其他格式符（%d, %x, %c, %s）如果你给的参数不对应，
 *            它就按图纸的尺寸强行截断或越界读取，瞎解释一通（产生垃圾值）。
 * 
 * [终极定律]：类型在编译后消失。运行时，格式符（图纸）+ 内存地址 = 一切。
 * ============================================================================
 */