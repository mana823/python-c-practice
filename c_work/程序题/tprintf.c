/* Prints int and float values in various frmats*/

#include <stdio.h>

int main(void)
{
    int i;
    float x;

    i = 40;
    x = 839.21f;

    printf("|%d|%5d|%-5d|%5.3d|\n", i, i, i, i); // <-- %d以十进制形式显示且占用最少的空间
    printf("|%10.3f|%10.3e|%-10g|\n", x, x, x);  // <-- 符号 - 是左对齐
    return 0;
}
// %e 像浮点数的"标准档案格式"——任何浮点数都能被它无损、统一地表示，所以感觉万能；但它只对浮点万能，且不智能（100 也写成 1.000000e+02）。
// 真正"智能万能"的是 %g，会按需选 %f/%e 并去零。 你的直觉对，精确说法是：%e = 浮点的通用强制表示，不是所有类型的万能转换。

// %10.2f 里的 10 是"总字符宽度"，小数点、数字、负号、补的空格全算在里面；.2 才是"小数点后几位"，只数小数部分。 
// 宽度管整体占几格，精度管小数几位，小数点算在宽度里，不算在精度里。