// * 你的笔记批改：
// 【底层暴击：多个独立 if 绝对无法利用顺序自动排除】
// 1. 物理真相：独立的 if 在汇编中就是独立的 CMP 和条件跳转。
//    执行完前面，如果没有 JMP 拦截，CPU 会顺延执行后面的判断。✅ 正确。
// 2. 解决办法：必须使用 else if（利用编译器生成的 JMP 指令跳过后续），
//    或者显式使用 && 限制上限和下限。✅ 正确。
// 3. [安全心法]：涉及区间判定，永远写成 if - else if 链。
//    依赖代码行数的先后顺序是非常脆弱的，极易引发逻辑穿透和变量覆盖漏洞。
//    ✅ 正确。本题如果写成独立 if，每档都会执行，
//    后面的赋值会覆盖前面的结果，这就是“变量覆盖”。
// ------------------------------------------------------------
// * 正确写法（本文件唯一可运行的 main，补全后三档）：

#include <stdio.h>

int main(void)
{
    float income;   // * 应纳税所得额。
    float tax;      // * 税金。

    printf("Enter taxable income: ");
    scanf("%f", &income);

    // * 用 if-else if 链按区间从低到高判断，
    // * 后面的分支隐含“前面条件都为假”，下界不用再写。
    if (income < 750)
        tax = income * 0.01f;
    else if (income < 2250)
        tax = 7.50f + (income - 750) * 0.02f;
    else if (income < 3750)
        tax = 37.50f + (income - 2250) * 0.03f;
    else if (income < 5250)
        tax = 82.50f + (income - 3750) * 0.04f;
    else if (income < 7000)
        tax = 142.50f + (income - 5250) * 0.05f;
    else
        tax = 230.00f + (income - 7000) * 0.06f;

    // * 金额保留两位小数，末尾换行。
    printf("You need pay $%.2f\n", tax);

    return 0;
}

// * 验证：
//   收入 500   → 500 * 0.01 = 5.00
//   收入 1000  → 7.50 + (1000 - 750) * 0.02 = 7.50 + 5.00 = 12.50
//   收入 3000  → 37.50 + (3000 - 2250) * 0.03 = 37.50 + 22.50 = 60.00
//   收入 4000  → 82.50 + (4000 - 3750) * 0.04 = 82.50 + 10.00 = 92.50
//   收入 6000  → 142.50 + (6000 - 5250) * 0.05 = 142.50 + 37.50 = 180.00
//   收入 8000  → 230.00 + (8000 - 7000) * 0.06 = 230.00 + 60.00 = 290.00

