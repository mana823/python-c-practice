// * 批改：
// ✅ 12 点和 0 点的特殊处理思路正确。
// ✅ 你的注释“转化属于 12 和 00 最特殊”✅ 正确：
//    12 点不减小、仍是 PM；0 点要变成 12、且是 AM。
//
// ❌ 关键错误：第一个 if 里 `hour -= 12;` 修改了 hour，
//    导致第四个 if 判断的是“被减过之后的 hour”，不是原始输入。
//
// * 以输入 21:11 为例：
//   第一个 if：21 > 12 且 21 < 24 成立，
//              hour = 21 - 12 = 9，
//              打印 "09:11 PM"。
//   第四个 if：hour > 0 && hour < 12？
//              此时 hour 已经是 9，9 > 0 && 9 < 12 成立，
//              又打印一次 "09:11 AM"。
//   最终输出两行，先 PM 后 AM，错误。
//
// * 输入 13:00 同理：
//   第一个 if 把 hour 改成 1，打印 01:00 PM；
//   第四个 if 看到 1，又打印 01:00 AM。
//
// * 输入 12:00 和 0:30 恰好正确，因为：
//   12:00 不经过第一个 if，hour 仍是 12，第四个 if 的 12 < 12 不成立；
//   0:30 经过第三个 if 后 hour 变成 12，第四个 if 的 12 < 12 也不成立。
//   所以只有 13~23 点会重复输出。
//
// * 根本原因一句话：
//   改值发生在前面，后面的分支还在用改过的 hour 判断，造成重复命中。

// ============================================================
// * 三种修正思路（任选其一）
// ============================================================

// ------------------------------------------------------------
// * 改法 A：不改值，只做判断
// ------------------------------------------------------------
// * 分支里完全不碰 hour，输出时再用表达式计算显示值。
// * 这样四个独立 if 互不干扰，顺序也无所谓。
//
// 关键：
//   13~23 点不要写 hour -= 12，
//   而是 printf 里直接传 hour - 12。
//   0 点不要写 hour = 12，
//   而是 printf 里直接传 12。

// ------------------------------------------------------------
// * 改法 B：调整逻辑顺序，改值的分支放最后
// ------------------------------------------------------------
// * 你提的思路：“可以改一下逻辑顺序，让就算改了值也可以对应。”
// ✅ 完全正确。
// * 独立 if 结构可以保留，改值也可以保留，
//   只要把“会改值”的分支放到最后，
//   改值之后不再有分支依赖 hour 的原始值，就不会重复命中。
//
// * 调整顺序：
//   1. 0 点      → 输出 12:xx AM，不改值
//   2. 1~11 点   → 输出 xx:xx AM，不改值
//   3. 12 点     → 输出 12:xx PM，不改值
//   4. 13~23 点  → hour -= 12，输出 xx:xx PM（改值放最后）
//
// * 验证：
//   0:30  → 第 1 个命中，12:30 AM；后面都不成立。✅
//   9:05  → 第 2 个命中，9:05 AM；后面都不成立。✅
//   12:00 → 第 3 个命中，12:00 PM；第 4 个的 hour > 12 不成立。✅
//   21:11 → 前三个都不成立，第 4 个命中，hour 改 9，输出 9:11 PM；
//           因为它是最后一个分支，改值后没有后续判断，不会重复。✅
//   13:00 → 第 4 个命中，改 1，输出 1:00 PM；后面没有分支。✅

// ------------------------------------------------------------
// * 改法 C：运算位置挪到 printf 里
// ------------------------------------------------------------
// * 本质和改法 A 一样：hour 保持原始值，
//   把 hour - 12 或 12 直接写进 printf 的参数。
// * 这种写法在独立 if 结构里最省心，也不依赖分支顺序。

// ============================================================
// * 推荐写法（改法 B：保留你的独立 if 结构，改值放最后）
// * 本文件唯一可运行的 main：
// ============================================================

#include <stdio.h>

int main(void)
{
    int hour, min;

    printf("Enter a 24-hour time: ");
    scanf("%d:%d", &hour, &min);

    // * 0 点：特殊处理，显示 12，AM。不改 hour。
    if (hour == 0)
        printf("Equivalent 12-hour time: %.2d:%.2d AM\n", 12, min);

    // * 1~11 点：直接输出，AM。
    if (hour > 0 && hour < 12)
        printf("Equivalent 12-hour time: %.2d:%.2d AM\n", hour, min);

    // * 12 点：不减，仍是 PM。
    if (hour == 12)
        printf("Equivalent 12-hour time: %.2d:%.2d PM\n", hour, min);

    // * 13~23 点：改值放最后，改完不再有后续分支依赖 hour。
    if (hour > 12 && hour < 24) {
        hour -= 12;
        printf("Equivalent 12-hour time: %.2d:%.2d PM\n", hour, min);
    }

    return 0;
}

// * 验证：
//   21:11 → 09:11 PM，只输出一次  ✅
//   13:00 → 01:00 PM，只输出一次  ✅
//   12:00 → 12:00 PM              ✅
//   0:30  → 12:30 AM              ✅
//   9:05  → 09:05 AM              ✅
//   23:59 → 11:59 PM              ✅

// ============================================================
// * 小结
// ============================================================
// * 12 点和 0 点最特殊：
// *   12 点不减小，仍是 PM；
// *   0 点要显示成 12，且是 AM。
// *
// * 独立 if 结构可以保留，关键有三条：
// *   1. 要么不改值，只做判断，输出时再算（改法 A / C）；
// *   2. 要么把改值的分支放最后，改完不再判断 hour（改法 B）；
// *   3. 无论哪种，都不要让“改过的 hour”被后面的分支再次命中。
// *
// * 你的思路“调整逻辑顺序让改值也能对应”✅ 正确，
// * 改法 B 就是按这个思路写的。
