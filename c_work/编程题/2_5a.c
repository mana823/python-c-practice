// 第2章 第5题：输入 x，计算多项式 3x⁵ + 2x⁴ - 5x³ - x² + 7x - 6
// 提示：C 没有指数运算符，需要自乘。
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int x, y;  // * 正确：用 int 存储 x 和结果 y。
               // ? 可选：若希望支持小数 x，可改用 float 或 double。

    printf("Please input x value: ");  // * 正确：提示输入。
    scanf("%d", &x);                   // * 正确：读取整数 x。

    // * 正确：多项式各项幂次与题目一致。
    // *   3 * x*x*x*x*x  → 3x⁵  ✅
    // *   2 * x*x*x*x    → 2x⁴  ✅
    // *  -5 * x*x*x      → -5x³ ✅
    // *   - x*x          → -x²  ✅
    // *   7 * x          → 7x   ✅
    // *   - 6            → -6   ✅
    y = 3 * x*x*x*x*x + 2 * x*x*x*x - 5 * x*x*x - x*x + 7 * x - 6;

    printf("The value is %d !", y);  // * 正确：输出结果，末尾不需要换行。
    return 0;  // * 正确：程序正常结束。
}

