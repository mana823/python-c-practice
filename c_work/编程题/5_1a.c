// * 批改：
// ❌ 错误点：最后一个 else 碍事。
//
// * 分析：
//   前三个 if 是相互独立的语句，条件互斥，最多只有一个成立，
//   所以“多个独立 if”本身没问题。
//   问题出在最后一个 if 后面跟了一个 else：
//     else 只与最近的 if（第三个 if）配对，
//     但它在 1 位数、2 位数时照样会执行，把前面已经赋好的 line 覆盖成 4。
//
// * 逐例验证原代码：
//   输入 5：
//     第一个 if 成立，line = 1；
//     第二个 if 不成立；
//     第三个 if 不成立，进入 else，line = 4；
//     输出“5 有 4 位”，错误。
//   输入 50：
//     第一个 if 不成立；
//     第二个 if 成立，line = 2；
//     第三个 if 不成立，进入 else，line = 4；
//     输出“50 有 4 位”，错误。
//   输入 374：
//     第三个 if 成立，line = 3；
//     第三个 if 成立，不会走 else，line 保持 3；
//     输出“374 有 3 位”，正确。
//   输入 1000：
//     前三个 if 都不成立，进入 else，line = 4；
//     输出“1000 有 4 位”，正确。
//
// ! 你的注释“最后这个 else 和哪个 if 对应都无所谓”不成立：
// ! else 只与最近的 if 配对，而且它会在 1、2 位数时照样触发，
// ! 覆盖前面已经算好的 line。

// ------------------------------------------------------------
// * 正确写法 1：独立 if 链，不要 else
// ------------------------------------------------------------
// * 你的观察：“多个 if 没问题，碍事的是那个 else。” ✅ 正确。
// * 只要把最后一个 else 也改成独立 if，四个条件互斥，
// * 最多只有一个成立，就不会互相覆盖。
//
// 示例：
//   if (number >= 0 && number <= 9)
//       line = 1;
//   if (number >= 10 && number <= 99)
//       line = 2;
//   if (number >= 100 && number <= 999)
//       line = 3;
//   if (number >= 1000 && number <= 9999)
//       line = 4;
//
// * 验证：
//   5    → 只有第一个 if 成立，line = 1，后面不覆盖。✅
//   50   → 只有第二个 if 成立，line = 2。✅
//   374  → 只有第三个 if 成立，line = 3。✅
//   1000 → 只有第四个 if 成立，line = 4。✅

// ------------------------------------------------------------
// * 正确写法 2：if-else if 链
// ------------------------------------------------------------
// * 一旦某个条件成立，后面的分支全部跳过，也不会覆盖。
// * 代码更短，可读性更好，是本题更推荐的写法。

// * 本文件唯一可运行的 main（采用 if-else if 链）：

#include <stdio.h>

int main(void)
{
    int number, digits;

    printf("Enter a number: ");
    scanf("%d", &number);

    // * 按范围从 1 位到 4 位依次判断。
    // * 因为用了 else if，一旦前面的条件成立，后面的分支不再执行，
    // * 所以 digits 不会被覆盖。
    if (number >= 0 && number <= 9)
        digits = 1;
    else if (number >= 10 && number <= 99)
        digits = 2;
    else if (number >= 100 && number <= 999)
        digits = 3;
    else
        digits = 4;   // * 1000~9999，题目保证最多 4 位。

    // * 输出与题目示例一致，末尾加 \n 换行。
    printf("The number %d has %d digits\n", number, digits);

    return 0;
}

// * 验证：
//   输入 5    → digits = 1，输出 1 位  ✅
//   输入 50   → digits = 2，输出 2 位  ✅
//   输入 374  → digits = 3，输出 3 位  ✅
//   输入 1000 → digits = 4，输出 4 位  ✅

