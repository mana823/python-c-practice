//    把前面赋好的 line 覆盖成 4。
// ✅ 你的理解正确：多个独立 if 本身没问题，条件互斥不会互相覆盖；
//    真正碍事的是最后那个 else。
// * 两种正确写法：
//   1. 四个独立 if，不要 else，条件互斥；
//   2. 用 if-else if 链，一旦命中就跳过后面所有分支。
// * 第二种更推荐，代码更短，可读性更好。
