// ============================================================
// 第4章 第3题：不用算术分割，显示三位数逆序
// 题目：重新编写编程题 2 中的程序，使新程序不需要利用算术分割
//       就可以显示出 3 位数的逆序。
// 提示：参考 4.1 节的 upc.c 程序。
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int a, b, c;  // * 正确：三个 int 变量分别存百位、十位、个位。

    printf("Enter a three-digit number: ");  // * 正确：提示语与题目一致。

    // * 正确：使用 %1d 逐位读取，不使用 n/10、n%10 这类算术分割。
    // * %1d 的含义：读取一个宽度为 1 的十进制整数，即每次只读一个数字字符，
    // * 这正是 upc.c 中逐位读取数字的思路。
    // * 输入 123 时：
    // *   %1d 读 '1' → a = 1；
    // *   %1d 读 '2' → b = 2；
    // *   %1d 读 '3' → c = 3。
    // * 注意：%1d 会自动跳过前导空白，所以输入 " 123" 也能正确读取。
    scanf("%1d%1d%1d", &a, &b, &c);

    // * 正确：逆序输出，先输出个位 c，再十位 b，最后百位 a。
    // * 输入 123 → 输出 321；输入 120 → 输出 021，前导 0 也能正常输出。
    printf("The reversal is: %d%d%d", c, b, a);

    return 0;  // * 正确：程序正常结束。
}

// ============================================================
// 批改总结：
// ✅ 完全正确。
// * 用 scanf("%1d%1d%1d", ...) 逐位读取，没有使用算术分割，完全符合题目要求。
// * 输出顺序 c、b、a 正确实现逆序。
// * 对 120、100 这类含 0 的三位数也能正确输出 021、001。
// ? 小补充：如果输入超过三位，第四位及之后的字符会留在输入缓冲区，
// ?        本题只要求三位，不影响正确性。
// ============================================================