// ============================================================
// 第3章 第4题：电话号码格式转换
// 题目：
//   Enter phone number [(xxx) xxx-xxxx]: (404) 817-6900
//   You entered 404.817.6900
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int a, b, c;  // * 正确：三个号码段用 int 存储。

    printf("Enter phone number [(xxx) xxx-xxxx]: ");  // * 正确：提示格式与题目一致。

    // * 正确：scanf 格式串 "(%d)%d-%d" 可以读取 "(404) 817-6900"。
    // * 原因：第一个 %d 读 404 后，格式串匹配 ')'；
    // *       接下来的 %d 会自动跳过 ')' 后面的空格，读取 817；
    // *       然后格式串匹配 '-'，最后一个 %d 读取 6900。
    // * 你的注释“可以不空格，这是内部运作逻辑，外部只是表象” ✅ 正确：
    // *   格式串里不需要额外写空格，%d 本身会跳过前导空白。
    scanf("(%d)%d-%d", &a, &b, &c);

    // * 正确：按 xxx.xxx.xxxx 输出。
    // ? 潜在小问题：如果号码段以 0 开头，如 (012) 034-0567，
    // ? 用 %d 读取会丢失前导零，输出变成 12.34.567。
    // ? 若要求严格保留三位/四位，应改用 %03d.%03d.%04d。
    // ? 但题目示例没有前导零，按原题用 %d 通常可接受。
    printf("You entered %d.%d.%d", a, b, c);

    return 0;  // * 正确：程序正常结束。
}

// ============================================================
// 批改总结：
// ✅ 完全正确。scanf 格式串能正确处理 ')' 后的空格，输出格式也符合题目。
// ? 可选改进：若想保留号码段的前导零，输出改用 %03d.%03d.%04d。
// ============================================================