// ============================================================
// 第4章 第2题：扩展上题，处理 3 位数并逆序输出
// 题目：
//   Enter a three-digit number: 123
//   The reversal is: 321
// 提示：n % 10 是个位；n / 10 % 10 是十位；n / 100 是百位。
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int n;  // * 正确：用 int 存储输入的三位数。

    printf("Enter a three-digit number: ");  // * 正确：提示语与题目要求一致。
    scanf("%d", &n);                         // * 正确：读取整数。

    // * 正确：逆序输出三位数。
    // *   n % 10        → 个位
    // *   n / 10 % 10   → 十位
    // *   n / 100       → 百位
    // *
    // * 关键点：
    // *   / 和 % 优先级相同，且左结合，
    // *   所以 n / 10 % 10 等价于 (n / 10) % 10，结果就是十位数字。
    // *   为了可读性，也可以显式写成 (n / 10) % 10，但原写法完全正确。
    // *
    // * 连续使用 %d%d%d 输出，即使某一位是 0 也会正常输出 0，
    // * 例如 120 → 021，100 → 001，符合“三位数逆序”的格式。
    printf("The reversal is: %d%d%d", n % 10, n / 10 % 10, n / 100);

    return 0;  // * 正确：程序正常结束。
}

// ============================================================
// 批改总结：
// ✅ 完全正确。
// * 个位、十位、百位的提取公式都正确；
// * n / 10 % 10 的左结合理解正确；
// * 输出顺序是个位、十位、百位，正好逆序；
// * 对含 0 的三位数也能正确输出，如 120 → 021。
// ? 可选改进：把 n / 10 % 10 写成 (n / 10) % 10，可读性更好，但不是必须。
// ============================================================