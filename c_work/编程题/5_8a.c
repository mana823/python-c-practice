// * 正确思路（按“能赶上的下一班”）：
//   把每个起飞时间换算成“从午夜开始的分钟数”：
//     8:00  → 480
//     9:43  → 583
//     11:19 → 679
//     12:47 → 767
//     14:00 → 840
//     15:45 → 945
