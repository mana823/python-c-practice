// ============================================================
// 第3章 第6题：修改 addfrac.c，同时输入两个分数，中间用加号隔开
// 题目：
//   Enter two fractions separated by a plus sign: 5/6+3/4
//   The sum is 38/24
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int num1, denom1, num2, denom2, result_num, result_denom;
    // * 正确：分子、分母、结果分子、结果分母都用 int。
    // * 你的注释“由于我们用的是通分，用整数完全够用” ✅ 正确。

    printf("Enter two fractions separated by a plus sign: ");
    // * 正确：提示语与题目示例完全一致。

    // * 正确：格式串 "%d/%d+%d/%d" 能精确读取 "5/6+3/4"。
    // * 过程：
    // *   %d 读 5，格式串 '/' 匹配输入 '/'；
    // *   %d 读 6，格式串 '+' 匹配输入 '+'；
    // *   %d 读 3，格式串 '/' 匹配输入 '/'；
    // *   %d 读 4。
    // * 你的注释“直接在输入时就把 / 给写了，运算在内部，输入在外部显示” ✅ 正确：
    // *   格式串中的 '/' 和 '+' 是字面匹配字符，只用于匹配输入，不读入变量；
    // *   真正读入变量的是四个 %d 对应的数字。
    scanf("%d/%d+%d/%d", &num1, &denom1, &num2, &denom2);

    // * 正确：通分公式。
    // *   num1/denom1 + num2/denom2
    // * = (num1*denom2 + num2*denom1) / (denom1*denom2)
    result_num = num1 * denom2 + num2 * denom1;  // * 通分后的分子
    result_denom = denom1 * denom2;              // * 通分后的分母

    // * 正确：输出结果。
    // * 你的注释“注意，结果并没有化为最简分数” ✅ 正确。
    // * 题目示例 38/24 就是未约分的结果，因此这样输出完全符合题目要求。
    printf("The sum is %d/%d\n", result_num, result_denom);

    return 0;  // * 正确：程序正常结束。
}

// ============================================================
// 批改总结：
// ✅ 完全正确。输入格式、通分公式、输出格式全部符合题目要求。
// * 以 5/6+3/4 为例：
// *   result_num   = 5*4 + 3*6 = 20 + 18 = 38
// *   result_denom = 6*4 = 24
// *   输出 38/24，与题目示例一致。
// ============================================================