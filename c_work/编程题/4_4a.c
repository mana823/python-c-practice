// ============================================================
// 第4章 第4题：整数转八进制，输出 5 位（含前导 0）
// 题目：
//   Enter a number between 0 and 32767: 1953
//   In octal, your number is: 03641
// 要求：输出固定 5 位，即使不需要这么多位也要补前导 0。
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int n;  // * 正确：用 int 存储 0~32767 的整数。

    printf("Enter a number between 0 and 32767: ");  // * 正确：提示语与题目一致。
    scanf("%d", &n);                                 // * 正确：读取整数。

    // * 正确：输出前缀与题目示例完全一致。
    // *   "In octal, your number is: " 中 octal 后面有逗号，✅
    // *
    // * 五位八进制数字的计算完全正确：
    // *   第 1 位（最高位）：n / 8 / 8 / 8 / 8 % 8
    // *   第 2 位：        n / 8 / 8 / 8 % 8
    // *   第 3 位：        n / 8 / 8 % 8
    // *   第 4 位：        n / 8 % 8
    // *   第 5 位（最低位）：n % 8
    // *
    // * 由于 / 和 % 优先级相同且左结合，这些表达式会按从左到右依次计算，
    // * 结果正好对应八进制的各位，不需要额外加括号也正确。
    // *
    // * 以 n = 1953 验证：
    // *   第 1 位：1953/8/8/8/8 % 8 = 0
    // *   第 2 位：1953/8/8/8 % 8   = 3
    // *   第 3 位：1953/8/8 % 8     = 6
    // *   第 4 位：1953/8 % 8       = 4
    // *   第 5 位：1953 % 8         = 1
    // *   输出：In octal, your number is: 03641  ✅
    printf("In octal, your number is: %d%d%d%d%d",
           n / 8 / 8 / 8 / 8 % 8,
           n / 8 / 8 / 8 % 8,
           n / 8 / 8 % 8,
           n / 8 % 8,
           n % 8);

    return 0;  // * 正确：程序正常结束。
}

