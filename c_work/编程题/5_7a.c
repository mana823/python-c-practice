// ============================================================
// * 写法 2：题目提示的标准解法（恰好 4 条 if 语句）
// * 本文件唯一可运行的 main
// ============================================================
// * 思路和写法 1 完全一样，只是把 ?: 换成 if-else。
// * 每条 if-else 算一条 if 语句，正好 4 条：
//   第 1 条：比较 a、b，得到 max1、min1；
//   第 2 条：比较 c、d，得到 max2、min2；
//   第 3 条：比较 max1、max2，得到 max；
//   第 4 条：比较 min1、min2，得到 min。
//
// * 注意：如果用“先假设 max = a，再逐个 if 比较 b、c、d”的写法，
//   找最大值要 3 条 if，找最小值又要 3 条 if，一共 6 条，
//   不是题目说的“4 条足够”。
// * 题目的 4 条 if，正是“两两比较，再比较两组结果”这个思路。

#include <stdio.h>

int main(void)
{
    int a, b, c, d;
    int max1, min1, max2, min2, max, min;

    printf("Enter four integers: ");
    scanf("%d%d%d%d", &a, &b, &c, &d);

    // * 第 1 条 if：比较 a 和 b，大的给 max1，小的给 min1。
    if (a > b) {
        max1 = a;
        min1 = b;
    } else {
        max1 = b;
        min1 = a;
    }

    // * 第 2 条 if：比较 c 和 d，大的给 max2，小的给 min2。
    if (c > d) {
        max2 = c;
        min2 = d;
    } else {
        max2 = d;
        min2 = c;
    }

    // * 第 3 条 if：比较两组最大值，得到四个数的最大值。
    if (max1 > max2)
        max = max1;
    else
        max = max2;

    // * 第 4 条 if：比较两组最小值，得到四个数的最小值。
    if (min1 < min2)
        min = min1;
    else
        min = min2;

    printf("Largest: %d\n", max);
    printf("Smallest: %d", min);

    return 0;
}

