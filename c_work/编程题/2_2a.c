// ============================================================
// 第2章 第2题：计算球体体积
// 题目：半径为 10 m，公式 v = 4/3 π r³。
// 注意：4/3 应写为 4.0f/3.0f；C 没有指数运算符，r³ 需自乘两次。
// ============================================================

#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int r = 10;     // * 正确：半径 r = 10。
    float v;        // * 正确：体积用 float 存储。

    // ! 原始错误行：v = (4.0f / 3.0f) * r * r * r;
    // ! 错误原因：漏乘了 π！公式是 v = (4/3) * π * r³。
    // * 正确写法：需要乘以圆周率，例如 3.14159f。
    v = (4.0f / 3.0f) * 3.14159f * r * r * r;  // * 正确：计算球体体积。

    // ! 原始行：printf("The V is %f π", v);
    // ! 问题1：字符串里直接写了 π 字符，虽然部分环境支持，但通常应避免，改用文字 pi 或直接输出数值。
    // ! 问题2：末尾没有换行符 \n，输出会紧贴命令提示符。
    printf("The V is %f\n", v);  // * 修正：去掉 π 字符，加上换行，输出体积数值。

    return 0;  // * 正确：程序正常结束。
}

// ============================================================
// 关于你的回答：“如果写成 4/3，C 程序会省略小数部分”
// ✅ 基本正确。
// * 更准确地说：4 和 3 都是 int，所以 4/3 执行整数除法，结果被截断为 1，
//   而不是 1.333...，导致体积计算严重偏小。
// * 应写成 4.0f / 3.0f（或 4.0 / 3.0）进行浮点除法。
// ============================================================

// ============================================================
// 批改总结：
// ❌ 主要错误：体积计算漏乘 π。
// ⚠️ 次要问题：printf 中直接写 π 字符、缺少换行。
// ✅ 你对整数除法 4/3 的理解正确。
// * 修正后的程序可正确计算球体体积。
// ============================================================