// 题目要求输出：
//        *
//       *
//      *
// *   *
//  * *
//   *
// ============================================================

#include "stdio.h"  // ! 建议改为 #include <stdio.h>，标准库头文件推荐用尖括号。
                    // ? 用引号也能编译，但会先在当前目录找，再找系统目录，不是最佳实践。

int main(void)
{
    printf("%8s\n", "*");    // * 正确。%8s 右对齐，输出 7 个空格 + *，对应第一行。
    printf("%7s\n", "*");    // * 正确。输出 6 个空格 + *，对应第二行。
    printf("%6s\n", "*");    // * 正确。输出 5 个空格 + *，对应第三行。
    printf("%s\n", "*   *"); // * 正确。直接输出 * 三个空格 *，对应第四行。
    printf("%2s%2s\n", "*", "*"); // * 正确。%2s 输出 " *"，两个合起来是 " * *"，对应第五行。
    printf("%3s", "*");      // * 基本正确。%3s 输出两个空格 + *，对应第六行。
                             // ? 但缺少换行符 \n，建议改为 printf("%3s\n", "*");
    return 0;                // * 正确。
}                            // ? 这里多余的空行不影响编译。

// ============================================================
// 批改总结：
// ✅ 整体正确，输出与题目要求的图形一致。
