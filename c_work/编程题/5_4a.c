// ============================================================
// * 连续区间的“上界不含”写法，为什么成立？
// ============================================================
// * 关键：if-else if 链的求值顺序是“从上到下，命中即停”。
// * 这正是编译器/执行顺序在起作用：
// *   - 只有前面的条件全部为假，才会走到后面的分支；
// *   - 所以后面的分支天然隐含了“前面所有条件都为假”这个前提。
//
// * 例如写成：
//     if (speed < 1)        ...
//     else if (speed < 4)   ...
//     else if (speed < 28)  ...
//
// * 当执行到 else if (speed < 4) 时，
// * 编译器/执行顺序已经保证 speed < 1 为假，
// * 也就是隐含了 speed >= 1。
// * 所以 speed < 4 实际覆盖的是 1 <= speed < 4，
// * 正好对应表格的 1~3.999...
//
// * 也就是说：
// *   “上界不含”写法不是条件本身表达了整个区间，
// *   而是靠 else if 的顺序，把下界交给了前面的分支去排除。
// *   下界不是没写，而是由“前面分支不成立”这个执行顺序隐含保证的。
//
// * 如果不用 else if，而是用多个独立 if：
//     if (speed < 1) ...
//     if (speed < 4) ...
// * 那么 speed = 0.5 时两个 if 都会成立，
// * 因为第二个 if 不再隐含“speed >= 1”。
// * 这时就必须显式写 speed >= 1 && speed < 4。
//
// * 结论：
// *   连续区间用“上界不含”写法，必须配合 else if 链；
// *   它的正确性依赖 else if 的求值顺序，
// *   不是条件本身独立成立。
// ============================================================

// ------------------------------------------------------------
// * 正确思路：
//   1. 输入一个风速值 speed（海里/小时）。
//   2. 用 if-else if 链按区间从低到高判断。
//   3. 每个区间输出对应描述。
//   4. 推荐用“上界不含”的连续区间写法，避免小数漏档；
//      如果坚持闭区间，就要保证区间连续无缝，或者限定输入为整数。

// * 本文件唯一可运行的 main：

#include <stdio.h>

int main(void)
{
    float speed;   // * 风速（海里/小时）。

    printf("Enter wind speed (knots): ");
    scanf("%f", &speed);

    // * 按区间从低到高判断，用 if-else if 链，保证只命中一个分支。
    // * 这里用“上界不含”的写法：
    // *   后面的分支隐含了“前面所有条件都为假”，
    // *   所以不需要再显式写 >= 下界。
    // * 浮点数和整型常量比较没问题，1、4、28 等会被自动转换成 float。
    if (speed < 1)
        printf("Calm\n");
    else if (speed < 4)          // * 执行到这里，已隐含 speed >= 1，覆盖 1 ~ 3.999...
        printf("Light air\n");
    else if (speed < 28)         // * 已隐含 speed >= 4，覆盖 4 ~ 27.999...
        printf("Breeze\n");
    else if (speed < 48)         // * 已隐含 speed >= 28，覆盖 28 ~ 47.999...
        printf("Gale\n");
    else if (speed < 64)         // * 已隐含 speed >= 48，覆盖 48 ~ 63.999...
        printf("Storm\n");
    else                         // * 已隐含 speed >= 64，覆盖 >= 64
        printf("Hurricane\n");

    return 0;
}

