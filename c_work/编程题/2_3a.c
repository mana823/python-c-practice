#include <stdio.h>  // * 正确：标准输入输出头文件。

int main(void)
{
    int r;          // * 正确：用 int 存储半径。
    float v;        // * 正确：用 float 存储体积。
                    // ? 可选：若想支持小数半径，可改用 double，scanf 用 %lf，printf 用 %f。

    printf("What r value do you want?: ");  // * 正确：提示用户输入，给 scanf 铺路。
    scanf("%d", &r);                        // * 正确：读取整数半径。
                                            // * 用户按回车后，终端自动换到下一行。

    // * 正确：4.0f / 3.0f 做浮点除法，避免整数除法截断。
    // * 正确：r * r * r 计算 r³，因为 C 没有指数运算符。
    // * 正确：乘以 3.14159f 近似 π。
    v = (4.0f / 3.0f) * 3.14159f * r * r * r;

    printf("The V is %.2f", v);  // * 正确：输出体积，保留两位小数。
                                 // * 这里不需要加 \n。题目没要求换行。
                                 // * 原因：scanf 等待输入时，用户敲回车，终端已经换行；
                                 // *       后面这条 printf 从新行开始输出，完全没问题。
                                 // *       最后不加 \n，只是程序结束后 shell 提示符会紧跟，
                                 // *       这不影响本题正确性。

    // * 你的注释：“如果写成2.f就是宽度为2，小数0位” ✅ 正确。
    // *   %.2f → 精度为 2，小数点后保留 2 位。
    // *   %2.f → 最小宽度为 2，精度为 0，即不输出小数部分。
    // ? 注意：%.2f 和 %2.f 很容易混淆，前者控制小数位数，后者控制最小宽度。

    return 0;  // * 正确：程序正常结束。
}

