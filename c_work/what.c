/* ============================================================================
 * 【极客复盘：C语言换行符（\n）的“中间商障眼法”】
 * ============================================================================
 * 
 * 1. 物理现实（未经C语言包装）：
 *    - ASCII码表里，13（\r）是回车（Carriage Return），10（\n）是回行/换行（Line Feed）。
 *    - 你按下键盘的 Enter 键，操作系统给你的底层数据是：
 *      - Windows系统：给你塞两个字节 \r\n (13, 10)
 *      - Linux/Mac系统：只给你塞一个字节 \n (10)
 * 
 * 2. C语言的障眼法（双面间谍）：
 *    - 为了让你写的代码能在所有系统里乱跑，C语言的标准库（I/O库）出手了。
 *    - 【输入时】：不管你操作系统给我的是 \r\n 还是 \n，C库统统把它们吃掉，翻译成唯一纯正的 \n (10) 交给你的程序。所以你 scanf/getchar 永远只会读到 10。
 *    - 【输出时】：你在代码里只写了一个 \n，C库会根据当前系统，自动决定往文件里写 \n 还是 \r\n。
 * 
 * 3. 为什么要这么搞？
 *    - 跨平台！程序员只写一个 \n，代码放到 Windows 下自动变成回车+换行，放到 Linux 下自动变成换行。屏蔽了操作系统的底层差异。
 * 
 * 4. [极客安防暴击：CRLF 注入]：
 *    - 既然 C 语言能帮忙翻译，那如果黑客直接绕过 C 语言的 I/O 库，
 *      用 Socket 强行写入原始的 13 和 10 (0x0D 0x0A) 会怎样？
 *    - HTTP 协议只认 \r\n 作为头部结束标志。黑客通过网络包强行塞入 %0d%0a，
 *      就能欺骗后端服务器，切断正常的 HTTP 响应头，插入恶意代码（CRLF 注入）。
 * ============================================================================
 */


